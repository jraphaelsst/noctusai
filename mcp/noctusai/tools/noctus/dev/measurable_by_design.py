"""Pure detector behind ``check_measurable_by_design`` (KB § PATTERNS/architect/measurement-by-design.md).

Owner rule 2026-11-09: everything a product does is measured, so the schema must GENERATE the data -- business
entities are rows, every row is timestamped, every lifecycle change is captured append-only. This module is the
deterministic, SQL-text-only half of the gate over a NEW migration (delta, never the historical tree):

  (a) ``missing_created_at``  -- a domain ``CREATE TABLE`` with no creation timestamp                  -> high
  (b) ``lifecycle_no_events`` -- a table with a status/etapa-like column and no companion append-only
                                 transition capture anywhere in the product's migrations              -> high
  (c) ``outcome_free_text``   -- an outcome/result-like column that is free TEXT (no CHECK/enum)       -> warning
  (d) ``mutable_no_updated``  -- a lifecycle table with no ``updated_at``                              -> warning
  (e) ``event_no_actor``      -- an event/transition table with no actor column                        -> warning

Escape (recorded to gate telemetry by the CLI): ``-- measurable: <reason, >=10 chars>`` (whole file) or
``-- measurable[<table>]: <reason>`` (one table). Pure join/lookup/cache/config/queue/lock tables are exempt by
the heuristics below (tuned against the real migration tree; numbers in the KB doc).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

# creation-timestamp column names accepted as "this row is dated" (pt-BR + en conventions found in the tree)
_TS_COLS = {
    "created_at", "criado_em", "criada_em", "registrado_em", "registrada_em", "occurred_at", "ocorreu_em",
    "recorded_at", "inserted_at", "ts", "at", "started_at", "iniciado_em", "enviado_em", "sent_at",
    "received_at", "recebido_em", "granted_at", "concedido_em", "uploaded_at", "reserved_at", "logged_at",
    "synced_at", "first_seen_at", "data_criacao", "created", "date", "day", "dia", "period", "periodo",
    "bucket_start", "captured_at", "snapshot_at", "emitted_at", "emitido_em", "event_at", "evento_em",
}
_STATUS_RE = re.compile(r"^(status|estado|etapa|fase|stage|situacao|state|.+_(status|estado|etapa|fase|situacao|stage))$")
_OUTCOME_RE = re.compile(r"^(outcome|resultado|result|desfecho|motivo_(perda|encerramento|cancelamento)|"
                         r"resolucao|conclusao|veredito|verdict|.+_(outcome|resultado|desfecho))$")
_ACTOR_RE = re.compile(r"^(actor.*|ator.*|user_id|usuario.*|criado_por|created_by|registrado_por|by_user.*|responsavel.*|"
                       r"changed_by|alterado_por|performed_by|executado_por|autor.*|operador.*|corretor_id|"
                       r"agente_id|agent_id|.+_por|.+_by)$")
_EVENT_TABLE_RE = re.compile(r"(_eventos?|_events?|_transicoes|_transitions?|_historico|_history|_historia|"
                             r"_movimentos?|_audit|_auditoria|_log|_logs|_ledger|_diffs?|_changes|_revisoes|_revisions)$")
# tables that carry no business lifecycle of their own: lookup / cache / config / infra
_EXEMPT_TABLE_RE = re.compile(
    r"(_cache|_caches|_config|_configs|_configuracao|_configuracoes|_settings|_setting|_lookup|_catalog|_catalogo|"
    r"_locks?|_rate_limits?|_counters?|_tokens?|_keys|_secrets?|_sessions?|_queue|_fila|_outbox|_inbox|_tmp|_staging|"
    r"_chunks?|_embeddings?|_vectors?|_blobs?|_templates?|_defaults|_enum|_types|_tipos|_roles|_papeis|_grants|"
    r"_links|_map|_mapa|_mappings?|_aliases|_flags|_sync|_cursor|_cursors)$|^schema_migrations$|^_|^status_pagina$")
# tables that ARE a measurement record themselves (a run/metric row is its own event, dated by started_at/ts/period):
# no companion transition table needed for their status column.
_SELF_RECORD_RE = re.compile(r"(_runs?|_audits?|_mensagens|_messages|_sincronizacao|_sincronizacoes|_execucoes|_execucao|_metrics?|_metricas?|_usage|_uso|_snapshots?|_deliveries|_attempts|_tentativas)$")
_GENERATED_RE = re.compile(r"generated by noctusai_lib|do not hand-edit", re.IGNORECASE)
_LIFECYCLE_COL_STMT = re.compile(r"\bcheck\s*\(", re.IGNORECASE)
_ESCAPE_RE = re.compile(r"--\s*measurable(?:\[(?P<t>[\w.\"-]+)\])?\s*:\s*(?P<why>[^\n]*)", re.IGNORECASE)
_CREATE_TABLE_RE = re.compile(
    r"^\s*CREATE\s+(?:UNLOGGED\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?"
    r"(?:\"?(?P<schema>[\w-]+)\"?\.)?\"?(?P<table>[\w-]+)\"?\s*\(", re.IGNORECASE)
_ADD_COL_RE = re.compile(
    r"^\s*ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?(?:ONLY\s+)?(?:\"?(?P<schema>[\w-]+)\"?\.)?\"?(?P<table>[\w-]+)\"?\s+(?P<rest>.*)$",
    re.IGNORECASE | re.DOTALL)
_ADD_COLUMN_ITEM = re.compile(r"ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?\"?(?P<col>[\w-]+)\"?\s+(?P<def>[^,]*(?:\([^)]*\)[^,]*)*)",
                              re.IGNORECASE)
_CONSTRAINT_HEADS = ("constraint", "primary", "foreign", "unique", "check", "like", "exclude")


@dataclass
class Table:
    schema: str | None
    name: str
    columns: dict[str, str] = field(default_factory=dict)  # col -> raw definition (lowercase)
    constraints: list[str] = field(default_factory=list)  # raw table-level constraint text (lowercase)
    line: int = 1
    created: bool = True  # False when only seen through ALTER ... ADD COLUMN


def _split_top_level(body: str) -> list[str]:
    parts, depth, cur = [], 0, []
    for ch in body:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    return parts


def _body_of(stmt: str) -> str:
    start = stmt.find("(")
    depth = 0
    for i in range(start, len(stmt)):
        if stmt[i] == "(":
            depth += 1
        elif stmt[i] == ")":
            depth -= 1
            if depth == 0:
                return stmt[start + 1:i]
    return stmt[start + 1:]


def parse_tables(cleaned_sql: str, statements: list[str]) -> list[Table]:
    """Tables created or column-extended by ``statements`` (comments already stripped)."""
    out: list[Table] = []
    for st in statements:
        m = _CREATE_TABLE_RE.match(st)
        if m:
            t = Table((m.group("schema") or "").lower() or None, m.group("table").lower(),
                      line=cleaned_sql[: cleaned_sql.find(st)].count("\n") + 1 if st in cleaned_sql else 1)
            for item in _split_top_level(_body_of(st)):
                low = item.lower()
                head = low.split(None, 1)[0] if low.split() else ""
                if head in _CONSTRAINT_HEADS:
                    t.constraints.append(low)
                    continue
                cm = re.match(r"\"?([\w-]+)\"?\s*(.*)", item, re.DOTALL)
                if cm:
                    t.columns[cm.group(1).lower()] = cm.group(2).lower()
            out.append(t)
            continue
        a = _ADD_COL_RE.match(st)
        if a and re.search(r"\bADD\s+COLUMN\b", a.group("rest"), re.IGNORECASE):
            t = Table((a.group("schema") or "").lower() or None, a.group("table").lower(), created=False,
                      line=cleaned_sql[: cleaned_sql.find(st)].count("\n") + 1 if st in cleaned_sql else 1)
            for cm in _ADD_COLUMN_ITEM.finditer(a.group("rest")):
                t.columns[cm.group("col").lower()] = cm.group("def").lower()
            out.append(t)
    return out


def _constrained(col: str, defn: str, t: Table, all_sql_lower: str) -> bool:
    """True when ``col`` is an enum: inline CHECK, table CHECK naming it, ADD CONSTRAINT ... CHECK naming it, or a
    non-text user type (an ``CREATE TYPE ... AS ENUM`` column)."""
    if _LIFECYCLE_COL_STMT.search(defn):
        return True
    if any(c.startswith("check") or " check" in c for c in t.constraints if re.search(rf"\b{re.escape(col)}\b", c)):
        return True
    if re.search(rf"check\s*\([^;]*\b{re.escape(col)}\b[^;]*\bin\s*\(", all_sql_lower):
        return True
    base = defn.split(None, 1)[0] if defn.split() else ""
    return bool(base) and base not in ("text", "varchar", "character", "citext", "jsonb", "json") and not base.startswith(
        ("varchar", "character"))


def _has_default_now_stamp(t: Table) -> bool:
    """Any ``*_at`` / ``*_em`` timestamp column defaulting to now(): the row is dated under a local name."""
    return any(re.search(r"(_at|_em)$", c) and "timestamp" in d and re.search(r"default\s+(now\(\)|current_timestamp)", d)
               for c, d in t.columns.items())


def is_exempt_table(t: Table) -> bool:
    """Pure join / lookup / cache / config / infra tables carry no business lifecycle to measure."""
    if _EXEMPT_TABLE_RE.search(t.name):
        return True
    for col, defn in t.columns.items():  # singleton / natural-key settings row: PK is not a surrogate `id`
        if "primary key" in defn and col != "id":
            return True
    pk_cols = [c for c in t.constraints if c.startswith("primary key") or " primary key" in c]
    ids = [c for c in t.columns if c == "id" or c.endswith("_id")]
    if pk_cols and re.search(r",", pk_cols[0]) and len(ids) >= len(t.columns) - 1:
        return True  # composite-PK join table
    if t.columns and len(t.columns) <= 3 and all(c == "id" or c.endswith("_id") for c in t.columns):
        return True
    return False


def companion_events_exist(table: str, schema: str | None, corpus_lower: str) -> bool:
    """An append-only transition/event capture for ``table`` exists in ``corpus_lower`` (the product's migrations)."""
    base = re.escape(table)
    stem = re.escape(table.rstrip("s")) if table.endswith("s") else base
    # (1) a table named <t>_eventos / _transicoes / _historico / ... (singular or plural stem)
    if re.search(rf"create\s+table\s+(?:if\s+not\s+exists\s+)?(?:[\w\"-]+\.)?\"?(?:{base}|{stem})_"
                 rf"(?:eventos?|events?|transicoes|transitions?|historico|history|historia|movimentos?|audit|auditoria|log|logs|"
                 rf"revisoes|revisions|changes)\b", corpus_lower):
        return True
    # (2) any event-ish table that REFERENCES this table
    for m in re.finditer(r"create\s+table\s+(?:if\s+not\s+exists\s+)?(?:[\w\"-]+\.)?\"?([\w-]+)\"?\s*\((.*?)\);", corpus_lower, re.S):
        if _EVENT_TABLE_RE.search(m.group(1)) and re.search(rf"references\s+(?:[\w\"-]+\.)?\"?{base}\"?\b", m.group(2)):
            return True
    # (3) an audit / transition trigger or transition-log organ attached to it
    if re.search(rf"create\s+(?:or\s+replace\s+)?trigger\s+[\w\"-]+[^;]*?\bon\s+(?:[\w\"-]+\.)?\"?{base}\"?[^;]*?"
                 rf"(?:audit|transition|transicao|historico|event|log_)", corpus_lower, re.S):
        return True
    if re.search(rf"create\s+(?:or\s+replace\s+)?trigger\s+[\w\"-]+[^;]*?\bon\s+(?:[\w\"-]+\.)?\"?{base}\"?\b", corpus_lower, re.S) \
            and re.search(r"insert\s+into\s+(?:[\w\"-]+\.)?\"?[\w-]*(?:_movimentos?|_eventos?|_events?|_transicoes|_historico)\b", corpus_lower):
        return True  # a trigger on the table feeds a generic movement/event ledger (pipeline_movimentos shape)
    if re.search(rf"(?:transition_log_migration|es_events|es_streams)[^;]*\b{base}\b", corpus_lower, re.S):
        return True
    # (4) a generic ledger (e.g. core.audit_logs / fin_ledger) is declared as the capture for it
    return False


def scan_sql(raw: str, rel: str, corpus_lower: str = "", seed_tables: frozenset[str] = frozenset()) -> tuple[list[dict], list[dict]]:
    """(findings, escapes) for one migration. ``corpus_lower`` = all of the product's migration text, lowercased
    (companion events may live in an earlier/later migration of the same product)."""
    from noctusai_lib.testing.migration_parser import _strip_block_comments, _strip_line_comments, _walk_statements

    findings: list[dict] = []
    escapes: list[dict] = []
    if re.search(r"(?:^|/)001_[^/]*\.sql$", rel):
        # a product's first migration is the SCAFFOLD baseline (copy of the seed template: invitations, status_pagina,
        # tool_call_audits, ...) -- the seed owns that design. Product-specific tables arrive in 002+.
        return findings, escapes
    if _GENERATED_RE.search(raw[:400]):
        # seed-organ render (finance, ...): the measurement design lives in the ORGAN's generator, reviewed once there
        # (KB doc § Organs), never re-litigated per rendered copy.
        return findings, escapes
    file_escape = ""
    table_escape: dict[str, str] = {}
    for m in _ESCAPE_RE.finditer(raw):
        why = m.group("why").strip()
        t = (m.group("t") or "").strip('"').split(".")[-1].lower()
        if len(why) < 10:
            findings.append({"file": rel, "line": raw[: m.start()].count("\n") + 1, "severity": "high",
                             "rule": "escape_reason_short",
                             "issue": f"{rel} `-- measurable:` escape needs a reason of >=10 chars (got {why!r})."})
            continue
        if t:
            table_escape[t] = why
        else:
            file_escape = why
    cleaned = _strip_block_comments(_strip_line_comments(raw))
    stmts = list(_walk_statements(cleaned))
    corpus = (corpus_lower or "") + "\n" + cleaned.lower()
    all_lower = corpus
    seen: dict[str, Table] = {}
    for t in parse_tables(cleaned, stmts):
        key = f"{t.schema or ''}.{t.name}"
        if key in seen:
            seen[key].columns.update(t.columns)
            seen[key].constraints += t.constraints
            seen[key].created = seen[key].created or t.created
        else:
            seen[key] = t
    for t in seen.values():
        qual = f"{t.schema + '.' if t.schema else ''}{t.name}"
        why = table_escape.get(t.name) or file_escape
        if why:
            escapes.append({"file": rel, "table": qual, "reason": why})
            continue
        if t.name in seed_tables:
            continue
        is_event = bool(_EVENT_TABLE_RE.search(t.name))
        if t.created and not is_exempt_table(t):
            if not (set(t.columns) & _TS_COLS) and not _has_default_now_stamp(t):
                findings.append({
                    "file": rel, "line": t.line, "severity": "high", "rule": "missing_created_at", "table": qual,
                    "issue": (f"{rel}:{t.line} new table `{qual}` has no creation timestamp (`created_at timestamptz NOT NULL "
                              "DEFAULT now()`): a row that is not dated cannot be counted per day/week/cohort. Add it "
                              "(noctus.dev.scaffold_migration with_table emits it) or, for a genuine join/lookup, "
                              "`-- measurable[<table>]: <reason>`. KB § PATTERNS/architect/measurement-by-design.md.")})
            if is_event and not any(_ACTOR_RE.match(c) for c in t.columns):
                findings.append({
                    "file": rel, "line": t.line, "severity": "warning", "rule": "event_no_actor", "table": qual,
                    "issue": (f"{rel}:{t.line} event/transition table `{qual}` records no actor (actor_id/actor_kind/"
                              "user_id/criado_por): 'who did it' is half the metric. KB § PATTERNS/architect/measurement-by-design.md.")})
        if is_exempt_table(t) or is_event or _SELF_RECORD_RE.search(t.name):
            continue
        status_cols = [c for c in t.columns if _STATUS_RE.match(c)]
        life = [c for c in status_cols if _constrained(c, t.columns[c], t, all_lower)]
        if life and not companion_events_exist(t.name, t.schema, corpus):
            findings.append({
                "file": rel, "line": t.line, "severity": "high", "rule": "lifecycle_no_events", "table": qual,
                "issue": (f"{rel}:{t.line} `{qual}` has a lifecycle column ({', '.join(life)}) but no append-only "
                          "transition capture (a `<t>_eventos/_transicoes/_historico` table, an audit trigger, or the "
                          "transition-log primitive): the row only knows its CURRENT state, so time-in-stage, "
                          "conversion and who-moved-it are unrecoverable. Add the companion events table in the same "
                          "migration (noctus.dev.scaffold_migration with_eventos) or `-- measurable[<table>]: <reason>`. "
                          "KB § PATTERNS/architect/measurement-by-design.md.")})
        if life and t.created and "updated_at" not in t.columns and "atualizado_em" not in t.columns:
            findings.append({
                "file": rel, "line": t.line, "severity": "warning", "rule": "mutable_no_updated", "table": qual,
                "issue": (f"{rel}:{t.line} `{qual}` has a lifecycle column but no `updated_at`. "
                          "KB § PATTERNS/architect/measurement-by-design.md.")})
        for c, d in t.columns.items():
            if _OUTCOME_RE.match(c) and not _constrained(c, d, t, all_lower):
                findings.append({
                    "file": rel, "line": t.line, "severity": "warning", "rule": "outcome_free_text", "table": qual,
                    "issue": (f"{rel}:{t.line} `{qual}.{c}` looks like an outcome but is free text: outcomes must be a "
                              "CHECK-enum (or enum type) so they aggregate; keep the explanation in a separate `*_obs` "
                              "text column. KB § PATTERNS/architect/measurement-by-design.md.")})
    return findings, escapes


_SEED_TABLES: dict[str, frozenset[str]] = {}


def seed_owned_tables(root: Path) -> frozenset[str]:
    """Table names the seed's own baseline migrations create (status_pagina, invitations, ...). Derived from
    ``products/seed/backend/migrations`` -- never a hand list -- so a freshly scaffolded product's 001 migration
    (a copy of the seed baseline) does not trip the gate: the seed organ owns that measurement design."""
    key = str(root)
    if key not in _SEED_TABLES:
        names: set[str] = set()
        try:
            for f in (root / "products" / "seed" / "backend" / "migrations").glob("*.sql"):
                for m in _CREATE_TABLE_RE.finditer(f.read_text(encoding="utf-8", errors="replace")):
                    names.add(m.group("table").lower())
        except OSError:
            pass
        _SEED_TABLES[key] = frozenset(names)
    return _SEED_TABLES[key]


def product_corpus(root: Path, rel: str) -> str:
    """Lowercased text of every migration of the product that owns ``rel`` (companion events may live elsewhere)."""
    parts = Path(rel).parts
    if len(parts) < 4 or parts[0] != "products":
        return ""
    mdir = root / "products" / parts[1] / "backend" / "migrations"
    chunks: list[str] = []
    try:
        for f in sorted(mdir.glob("*.sql")):
            if f.as_posix().endswith(rel):
                continue
            chunks.append(f.read_text(encoding="utf-8", errors="replace").lower())
    except OSError:
        return ""
    return "\n".join(chunks)
