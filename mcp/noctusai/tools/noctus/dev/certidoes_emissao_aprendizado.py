"""``noctus.dev.certidoes_emissao_aprendizado`` — what InfoSimples really does.

social-wiring records EVERY InfoSimples certidão call in
``social_wiring.certidao_emissao_observacoes`` (migration 186) and reclassifies
failure signatures into ``certidao_emissao_aprendizados`` events (the learned
trigger behind the Receita 2ª-via fallback). This tool turns that record into
knowledge:

* ``mode='report'`` (default, READ-ONLY): per tipo — call counts, success rate,
  failure signatures with count + class (pcen / transitoria / desconhecida) +
  masked examples, cost of the fallback retries, suggested trigger changes —
  plus ``novos_aprendizados`` (classification events newer than the last
  ``sync``).
* ``mode='sync'`` (dev-side; the caller commits the result): idempotently
  regenerates (a) the ``[observado]`` entries of the sidecar
  ``certidoes/infosimples.knowledge.yaml`` (build-learn-cache mindset —
  known_facts / errors_encountered / drifts_surfaced) and (b) the
  "Comportamento observado (vs documentação oficial)" section of
  ``KNOWLEDGE-BASE/CONTEXT/INTEGRATIONS/infosimples-certidoes.md`` between its
  BEGIN/END markers. Output is derived ONLY from the data (no wall-clock), so a
  re-run on unchanged data writes nothing (``changed=False``).

The classification logic is NOT re-implemented here: this module loads the
product's own pure ``aprendizado.py`` by path, so the report can never drift
from what the product acts on.

Credentials: the same SqlExecutor seam as ``noctus.dev.schema_drift`` (Supabase
Management API, PAT resolved DB-first); none ⇒ ``not_configured`` (never a
faked empty report). No PII is read: observations store no token/name/document
(only an HMAC key).

KB § INTEGRATIONS/infosimples-certidoes.md · KB § PATTERNS/common/build-learn-cache-mindset.md.
"""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path
from typing import Any, Optional

import yaml

from . import migrate_product as _mp

_APRENDIZADO_REL = "products/social-wiring/backend/app/modules/certidoes/aprendizado.py"
SIDECAR_REL = "products/social-wiring/backend/app/modules/certidoes/infosimples.knowledge.yaml"
KB_REL = "KNOWLEDGE-BASE/CONTEXT/INTEGRATIONS/infosimples-certidoes.md"
BEGIN = "<!-- BEGIN observed-behaviour (generated by noctus.dev.certidoes_emissao_aprendizado) -->"
END = "<!-- END observed-behaviour -->"
PREFIXO = "[observado] "
LIMITE_LINHAS = 20000

_OBS_SQL = (
    "SELECT id, org_id, tipo, sucesso, assinatura, preferencia_emissao, fallback_de, "
    "data_tipo, documento_hash, created_at, tentativa, code, code_message, errors, "
    "price_brl, billable, validade FROM social_wiring.certidao_emissao_observacoes "
    f"ORDER BY created_at LIMIT {LIMITE_LINHAS};"
)
_EVT_SQL = (
    "SELECT org_id, tipo, assinatura, classe, classe_anterior, evidencia, "
    "primeira_obs_em, ultima_obs_em, decidido_em "
    "FROM social_wiring.certidao_emissao_aprendizados ORDER BY decidido_em;"
)


def _carregar_aprendizado(root: Path):
    """The product's pure module, loaded by path (stdlib-only by contract)."""
    path = root / _APRENDIZADO_REL
    spec = importlib.util.spec_from_file_location("_sw_certidoes_aprendizado", path)
    if spec is None or spec.loader is None:  # pragma: no cover
        raise ImportError(f"cannot load {path}")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _ts(valor: Any) -> str:
    return str(valor or "")


def _sidecar(root: Path) -> dict:
    p = root / SIDECAR_REL
    if not p.exists():
        return {}
    return yaml.safe_load(p.read_text(encoding="utf-8")) or {}


def _novos(eventos: list[dict], desde: str) -> list[dict]:
    return [
        {k: e.get(k) for k in ("tipo", "assinatura", "classe", "classe_anterior", "evidencia", "decidido_em")}
        for e in eventos if _ts(e.get("decidido_em")) > desde
    ]


def _ultimos(eventos: list[dict]) -> list[dict]:
    """Latest event per (org, tipo, assinatura) — the class in force."""
    out: dict[tuple, dict] = {}
    for e in sorted(eventos, key=lambda e: _ts(e.get("decidido_em"))):
        out[(e.get("org_id"), e.get("tipo"), e.get("assinatura"))] = e
    return list(out.values())


