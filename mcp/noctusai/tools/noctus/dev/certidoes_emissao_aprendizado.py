def certidoes_emissao_aprendizado(
    mode: str = "report",
    *,
    executor: "_mp.SqlExecutor | None" = None,
    repo_root: Optional[Path] = None,
    project_ref: str = "nyplttplcoyiiqjrvtiw",
    worktree_path: Optional[str] = None,
) -> dict[str, Any]:
    """See module docstring. Never raises — every failure is a typed ``status``."""

    def _res(status: str, **kw: Any) -> dict[str, Any]:
        base: dict[str, Any] = {
            "ok": status in ("ok", "synced", "unchanged"), "status": status, "mode": mode,
            "observacoes": 0, "relatorio": None, "novos_aprendizados": [],
            "aprendizados_ate": None, "wrote": [], "changed": False, "error": None,
        }
        base.update(kw)
        return base

    if mode not in ("report", "sync"):
        return _res("error", error=f"unknown mode {mode!r} (report | sync)")
    try:
        if repo_root is None:
            from workspace import resolve_caller_root
            repo_root = resolve_caller_root(worktree_path)
        ap = _carregar_aprendizado(repo_root)
    except Exception as exc:  # noqa: BLE001 — typed status, never raises
        return _res("error", error=f"cannot load aprendizado module: {exc}")

    if executor is None:
        executor = _mp.make_sql_executor(project_ref=project_ref)
    if executor is None:
        return _res(
            "not_configured",
            error="NOC-REMEDIATE[credentials]: no supabase_access_token resolved — cannot read "
                  "the observations. Same resolution path as noctus.dev.migrate_product.",
        )
    obs_r = executor.execute(_OBS_SQL)
    if not obs_r.get("ok"):
        return _res("error", error="could not read certidao_emissao_observacoes: " + str(obs_r.get("error")))
    evt_r = executor.execute(_EVT_SQL)
    if not evt_r.get("ok"):
        return _res("error", error="could not read certidao_emissao_aprendizados: " + str(evt_r.get("error")))
    observacoes = obs_r.get("rows") or []
    eventos = evt_r.get("rows") or []
    for o in observacoes:  # PostgREST/Mgmt API hands JSONB back parsed, but be safe
        if isinstance(o.get("errors"), str):
            try:
                o["errors"] = json.loads(o["errors"])
            except ValueError:
                o["errors"] = []

    relatorio = ap.relatorio(observacoes)
    vigentes = _ultimos(eventos)
    ate = max((_ts(e.get("decidido_em")) for e in eventos), default="")
    sidecar = _sidecar(repo_root)
    desde = _ts(sidecar.get("aprendizados_ate"))
    novos = _novos(eventos, desde)

    if mode == "report":
        return _res("ok", observacoes=len(observacoes), relatorio=relatorio,
                    novos_aprendizados=novos, aprendizados_ate=ate or None)

    # ---- sync (idempotent, deterministic) ----
    try:
        gerado = _entradas_sidecar(relatorio, vigentes)
        novo_sidecar = _mesclar_sidecar(sidecar, gerado, ate)
        sidecar_path = repo_root / SIDECAR_REL
        sidecar_txt = yaml.safe_dump(novo_sidecar, allow_unicode=True, sort_keys=False, width=100)
        kb_path = repo_root / KB_REL
        kb_atual = kb_path.read_text(encoding="utf-8") if kb_path.exists() else ""
        if not kb_atual:
            return _res("error", error=f"{KB_REL} does not exist — it carries the generated section markers",
                        observacoes=len(observacoes))
        kb_novo = _substituir_regiao(kb_atual, _markdown(relatorio, vigentes))
        wrote: list[str] = []
        if not sidecar_path.exists() or sidecar_path.read_text(encoding="utf-8") != sidecar_txt:
            sidecar_path.write_text(sidecar_txt, encoding="utf-8")
            wrote.append(SIDECAR_REL)
        if kb_novo != kb_atual:
            kb_path.write_text(kb_novo, encoding="utf-8")
            wrote.append(KB_REL)
    except OSError as exc:
        return _res("error", error=f"could not write the sidecar/KB: {exc}", observacoes=len(observacoes))
    return _res(
        "synced" if wrote else "unchanged", observacoes=len(observacoes), relatorio=relatorio,
        novos_aprendizados=novos, aprendizados_ate=ate or None, wrote=wrote, changed=bool(wrote),
    )


def register(server) -> None:
    @server.tool(
        name="noctus.dev.certidoes_emissao_aprendizado",
        description=(
            "What InfoSimples REALLY does with certidão emissions (vs its docs): reads the "
            "social-wiring emission watcher (certidao_emissao_observacoes + certidao_emissao_"
            "aprendizados, migration 186) via the Supabase Management API and returns, per "
            "tipo, call counts, success rate, failure signatures (count, class pcen/"
            "transitoria/desconhecida, masked examples), the cost of 2ª-via retries, suggested "
            "trigger changes, and 'novos_aprendizados' since the last sync. mode='report' "
            "(default) is read-only; mode='sync' idempotently regenerates the [observado] "
            "entries of certidoes/infosimples.knowledge.yaml and the 'Comportamento observado' "
            "section of KB INTEGRATIONS/infosimples-certidoes.md (dev-side files — commit the "
            "result). Pass worktree_path from inside a git worktree. No PAT ⇒ not_configured. "
            "KB § INTEGRATIONS/infosimples-certidoes.md."
        ),
    )
    def _certidoes_emissao_aprendizado(
        mode: str = "report",
        project_ref: str = "nyplttplcoyiiqjrvtiw",
        worktree_path: Optional[str] = None,
    ) -> dict:
        return certidoes_emissao_aprendizado(mode, project_ref=project_ref, worktree_path=worktree_path)


