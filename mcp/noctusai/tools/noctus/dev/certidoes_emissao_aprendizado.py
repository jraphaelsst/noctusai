def _entradas_sidecar(relatorio: dict, vigentes: list[dict]) -> dict[str, list]:
    facts: list[str] = []
    errors: list[dict] = []
    drifts: list[dict] = []
    for tipo, t in sorted(relatorio["tipos"].items()):
        taxa = t["taxa_sucesso"]
        facts.append(
            f"{PREFIXO}{tipo}: {t['chamadas']} chamadas, {t['sucessos']} com sucesso"
            f" ({'—' if taxa is None else f'{taxa:.0%}'}); {t['retries_2via']} retentativas 2ª via"
            f" (R$ {t['custo_retries_brl']})."
        )
    for e in sorted(vigentes, key=lambda e: (e["tipo"], e["assinatura"])):
        ev = e.get("evidencia") or {}
        quando = _ts(e.get("decidido_em"))[:10]
        if e["classe"] == "pcen":
            drifts.append({
                "drift": f"{PREFIXO}{e['tipo']}: a documentação da InfoSimples não dá código/mensagem para a recusa de "
                         f"emissão nova (PCEN); observado: assinatura '{e['assinatura']}' seguida de 2ª via PCEN "
                         f"({ev.get('pcen', '?')} casos).",
                "surfaced_during": "emission watcher", "resolved": True,
                "resolution": f"gatilho aprendido em {quando}: pede 2ª via",
            })
        elif e["classe"] == "transitoria":
            errors.append({
                "when": quando,
                "error": f"{PREFIXO}{e['tipo']}: assinatura '{e['assinatura']}' é transitória "
                         f"({ev.get('transitoria', '?')} casos: a 2ª via também falhou ou a nova voltou a funcionar).",
                "resolution": "gatilho aprendido: não repete a chamada como 2ª via (economiza a chamada cobrada)",
                "avoidable_by": "não tratar essa falha como PCEN",
            })
    return {"known_facts": facts, "errors_encountered": errors, "drifts_surfaced": drifts}


def _markdown(relatorio: dict, vigentes: list[dict]) -> str:
    linhas = [
        "Gerado a partir de `certidao_emissao_observacoes` / `certidao_emissao_aprendizados` "
        "(`noctus.dev.certidoes_emissao_aprendizado mode=sync`). Não editar à mão.",
        "",
        f"Observações analisadas: **{relatorio['total_observacoes']}** "
        f"(limiar de confirmação: {relatorio['limiar_confirmacao']}, margem: {relatorio['margem_confirmacao']}×).",
        "",
    ]
    if not relatorio["tipos"]:
        linhas.append("_Ainda sem observações._")
    for tipo, t in sorted(relatorio["tipos"].items()):
        taxa = "—" if t["taxa_sucesso"] is None else f"{t['taxa_sucesso']:.0%}"
        linhas += [
            f"### `{tipo}`",
            "",
            f"- Chamadas: {t['chamadas']} · sucesso: {t['sucessos']} ({taxa}) · emissões PCEN: {t['emissoes_pcen']}",
            f"- Retentativas 2ª via: {t['retries_2via']} (sem sucesso: {t['retries_2via_sem_sucesso']}) · "
            f"custo: R$ {t['custo_retries_brl']} (sem sucesso: R$ {t['custo_retries_sem_sucesso_brl']})",
        ]
        if t["assinaturas_de_falha"]:
            linhas += ["", "| Assinatura da falha | Ocorrências | Classe |", "|---|---:|---|"]
            for s in t["assinaturas_de_falha"]:
                linhas.append(f"| `{s['assinatura']}` | {s['ocorrencias']} | {s['classe']} |")
        linhas.append("")
    if vigentes:
        linhas += ["### Aprendizados em vigor", ""]
        for e in sorted(vigentes, key=lambda e: (e["tipo"], e["assinatura"])):
            linhas.append(
                f"- `{e['tipo']}` · `{e['assinatura']}` → **{e['classe']}** "
                f"(desde {_ts(e.get('decidido_em'))[:10]})"
            )
        linhas.append("")
    if relatorio["sugestoes"]:
        linhas += ["### Sugestões", ""] + [f"- {s}" for s in relatorio["sugestoes"]] + [""]
    return "\n".join(linhas).rstrip() + "\n"


def _substituir_regiao(texto: str, novo: str) -> str:
    bloco = f"{BEGIN}\n{novo}{END}"
    padrao = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if padrao.search(texto):
        return padrao.sub(lambda _m: bloco, texto)
    return texto.rstrip("\n") + "\n\n" + bloco + "\n"


def _mesclar_sidecar(atual: dict, gerado: dict[str, list], ate: str) -> dict:
    novo = dict(atual)
    for campo, entradas in gerado.items():
        chave = "drift" if campo == "drifts_surfaced" else ("error" if campo == "errors_encountered" else None)
        manuais = []
        for item in atual.get(campo) or []:
            texto = item if isinstance(item, str) else str(item.get(chave, ""))
            if not texto.startswith(PREFIXO):
                manuais.append(item)
        novo[campo] = manuais + entradas
    novo["aprendizados_ate"] = ate
    return novo


