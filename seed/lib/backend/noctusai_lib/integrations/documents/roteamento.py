"""Model routing lookup: which model reads a document first, which one is the
fallback, and how precise a model measured on (doc type, field).

Data, not code: the table is `roteamento_modelos.TABELA`, GENERATED by
`roteamento_gerador.gerar` from measured evidence (see that module for the
rules: Anthropic only, Fable never routed, overrides only on a clear and
sufficiently-sampled separation). This module only reads it.

Routing applies to the seed-canonical document provider (Anthropic). Any
other vendor keeps its `providers.OCR_MODELS` / `ESCALATION_OCR_MODELS` pins —
no measurement exists for them (`NOC-REMEDIATE[escalation-model-openai-gemini]`).

A document is read ONCE per model, so the primary model is the DOC-TYPE row's;
a (doc type, field) row whose primary differs from its doc-type row is still
honoured through the trust gate — its measured precision for the doc-type
primary is what `confianca` judges, and its fallback is the model consulted.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Optional

from noctusai_lib.integrations.documents import autoridade
from noctusai_lib.integrations.documents.roteamento_gerador import (
    LIMIAR_PRECISAO,
    PROVEDOR,
)
from noctusai_lib.integrations.documents.roteamento_modelos import TABELA


@dataclass(frozen=True)
class Rota:
    primario: str
    fallback: str
    #: `padrao` (global default — no row for this type), `tipo` (the
    #: doc-type row), `medido` (a row the data moved off its default).
    origem: str
    n_leituras: int = 0
    n_documentos: int = 0


@dataclass(frozen=True)
class Medida:
    n_leituras: int
    n_documentos: int
    acuracia: Optional[float]
    precisao_residual: Optional[float]
    suficiente: bool


def _tabela(tabela: Optional[Mapping[str, Any]]) -> Mapping[str, Any]:
    return TABELA if tabela is None else tabela


def rota(
    tipo_documento: Optional[str],
    campo: Optional[str] = None,
    *,
    tabela: Optional[Mapping[str, Any]] = None,
) -> Rota:
    """The route for a doc type (and optionally one field of it)."""
    t = _tabela(tabela)
    tipo = autoridade.tipo_normalizado(tipo_documento) or ""
    if campo is not None:
        linha = t["por_campo"].get(f"{tipo}/{campo}")
        if linha is not None:
            return Rota(linha["primario"], linha["fallback"], linha["origem"],
                        linha["n_leituras"], linha["n_documentos"])
    linha = t["por_tipo"].get(tipo)
    if linha is not None:
        return Rota(linha["primario"], linha["fallback"],
                    "tipo" if linha["origem"] == "padrao" else linha["origem"],
                    linha["n_leituras"], linha["n_documentos"])
    padrao = t["padrao_global"]
    return Rota(padrao["primario"], padrao["fallback"], "padrao")


def precisao(
    modelo: str,
    tipo_documento: Optional[str],
    campo: str,
    *,
    tabela: Optional[Mapping[str, Any]] = None,
) -> Optional[Medida]:
    """The measured precision of `modelo` on (doc type, field) — `None` when
    never measured, or when the sample does not clear the minimum-sample rule
    (a thin sample is no verdict, either way)."""
    tipo = autoridade.tipo_normalizado(tipo_documento) or ""
    cel = _tabela(tabela)["precisao"].get(f"{modelo}|{tipo}|{campo}")
    if cel is None or not cel["suficiente"]:
        return None
    return Medida(cel["n_leituras"], cel["n_documentos"], cel["acuracia"],
                  cel["precisao_residual"], cel["suficiente"])


def roteia(provider: Optional[str]) -> bool:
    """Does the routing table govern this vendor?"""
    return provider is None or provider == PROVEDOR


__all__ = ["LIMIAR_PRECISAO", "Medida", "Rota", "precisao", "rota", "roteia"]
