"""`leads_table_ddl(schema)` / `leads_migration(schema)` -- the leads DDL for a product schema.

Same conventions as the other organs: `org_id UUID NOT NULL`, RLS on, own-org SELECT for
`authenticated` + the literal-named `service_role_bypass`; the backend writes through the service
role, so no authenticated write policy exists. Re-runnable (`IF NOT EXISTS`, `DROP POLICY IF EXISTS`).

`stage` / `origin` are plain TEXT on purpose -- they are product DATA (`LeadsConfig`), so changing
them never needs a migration. `position` is `numeric` (fractional ordering, see
`domain.pipeline.ordering`): an integer column would put a card on the wrong side of its neighbour.
`phone` is canonical E.164 (`primitives.phone.normalize_phone`).

Prerequisite (not created here): `public.current_org_id_for(text)`.
"""
from __future__ import annotations

from noctusai_lib.domain._organ_common import org_rls
from noctusai_lib.domain.sql_templates import set_search_path

LEADS_MIGRATION_HEADER = "-- Leads organ -- generated by noctusai_lib.domain.leads.sql"
UQ_CHAT = "uq_{table}_chat"


def leads_table_ddl(schema: str, *, table: str = "leads", org_id_expr: str | None = None) -> str:
    """The `leads` table + indexes + RLS, schema-qualified (no header / search_path prelude)."""
    if not schema or not schema.strip():
        raise ValueError("leads_table_ddl requires a non-empty schema")
    expr = org_id_expr or f"public.current_org_id_for('{schema}')"
    s, t = schema, table
    return f"""CREATE TABLE IF NOT EXISTS {s}.{t} (
    id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id                 UUID NOT NULL,
    name                   TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    phone                  TEXT,
    email                  TEXT,
    origin                 TEXT NOT NULL,
    stage                  TEXT NOT NULL,
    position               NUMERIC NOT NULL DEFAULT 0,
    stage_changed_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes                  TEXT,
    tags                   TEXT[] NOT NULL DEFAULT '{{}}',
    whatsapp_connection_id UUID,
    whatsapp_chat_id       TEXT,
    first_contact_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_message_at        TIMESTAMPTZ,
    last_message_preview   TEXT,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by             UUID
);
-- One lead per WhatsApp chat: the guard that makes `upsert_from_whatsapp` idempotent under concurrent webhooks.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_CHAT.format(table=t)}
    ON {s}.{t} (org_id, whatsapp_connection_id, whatsapp_chat_id)
    WHERE whatsapp_connection_id IS NOT NULL AND whatsapp_chat_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_{t}_board ON {s}.{t} (org_id, stage, position);
CREATE INDEX IF NOT EXISTS idx_{t}_first_contact ON {s}.{t} (org_id, first_contact_at DESC, id DESC);
{org_rls(s, t, expr, grants=True)}
"""


def leads_migration(schema: str, *, table: str = "leads", org_id_expr: str | None = None) -> str:
    """The whole leads migration body for `schema` (header + search_path + DDL)."""
    return "\n\n".join(
        [LEADS_MIGRATION_HEADER, f"{set_search_path(schema)};", leads_table_ddl(schema, table=table, org_id_expr=org_id_expr)]
    )


__all__ = ["LEADS_MIGRATION_HEADER", "UQ_CHAT", "leads_migration", "leads_table_ddl"]
