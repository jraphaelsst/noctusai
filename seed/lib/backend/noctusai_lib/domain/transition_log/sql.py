def _lit(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _arr(values) -> str:
    return "ARRAY[" + ", ".join(_lit(v) for v in values) + "]::text[]"


class _R:
    """Pre-computed SQL fragments for one config."""

    def __init__(self, cfg: TransitionLogConfig) -> None:
        self.cfg = cfg
        s = cfg.schema
        self.s = s
        self.ev = cfg.events_table
        self.qev = f"{s}.{cfg.events_table}"
        self.qst = f"{s}.{cfg.state_table}"
        self.T = cfg.state_type
        self.org = cfg.state_org_column
        self.keys = cfg.key

    def key_from(self, src: str, k) -> str:
        return f"({src}->>{_lit(k.name)})::{k.type}"

    def ev_match(self, alias: str = "e", src: str = "p_key") -> str:
        return " AND ".join(f"{alias}.{k.name} = {self.key_from(src, k)}" for k in self.keys)

    def st_match(self, alias: str = "s", src: str = "p_key") -> str:
        return " AND ".join(f"{alias}.{k.state_column} = {self.key_from(src, k)}" for k in self.keys)

    def key_missing(self, src: str = "p_key") -> str:
        parts = [f"{src} IS NULL", f"jsonb_typeof({src}) <> 'object'"]
        parts += [f"({src}->>{_lit(k.name)}) IS NULL" for k in self.keys]
        return " OR ".join(parts)

    @property
    def key_cols(self) -> str:
        return ", ".join(k.name for k in self.keys)

    @property
    def created_expr(self) -> str:
        col = self.cfg.state_created_at_column
        return f"s.{col}" if col else "NULL::timestamptz"


def _refused(code: str, extra: str = "") -> str:
    tail = f", {extra}" if extra else ""
    return f"RETURN jsonb_build_object('status', 'refused', 'code', {_lit(code)}{tail});"


def _secdef(r: _R, name: str, args: str, sig: str, returns: str, body: str, *, volatility: str = "") -> str:
    fn = f"{r.s}.{r.cfg.rpc(name)}"
    vol = f"\n{volatility}" if volatility else ""
    return f"""CREATE OR REPLACE FUNCTION {fn}({args}) RETURNS {returns}
LANGUAGE plpgsql{vol}
SECURITY DEFINER
{definer_search_path(r.s)}
AS $fn$
{body.strip()}
$fn$;
REVOKE ALL ON FUNCTION {fn}({sig}) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {fn}({sig}) TO service_role;"""


def _validate_common(r: _R) -> str:
    """Caller-input refusals shared by create / record_created / transition (the CHECKs are the backstop)."""
    return f"""    p_data := COALESCE(p_data, '{{}}'::jsonb);
    IF jsonb_typeof(p_data) <> 'object' THEN
        {_refused('invalid_data')}
    END IF;
    IF p_actor_kind IS NULL OR p_actor_kind <> ALL ({_arr(r.cfg.actor_kinds)}) THEN
        {_refused('invalid_actor_kind')}
    END IF;"""


def _table(r: _R) -> str:
    cfg = r.cfg
    key_defs = "\n".join(f"    {k.name:<16}{k.type.upper()} NOT NULL," for k in r.keys)
    creation = f"({_lit(CREATED_EVENT)}, {_lit(IMPORTED_INITIAL_EVENT)})"
    kinds = ", ".join(_lit(k) for k in cfg.all_actor_kinds)
    fk = ""
    if cfg.foreign_key:
        st_cols = ", ".join(k.state_column for k in r.keys)
        fk = f"""
DO $do$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '{r.ev}_entity_fk' AND conrelid = '{r.qev}'::regclass) THEN
        ALTER TABLE {r.qev} ADD CONSTRAINT {r.ev}_entity_fk FOREIGN KEY ({r.key_cols})
            REFERENCES {r.qst} ({st_cols}) ON DELETE NO ACTION ON UPDATE NO ACTION DEFERRABLE INITIALLY IMMEDIATE;
    END IF;
END
$do$;"""
    return f"""-- Events of `{cfg.aggregate}` (state truth: {r.qst}.{cfg.state_column}). Append-only; seq 1 is always the creation event.
CREATE TABLE IF NOT EXISTS {r.qev} (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id          UUID NOT NULL,
{key_defs}
    seq             INTEGER NOT NULL,
    from_state      {r.T.upper()},
    to_state        {r.T.upper()},
    event_type      TEXT NOT NULL,
    data            JSONB NOT NULL DEFAULT '{{}}'::jsonb,
    actor_id        UUID,
    actor_kind      TEXT NOT NULL,
    correlation_id  UUID,
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    recorded_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT {r.ev}_seq_positive CHECK (seq >= 1),
    CONSTRAINT {r.ev}_creation_first CHECK ((seq = 1) = (event_type IN {creation}) AND (event_type NOT IN {creation} OR from_state IS NULL)),
    CONSTRAINT {r.ev}_event_type_shape CHECK (event_type ~ {_lit(EVENT_TYPE_PATTERN)}),
    CONSTRAINT {r.ev}_data_object CHECK (jsonb_typeof(data) = 'object'),
    CONSTRAINT {r.ev}_actor_kind CHECK (actor_kind IN ({kinds}))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_{r.ev}_entity_seq ON {r.qev} ({r.key_cols}, seq);
CREATE INDEX IF NOT EXISTS idx_{r.ev}_org_entity_seq ON {r.qev} (org_id, {r.key_cols}, seq);
CREATE INDEX IF NOT EXISTS idx_{r.ev}_correlation ON {r.qev} (org_id, correlation_id) WHERE correlation_id IS NOT NULL;{fk}
{org_rls(r.s, r.ev, f"public.current_org_id_for('{r.s}')", authenticated_select=False)}
GRANT ALL ON {r.qev} TO service_role;
COMMENT ON TABLE {r.qev} IS 'tier:org';

-- Immutability: UPDATE always refused, DELETE only under {cfg.erase_guc} (set by {cfg.rpc('erase_subject')} alone).
{guc_carveout_guard_sql(schema=r.s, table=r.ev, guc=cfg.erase_guc, error_message=f"{r.ev} is append-only", errcode=APPEND_ONLY_SQLSTATE, allow_ops=("DELETE",))}

CREATE OR REPLACE FUNCTION {r.s}.{r.ev}_refuse_truncate() RETURNS trigger
LANGUAGE plpgsql
{definer_search_path(r.s)}
AS $fn$
BEGIN
    RAISE EXCEPTION '{r.ev} is append-only (TRUNCATE refused)' USING ERRCODE = '{APPEND_ONLY_SQLSTATE}';
END;
$fn$;
REVOKE ALL ON FUNCTION {r.s}.{r.ev}_refuse_truncate() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS {r.ev}_no_truncate ON {r.qev};
CREATE TRIGGER {r.ev}_no_truncate BEFORE TRUNCATE ON {r.qev}
    FOR EACH STATEMENT EXECUTE FUNCTION {r.s}.{r.ev}_refuse_truncate();"""


def _erasures_table(schema: str) -> str:
    q = f"{schema}.{ERASURES_TABLE}"
    return f"""-- The schema's erasure log (shared by every transition-log aggregate): who erased which subject's history, when,
-- why, how many rows. Ids and counts only -- never the erased payload. Append-only, no carve-out.
CREATE TABLE IF NOT EXISTS {q} (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id          UUID NOT NULL,
    aggregate       TEXT NOT NULL,
    subject         JSONB NOT NULL,
    events_deleted  INTEGER NOT NULL,
    reason          TEXT NOT NULL,
    actor_id        UUID,
    erased_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT {ERASURES_TABLE}_reason_present CHECK (btrim(reason) <> '')
);
CREATE INDEX IF NOT EXISTS idx_{ERASURES_TABLE}_org ON {q} (org_id, aggregate, erased_at);
{org_rls(schema, ERASURES_TABLE, f"public.current_org_id_for('{schema}')", authenticated_select=False)}
GRANT ALL ON {q} TO service_role;
COMMENT ON TABLE {q} IS 'tier:org';
CREATE OR REPLACE FUNCTION {schema}.{ERASURES_TABLE}_append_only() RETURNS trigger
LANGUAGE plpgsql
{definer_search_path(schema)}
AS $fn$
BEGIN
    RAISE EXCEPTION '{ERASURES_TABLE} is append-only (% refused)', TG_OP USING ERRCODE = '{APPEND_ONLY_SQLSTATE}';
END;
$fn$;
REVOKE ALL ON FUNCTION {schema}.{ERASURES_TABLE}_append_only() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS {ERASURES_TABLE}_no_update_delete ON {q};
CREATE TRIGGER {ERASURES_TABLE}_no_update_delete BEFORE UPDATE OR DELETE ON {q}
    FOR EACH ROW EXECUTE FUNCTION {schema}.{ERASURES_TABLE}_append_only();
DROP TRIGGER IF EXISTS {ERASURES_TABLE}_no_truncate ON {q};
CREATE TRIGGER {ERASURES_TABLE}_no_truncate BEFORE TRUNCATE ON {q}
    FOR EACH STATEMENT EXECUTE FUNCTION {schema}.{ERASURES_TABLE}_append_only();"""


_EVENT_ARGS = (
    "p_data JSONB DEFAULT '{}'::jsonb, p_actor_id UUID DEFAULT NULL, p_actor_kind TEXT DEFAULT 'user', "
    "p_correlation_id UUID DEFAULT NULL, p_event_id UUID DEFAULT NULL, p_occurred_at TIMESTAMPTZ DEFAULT NULL"
)
_EVENT_SIG = "JSONB, UUID, TEXT, UUID, UUID, TIMESTAMPTZ"


def _insert_event(r: _R, *, key_src: str, seq: str, from_: str, to: str, type_: str,
                  data: str = "p_data", actor_id: str = "p_actor_id", actor_kind: str = "p_actor_kind",
                  corr: str = "p_correlation_id", event_id: str = "COALESCE(p_event_id, gen_random_uuid())",
                  occurred: str = "COALESCE(p_occurred_at, now())", into: str = "v_ev") -> str:
    keys = ", ".join(r.key_from(key_src, k) for k in r.keys)
    returning = f" RETURNING * INTO {into}" if into else ""
    return (f"INSERT INTO {r.qev} (id, org_id, {r.key_cols}, seq, from_state, to_state, event_type, data, actor_id, "
            f"actor_kind, correlation_id, occurred_at)\n"
            f"        VALUES ({event_id}, p_org, {keys}, {seq}, {from_}, {to}, {type_}, {data}, {actor_id}, "
            f"{actor_kind}, {corr}, {occurred}){returning};")


def _replay_block(r: _R, same: str) -> str:
    """After the lock: an existing event with the client's id is a replay when it is the SAME request."""
    return f"""    IF p_event_id IS NOT NULL THEN
        SELECT * INTO v_prev FROM {r.qev} WHERE id = p_event_id;
        IF FOUND THEN
            IF v_prev.org_id = p_org AND {same} THEN
                RETURN jsonb_build_object('status', 'replayed', 'event', to_jsonb(v_prev));
            END IF;
            {_refused('idempotency_conflict')}
        END IF;
    END IF;"""


def _rpcs(r: _R) -> list[str]:
    cfg = r.cfg
    T = r.T
    synthetic = (f"jsonb_build_object('synthetic', true, 'source', %s)", _lit(SYNTHETIC_ACTOR_KIND))
    lock = (f"SELECT s.{cfg.state_column}, {r.created_expr} INTO v_cur, v_created FROM {r.qst} s\n"
            f"        WHERE {r.st_match()} AND s.{r.org} = p_org FOR UPDATE;")
    upd_at = f", {cfg.state_updated_at_column} = now()" if cfg.state_updated_at_column else ""
    key_from_ins = ", ".join(f"{_lit(k.name)}, v_ins->{_lit(k.state_column)}" for k in r.keys)
    decl = f"""DECLARE
    v_cur     {T};
    v_created TIMESTAMPTZ;
    v_seq     INTEGER;
    v_prev    {r.qev}%ROWTYPE;
    v_ev      {r.qev}%ROWTYPE;"""

    transition = _secdef(
        r, "transition",
        f"p_org UUID, p_key JSONB, p_from {T}, p_to {T}, p_event_type TEXT DEFAULT {_lit(DEFAULT_EVENT_TYPE)}, {_EVENT_ARGS}",
        f"UUID, JSONB, {T}, {T}, TEXT, {_EVENT_SIG}", "JSONB",
        f"""{decl}
BEGIN
    IF {r.key_missing()} THEN
        {_refused('invalid_key')}
    END IF;
{_validate_common(r)}
    IF p_event_type IS NULL OR p_event_type !~ {_lit(EVENT_TYPE_PATTERN)} THEN
        {_refused('invalid_event_type')}
    END IF;
    IF p_event_type IN ({_lit(CREATED_EVENT)}, {_lit(IMPORTED_INITIAL_EVENT)}) THEN
        {_refused('reserved_event_type')}
    END IF;
    {lock}
    IF NOT FOUND THEN
        {_refused('not_found')}
    END IF;
{_replay_block(r, f"{r.ev_match('v_prev')} AND v_prev.event_type = p_event_type AND v_prev.to_state IS NOT DISTINCT FROM p_to")}
    IF v_cur IS DISTINCT FROM p_from THEN
        {_refused('stale_state', "'current_state', v_cur")}
    END IF;
    SELECT COALESCE(max(e.seq), 0) INTO v_seq FROM {r.qev} e WHERE {r.ev_match()};
    IF v_seq = 0 THEN
        -- No history yet (an entity older than its log): its initial state becomes a synthetic seq 1 first.
        {_insert_event(r, key_src='p_key', seq='1', from_='NULL', to='v_cur', type_=_lit(IMPORTED_INITIAL_EVENT),
                       data=synthetic[0] % _lit('lazy_first_transition'), actor_id='NULL', actor_kind=synthetic[1],
                       corr='p_correlation_id', event_id='gen_random_uuid()', occurred='COALESCE(v_created, now())', into='')}
        v_seq := 1;
    END IF;
    UPDATE {r.qst} s SET {cfg.state_column} = p_to{upd_at} WHERE {r.st_match()} AND s.{r.org} = p_org;
    {_insert_event(r, key_src='p_key', seq='v_seq + 1', from_='v_cur', to='p_to', type_='p_event_type')}
    RETURN jsonb_build_object('status', 'ok', 'event', to_jsonb(v_ev));
END;""",
    )

    record_created = _secdef(
        r, "record_created", f"p_org UUID, p_key JSONB, {_EVENT_ARGS}", f"UUID, JSONB, {_EVENT_SIG}", "JSONB",
        f"""{decl}
BEGIN
    IF {r.key_missing()} THEN
        {_refused('invalid_key')}
    END IF;
{_validate_common(r)}
    {lock}
    IF NOT FOUND THEN
        {_refused('not_found')}
    END IF;
{_replay_block(r, f"{r.ev_match('v_prev')} AND v_prev.event_type = {_lit(CREATED_EVENT)}")}
    IF EXISTS (SELECT 1 FROM {r.qev} e WHERE {r.ev_match()}) THEN
        {_refused('history_exists')}
    END IF;
    {_insert_event(r, key_src='p_key', seq='1', from_='NULL', to='v_cur', type_=_lit(CREATED_EVENT))}
    RETURN jsonb_build_object('status', 'ok', 'event', to_jsonb(v_ev));
END;""",
    )

    create = _secdef(
        r, "create", f"p_org UUID, p_row JSONB, {_EVENT_ARGS}", f"UUID, JSONB, {_EVENT_SIG}", "JSONB",
        f"""DECLARE
    v_row  JSONB;
    v_cols TEXT;
    v_ins  JSONB;
    v_key  JSONB;
    v_prev {r.qev}%ROWTYPE;
    v_ev   {r.qev}%ROWTYPE;
BEGIN
    IF p_row IS NULL OR jsonb_typeof(p_row) <> 'object' THEN
        {_refused('invalid_row')}
    END IF;
{_validate_common(r)}
    IF p_event_id IS NOT NULL THEN
        SELECT * INTO v_prev FROM {r.qev} WHERE id = p_event_id;
        IF FOUND THEN
            IF v_prev.org_id = p_org AND v_prev.event_type = {_lit(CREATED_EVENT)} THEN
                RETURN jsonb_build_object('status', 'replayed', 'event', to_jsonb(v_prev));
            END IF;
            {_refused('idempotency_conflict')}
        END IF;
    END IF;
    v_row := p_row || jsonb_build_object({_lit(r.org)}, p_org);
    SELECT string_agg(quote_ident(k), ', ') INTO v_cols FROM jsonb_object_keys(v_row) AS k;
    BEGIN
        EXECUTE format('INSERT INTO %I.%I AS x (%s) SELECT %s FROM jsonb_populate_record(NULL::%I.%I, $1) RETURNING to_jsonb(x.*)',
                       {_lit(r.s)}, {_lit(cfg.state_table)}, v_cols, v_cols, {_lit(r.s)}, {_lit(cfg.state_table)})
            INTO v_ins USING v_row;
        v_key := jsonb_build_object({key_from_ins});
        {_insert_event(r, key_src='v_key', seq='1', from_='NULL', to=f"(v_ins->>{_lit(cfg.state_column)})::{T}", type_=_lit(CREATED_EVENT))}
    EXCEPTION
        WHEN unique_violation THEN
            IF p_event_id IS NOT NULL THEN
                SELECT * INTO v_prev FROM {r.qev} WHERE id = p_event_id;
                IF FOUND AND v_prev.org_id = p_org AND v_prev.event_type = {_lit(CREATED_EVENT)} THEN
                    RETURN jsonb_build_object('status', 'replayed', 'event', to_jsonb(v_prev));
                END IF;
            END IF;
            {_refused('duplicate', "'detail', SQLERRM")}
        WHEN undefined_column OR not_null_violation OR check_violation OR foreign_key_violation
             OR invalid_text_representation OR datatype_mismatch OR invalid_datetime_format THEN
            {_refused('invalid_row', "'detail', SQLERRM")}
    END;
    RETURN jsonb_build_object('status', 'ok', 'event', to_jsonb(v_ev));
END;""",
    )

    history = _secdef(
        r, "history", "p_org UUID, p_key JSONB", "UUID, JSONB", "JSONB",
        f"""BEGIN
    IF {r.key_missing()} THEN
        {_refused('invalid_key')}
    END IF;
    RETURN jsonb_build_object('status', 'ok', 'events', COALESCE(
        (SELECT jsonb_agg(to_jsonb(e) ORDER BY e.seq) FROM {r.qev} e WHERE e.org_id = p_org AND {r.ev_match()}),
        '[]'::jsonb));
END;""",
        volatility="STABLE",
    )

    names = _arr(cfg.key_names)
    subject_match = " AND ".join(f"(NOT (p_subject ? {_lit(k.name)}) OR e.{k.name} = {r.key_from('p_subject', k)})" for k in r.keys)
    erase = _secdef(
        r, "erase_subject", "p_org UUID, p_subject JSONB, p_reason TEXT, p_actor_id UUID DEFAULT NULL",
        "UUID, JSONB, TEXT, UUID", "JSONB",
        f"""DECLARE
    v_n INTEGER;
BEGIN
    IF p_org IS NULL OR p_subject IS NULL OR jsonb_typeof(p_subject) <> 'object' OR NOT (p_subject ?| {names})
       OR EXISTS (SELECT 1 FROM jsonb_each(p_subject) j WHERE j.key <> ALL ({names}) OR jsonb_typeof(j.value) = 'null') THEN
        {_refused('invalid_key')}
    END IF;
    IF p_reason IS NULL OR btrim(p_reason) = '' THEN
        {_refused('invalid_reason')}
    END IF;
    -- The ONE gated delete (LGPD erasure, owner decision 2026-11-07): the flag is transaction-local and is
    -- dropped again before anything else runs, error or not.
    PERFORM set_config({_lit(cfg.erase_guc)}, 'on', true);
    BEGIN
        DELETE FROM {r.qev} e WHERE e.org_id = p_org AND {subject_match};
        GET DIAGNOSTICS v_n = ROW_COUNT;
    EXCEPTION WHEN OTHERS THEN
        PERFORM set_config({_lit(cfg.erase_guc)}, 'off', true);
        RAISE;
    END;
    PERFORM set_config({_lit(cfg.erase_guc)}, 'off', true);
    INSERT INTO {r.s}.{ERASURES_TABLE} (org_id, aggregate, subject, events_deleted, reason, actor_id)
        VALUES (p_org, {_lit(cfg.aggregate)}, p_subject, v_n, p_reason, p_actor_id);
    RETURN jsonb_build_object('status', 'ok', 'deleted', v_n);
END;""",
    )

    st_keys = ", ".join(f"s.{k.state_column}" for k in r.keys)
    backfill = _secdef(
        r, "backfill_initial_state", "p_org UUID DEFAULT NULL", "UUID", "INTEGER",
        f"""DECLARE
    v_n INTEGER;
BEGIN
    INSERT INTO {r.qev} (org_id, {r.key_cols}, seq, from_state, to_state, event_type, data, actor_kind, occurred_at)
    SELECT s.{r.org}, {st_keys}, 1, NULL, s.{cfg.state_column}, {_lit(IMPORTED_INITIAL_EVENT)},
           {synthetic[0] % _lit('transition_log_backfill')}, {synthetic[1]}, COALESCE({r.created_expr}, now())
      FROM {r.qst} s
     WHERE (p_org IS NULL OR s.{r.org} = p_org)
       AND NOT EXISTS (SELECT 1 FROM {r.qev} e WHERE {" AND ".join(f"e.{k.name} = s.{k.state_column}" for k in r.keys)})
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RETURN v_n;
END;""",
    )
    return [create, record_created, transition, history, erase, backfill]


def transition_log_migration(cfg: TransitionLogConfig, *, header: bool = True) -> str:
    """The whole transition-log DDL for ONE aggregate, as one re-runnable migration body.

    Several aggregates in one file: concatenate renders with ``header=False`` after the first (each keeps its
    own config marker; the shared erasure log is created idempotently by every render).
    """
    r = _R(cfg)
    sections = [
        *([MIGRATION_HEADER] if header else []),
        f"{CONFIG_MARKER}{cfg.to_marker_json()}",
        f"{set_search_path(cfg.schema)};",
        _erasures_table(cfg.schema),
        _table(r),
        f"-- Row-locked RPCs of `{cfg.aggregate}`: lock the state row, compare-and-set, write state + event in ONE transaction.",
        *_rpcs(r),
    ]
    return "\n\n".join(sections) + "\n"


def transition_log_backfill_sql(cfg: TransitionLogConfig, org_id: str | None = None) -> str:
    """The statement a pilot migration runs once AFTER the render: one synthetic `imported_initial_state` per
    existing entity without history (idempotent: an entity with any event is skipped)."""
    arg = "NULL" if org_id is None else f"{_lit(str(org_id))}::uuid"
    return f"SELECT {cfg.schema}.{cfg.rpc('backfill_initial_state')}({arg});"


def configs_in_migration(sql_text: str) -> list[TransitionLogConfig]:
    """Every aggregate rendered into a migration (re-derived from its config markers)."""
    out: list[TransitionLogConfig] = []
    for line in sql_text.splitlines():
        if line.startswith(CONFIG_MARKER):
            try:
                out.append(TransitionLogConfig.from_marker_json(line[len(CONFIG_MARKER):]))
            except (ValueError, TypeError, json.JSONDecodeError) as exc:
                raise ValueError(f"unparseable transition-log config marker: {exc}") from exc
    return out


