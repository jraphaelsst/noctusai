"""`transition_log_migration(cfg)` -- the events table, its guard and its RPCs for ONE aggregate.

The shape (KB § PATTERNS/backend/transition-log.md): a STATE row is the truth, an append-only EVENTS row
explains how it got there, and both are written in ONE transaction by a row-locked RPC. Before this
primitive the shape was hand-built ~8 times with inconsistent immutability (some guarded by triggers, some
append-only by convention, some ON DELETE CASCADE).

What one render emits (forward-only, idempotent -- applied twice by the chain replay):

* `<agg>_events (id, org_id, <key...>, seq, from_state, to_state, event_type, data, actor_id, actor_kind,
  correlation_id, occurred_at, recorded_at)` with `UNIQUE(<key...>, seq)`, an `(org_id, <key...>, seq)`
  index, `seq = 1 <=> creation event` (every log starts at its initial state), and a DEFERRABLE
  NO ACTION foreign key to the state row -- never ON DELETE CASCADE;
* immutability: `guc_carveout_guard_sql` refuses every UPDATE and every DELETE not made under the
  aggregate's transaction-local erasure flag, plus a statement trigger refusing TRUNCATE;
* the ONE gated erasure path (owner decision 2026-11-07, LGPD): `<agg>_erase_subject` -- SECURITY
  DEFINER, sets the flag, deletes only the subject's rows, logs the erasure to the schema's
  append-only `transition_log_erasures` (ids + counts + reason; no payload);
* RPCs in the inventory convention (jsonb `{status: ok|replayed|refused, code?, event?}`):
  `<agg>_create` (insert the state row + seq-1 `created`, atomically), `<agg>_record_created`
  (seq-1 `created` for a row the product's own SQL inserted), `<agg>_transition` (lock FOR UPDATE ->
  compare-and-set `from_state` -> write the state -> append the next seq; idempotent on a client event id),
  `<agg>_history`, `<agg>_erase_subject`, `<agg>_backfill_initial_state` (one synthetic
  `imported_initial_state` per entity without history). A transition on an entity with no history writes
  that synthetic seq-1 event itself first, so no log can ever start mid-story.

Every function is SECURITY DEFINER with a pinned `search_path`, EXECUTE revoked from PUBLIC/anon/authenticated
and granted to service_role. The events + erasure tables are `tier:org`, service-role only.
"""
