"""`approvals_migration(cfg)` -- the approvals organ DDL (service-only, `tier:org`) + the one RPC that makes a record atomic.

    apr_events   APPEND-ONLY: submitted / approved / rejected for a (subject_kind, subject_id, versao), with who, when, why.

There is no state table: the current versao is the highest `submitted`, its status is whether a decision event exists for it
(one derivation, no second place to disagree). Two partial UNIQUE indexes make "a versao is submitted once" and "a versao is
decided once" structural. `apr_record` is SECURITY DEFINER, service-role-only: under a per-subject advisory lock it checks the
versao is current and undecided and writes the event -- all or nothing. Tables are reached only through the API (service role).
"""
from __future__ import annotations

from noctusai_lib.domain._organ_common import definer_search_path, org_rls
from noctusai_lib.domain.sql_templates import set_search_path

from .config import ApprovalsConfig
from .types import DECISION_EVENTS, EVENT_KINDS

APPROVALS_MIGRATION_HEADER = "-- Approvals organ -- generated by noctusai_lib.domain.approvals.sql"
APPROVALS_TABLES = ("events",)
APPEND_ONLY_TABLES = ("events",)

UQ_SUBMITTED = "uq_{p}events_submitted"
UQ_DECIDED = "uq_{p}events_decided"
CK_EVENTS_KIND = "{p}events_kind"
CK_EVENTS_VERSAO = "{p}events_versao_positive"
CK_EVENTS_MOTIVO = "{p}events_reject_motivo"
EVENTS_GUARD_FN = "{p}events_append_only"
EVENTS_GUARD_MESSAGE = "{p}events is append-only"
#: raised by the RPC, translated by the Real ledger
ERR_STALE = "apr_stale_versao"
ERR_NOT_SUBMITTED = "apr_not_submitted"
ERR_ALREADY_DECIDED = "apr_already_decided"


def _quoted(values: tuple[str, ...]) -> str:
    return ", ".join(f"'{v}'" for v in values)


def _record_rpc(cfg: ApprovalsConfig, s: str) -> str:
    events, record = f"{s}.{cfg.table('events')}", f"{s}.{cfg.table('record')}"
    return f"""-- Record one approvals event atomically.
-- `p_row`: subject_kind, subject_id, versao, event ('submitted' | 'approved' | 'rejected'), actor_id?, motivo?, note?
-- submitted: the same versao again is a no-op; a lower one is stale. approved / rejected: the versao must be the current one and undecided.
CREATE OR REPLACE FUNCTION {record}(p_org UUID, p_row JSONB) RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER
{definer_search_path(s)}
AS $fn$
DECLARE
    v_kind    TEXT := p_row->>'subject_kind';
    v_subject UUID := (p_row->>'subject_id')::uuid;
    v_versao  INTEGER := (p_row->>'versao')::integer;
    v_event   TEXT := p_row->>'event';
    v_current INTEGER;
    v_row     {events}%ROWTYPE;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended(p_org::text || ':' || v_kind || ':' || v_subject::text, 0));
    SELECT max(versao) INTO v_current FROM {events}
     WHERE org_id = p_org AND subject_kind = v_kind AND subject_id = v_subject AND event = 'submitted';

    IF v_event = 'submitted' THEN
        IF v_current IS NOT NULL AND v_versao = v_current THEN
            RETURN jsonb_build_object('changed', false, 'event', NULL, 'versao', v_current);
        END IF;
        IF v_current IS NOT NULL AND v_versao < v_current THEN
            RAISE EXCEPTION '{ERR_STALE}' USING ERRCODE = 'P0001';
        END IF;
    ELSIF v_event IN ({_quoted(DECISION_EVENTS)}) THEN
        IF v_current IS NULL THEN
            RAISE EXCEPTION '{ERR_NOT_SUBMITTED}' USING ERRCODE = 'P0002';
        END IF;
        IF v_versao <> v_current THEN
            RAISE EXCEPTION '{ERR_STALE}' USING ERRCODE = 'P0001';
        END IF;
        IF EXISTS (SELECT 1 FROM {events} WHERE org_id = p_org AND subject_kind = v_kind AND subject_id = v_subject
                      AND versao = v_versao AND event IN ({_quoted(DECISION_EVENTS)})) THEN
            RAISE EXCEPTION '{ERR_ALREADY_DECIDED}' USING ERRCODE = 'P0001';
        END IF;
    ELSE
        RAISE EXCEPTION 'apr_record: unknown event' USING ERRCODE = '22023';
    END IF;

    INSERT INTO {events} (org_id, subject_kind, subject_id, versao, event, actor_id, motivo, note)
    VALUES (p_org, v_kind, v_subject, v_versao, v_event, nullif(p_row->>'actor_id', '')::uuid,
            nullif(btrim(p_row->>'motivo'), ''), p_row->>'note')
    RETURNING * INTO v_row;
    RETURN jsonb_build_object('changed', true, 'event', v_event, 'versao', v_versao, 'row', to_jsonb(v_row));
END;
$fn$;
REVOKE EXECUTE ON FUNCTION {record}(UUID, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {record}(UUID, JSONB) TO service_role;
"""


def approvals_migration(cfg: ApprovalsConfig, schema: str | None = None) -> str:
    s = schema or cfg.schema
    if s != cfg.schema:
        raise ValueError(f"schema {s!r} != cfg.schema {cfg.schema!r}")
    p = cfg.table_prefix
    events = cfg.table("events")
    guard_fn = EVENTS_GUARD_FN.format(p=p)
    body = f"""
CREATE TABLE IF NOT EXISTS {s}.{events} (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id       UUID NOT NULL,
    subject_kind TEXT NOT NULL CHECK (subject_kind ~ '^[a-z][a-z0-9_]{{0,39}}$'),
    subject_id   UUID NOT NULL,
    versao       INTEGER NOT NULL,
    event        TEXT NOT NULL,
    actor_id     UUID,
    motivo       TEXT,
    note         TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT {CK_EVENTS_KIND.format(p=p)} CHECK (event IN ({_quoted(EVENT_KINDS)})),
    CONSTRAINT {CK_EVENTS_VERSAO.format(p=p)} CHECK (versao > 0),
    CONSTRAINT {CK_EVENTS_MOTIVO.format(p=p)} CHECK (event <> 'rejected' OR length(btrim(coalesce(motivo, ''))) > 0)
);
-- A versao is submitted once and decided once: structural, so a concurrent double decision loses instead of duplicating.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_SUBMITTED.format(p=p)} ON {s}.{events} (org_id, subject_kind, subject_id, versao) WHERE event = 'submitted';
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_DECIDED.format(p=p)} ON {s}.{events} (org_id, subject_kind, subject_id, versao) WHERE event IN ({_quoted(DECISION_EVENTS)});
CREATE INDEX IF NOT EXISTS idx_{events}_subject ON {s}.{events} (org_id, subject_kind, subject_id, created_at);
CREATE INDEX IF NOT EXISTS idx_{events}_when ON {s}.{events} (org_id, created_at DESC);
CREATE OR REPLACE FUNCTION {s}.{guard_fn}()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER {definer_search_path(s)}
AS $$ BEGIN RAISE EXCEPTION '{EVENTS_GUARD_MESSAGE.format(p=p)}' USING ERRCODE = 'insufficient_privilege'; END; $$;
REVOKE ALL ON FUNCTION {s}.{guard_fn}() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {s}.{guard_fn}() TO service_role;
DROP TRIGGER IF EXISTS {guard_fn} ON {s}.{events};
CREATE TRIGGER {guard_fn}
    BEFORE UPDATE OR DELETE ON {s}.{events}
    FOR EACH ROW EXECUTE FUNCTION {s}.{guard_fn}();
"""
    section = (
        "-- Events: APPEND-ONLY. Every submission and every decision on a (subject, versao) is a row (who, when, why).\n"
        f"{body.strip()}\nCOMMENT ON TABLE {s}.{events} IS 'tier:org';\n"
        f"{org_rls(s, events, 'public.current_org_id_for(' + repr(s) + ')', grants=True, authenticated_select=False)}\n"
    )
    return "\n".join([APPROVALS_MIGRATION_HEADER, f"{set_search_path(s)};", section, _record_rpc(cfg, s)])


