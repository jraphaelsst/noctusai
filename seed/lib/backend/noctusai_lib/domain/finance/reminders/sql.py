"""`finance_reminders_migration(cfg, schema)` -- the dunning DDL, rendered into a product's own schema.

Additive to `finance_migration` (render it AFTER finance: the log references `<prefix>entries`). Same
conventions: `org_id UUID NOT NULL` everywhere, RLS enabled with an own-org SELECT policy for `authenticated`
plus `service_role_bypass` (the backend writes through the service role), forward-only and re-runnable
(`IF NOT EXISTS` / guarded ALTER -- the chain replay applies a new file twice).

The dedup ledger's UNIQUE index `uq_<prefix>reminder_log_dedup` on `(org_id, entry_id, rule_id, cycle_date)` IS
the idempotency contract: the engine claims a slot by INSERTing the log row BEFORE it sends, so a lost unique
race (two workers, a re-run, a retried tick) is a skipped send, and any OTHER insert failure aborts that send
loudly -- the Orbity upstream inserted its dedup row without a NOT NULL column, the insert failed unseen, and
nothing was ever deduplicated.
"""
from __future__ import annotations

from noctusai_lib.domain._organ_common import org_rls
from noctusai_lib.domain.sql_templates import set_search_path

from ..config import FinanceConfig
from .types import CHANNELS, DEFAULT_TIMEZONE, MAX_OFFSET_DAYS, MIN_OFFSET_DAYS, STATUSES

#: unprefixed table names this migration creates (the generator test iterates it: each needs org_id + RLS).
REMINDER_TABLES: tuple[str, ...] = ("reminder_settings", "reminder_rules", "reminder_log")


def _in(values: tuple[str, ...]) -> str:
    return ", ".join(f"'{v}'" for v in values)


def finance_reminders_migration(cfg: FinanceConfig, schema: str) -> str:
    """The whole dunning DDL for `schema`, as one re-runnable migration body."""
    if not schema or not schema.strip():
        raise ValueError("finance_reminders_migration requires a non-empty schema")
    s, o, p = schema, cfg.org_id_expr, cfg.table_prefix
    entries = f"{p}entries"
    settings, rules, log = (f"{p}{t}" for t in REMINDER_TABLES)
    parts = [
        "-- Finance billing reminders (dunning) -- generated by noctusai_lib.domain.finance.reminders.sql (do not hand-edit)",
        f"{set_search_path(schema)};",
        f"""-- Per-receivable opt-out (the host's UI flips it; the engine never sends for an opted-out receivable).
ALTER TABLE {s}.{entries} ADD COLUMN IF NOT EXISTS reminders_opt_out BOOLEAN NOT NULL DEFAULT false;""",
        f"""-- Per-org master switch + timezone. No row = reminders OFF (opt-in: dunning a client is never a surprise default).
CREATE TABLE IF NOT EXISTS {s}.{settings} (
    org_id     UUID PRIMARY KEY,
    enabled    BOOLEAN NOT NULL DEFAULT false,
    timezone   TEXT NOT NULL DEFAULT '{DEFAULT_TIMEZONE}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
{org_rls(s, settings, o)}""",
        f"""-- Rules: one per (org, channel, offset). offset_days is relative to the due date (-3 = three days before).
CREATE TABLE IF NOT EXISTS {s}.{rules} (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID NOT NULL,
    channel     TEXT NOT NULL CHECK (channel IN ({_in(CHANNELS)})),
    offset_days INTEGER NOT NULL CHECK (offset_days BETWEEN {MIN_OFFSET_DAYS} AND {MAX_OFFSET_DAYS}),
    template    TEXT NOT NULL CHECK (length(btrim(template)) > 0),
    enabled     BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_{rules}_offset ON {s}.{rules} (org_id, channel, offset_days);
CREATE INDEX IF NOT EXISTS idx_{rules}_org ON {s}.{rules} (org_id) WHERE enabled;
{org_rls(s, rules, o)}""",
        f"""-- The dedup ledger + send log. One row per (receivable, rule, cycle date); written BEFORE the send.
CREATE TABLE IF NOT EXISTS {s}.{log} (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID NOT NULL,
    entry_id    UUID NOT NULL REFERENCES {s}.{entries}(id) ON DELETE CASCADE,
    rule_id     UUID NOT NULL REFERENCES {s}.{rules}(id) ON DELETE RESTRICT,
    channel     TEXT NOT NULL CHECK (channel IN ({_in(CHANNELS)})),
    offset_days INTEGER NOT NULL,
    cycle_date  DATE NOT NULL,
    status      TEXT NOT NULL DEFAULT 'pending' CONSTRAINT {log}_status_check CHECK (status IN ({_in(STATUSES)})),
    attempts    INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    recipient   TEXT NOT NULL,
    message     TEXT NOT NULL,
    last_error  TEXT,
    provider_ref TEXT,
    sent_at     TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_{log}_dedup ON {s}.{log} (org_id, entry_id, rule_id, cycle_date);
CREATE INDEX IF NOT EXISTS idx_{log}_org_created ON {s}.{log} (org_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_{log}_retry ON {s}.{log} (org_id, cycle_date) WHERE status = 'failed';
{org_rls(s, log, o)}""",
    ]
    return "\n\n".join(parts) + "\n"


__all__ = ["REMINDER_TABLES", "finance_reminders_migration"]
