"""The ONE-STEP approval workflow the routines seam configures ``domain/editorial`` with.

Owner decision (2026-11-13): approval is a single step -- draft -> the owner approves or
rejects with a reason. No new approval machine: the editorial organ's fixed states are
reused with a single review stage (``revisao_editorial``) and a ``publish`` transition out of it:

    create    -> rascunho
    submit    rascunho -> revisao_editorial     (the run: machine-authored draft awaiting approval)
    publish   revisao_editorial -> publicado    (APPROVE; ``publicar``; no security stage)
    archive   any -> arquivado                  (REJECT; ``motivo`` required)
    send_back revisao_editorial -> rascunho     (``motivo`` required)

Runs are machine-authored (``SYSTEM_ACTOR``), so ``not_author`` is dropped: an owner who
pressed "trigger now" is not the author and a ``routine``-mode run publishes as the system.
The DB function generated by ``editorial_tables(schema, ROUTINES_WORKFLOW)`` enforces the same table.
"""
from __future__ import annotations

from uuid import UUID

from noctusai_lib.domain.editorial.workflow import (
    Action,
    EditorialWorkflow,
    Grant,
    State,
    Transition,
)

#: The actor of every machine step (collection, draft creation, auto-publish, scheduled runs).
SYSTEM_ACTOR = UUID("00000000-0000-4000-8000-0000000000a1")

_A, _S, _G = Action, State, Grant

ROUTINES_TRANSITIONS: tuple[Transition, ...] = (
    Transition(_A.CREATE, None, _S.RASCUNHO, _G.EDITAR, creates_version=True),
    Transition(_A.EDIT, _S.RASCUNHO, _S.RASCUNHO, _G.EDITAR, creates_version=True),
    Transition(_A.EDIT, _S.PUBLICADO, _S.RASCUNHO, _G.EDITAR, creates_version=True),
    Transition(_A.SUBMIT, _S.RASCUNHO, _S.REVISAO_EDITORIAL, _G.EDITAR),
    Transition(_A.PUBLISH, _S.REVISAO_EDITORIAL, _S.PUBLICADO, _G.PUBLICAR),
    Transition(_A.SEND_BACK, _S.REVISAO_EDITORIAL, _S.RASCUNHO, _G.PUBLICAR, needs_motivo=True),
    Transition(_A.ARCHIVE, _S.RASCUNHO, _S.ARQUIVADO, _G.PUBLICAR, needs_motivo=True),
    Transition(_A.ARCHIVE, _S.REVISAO_EDITORIAL, _S.ARQUIVADO, _G.PUBLICAR, needs_motivo=True),
    Transition(_A.ARCHIVE, _S.PUBLICADO, _S.ARQUIVADO, _G.PUBLICAR, needs_motivo=True),
)

ROUTINES_WORKFLOW = EditorialWorkflow(transitions=ROUTINES_TRANSITIONS)

#: Grants the system actor holds while running (create + submit; + publish in ``routine`` mode only).
SYSTEM_DRAFT_GRANTS: tuple[str, ...] = (Grant.EDITAR.value,)
SYSTEM_PUBLISH_GRANTS: tuple[str, ...] = (Grant.EDITAR.value, Grant.PUBLICAR.value)
#: What an org admin holds on the routines router (server-derived, never read from the request).
ADMIN_GRANTS: tuple[str, ...] = (Grant.EDITAR.value, Grant.PUBLICAR.value)

__all__ = [
    "ADMIN_GRANTS", "ROUTINES_TRANSITIONS", "ROUTINES_WORKFLOW", "SYSTEM_ACTOR",
    "SYSTEM_DRAFT_GRANTS", "SYSTEM_PUBLISH_GRANTS",
]
