"""`commerce_erp_migration(cfg, schema)` -- the ERP link DDL, as a DELTA over the base + money migrations.

Roadmap `erp-seed-2026-10.md` E5 / E6 / E7. A separate generator on purpose (the base `012` and the money delta are
APPLIED in a host and never rewritten): a host that also mounts the ERP organs renders THIS into its own migration, after
`items` and `commerce_money`.

What it adds:

* `commerce_products.item_id` -- nullable, composite FK `(org_id, item_id)` -> the items organ's `UNIQUE (org_id, id)`: the
  database refuses a product pointing at another org's item. Stock applies ONLY to products that carry it (a digital product
  needs none) -- E5/E6. A re-runnable guarded DO adds the FK (no `ADD CONSTRAINT IF NOT EXISTS`).
* `commerce_orders.channel` (`storefront` | `manual`, default `storefront`) -- E7: a staff/quote-made order is a channel value
  of the same orders table, not a second sales-order model.
* `commerce_orders.source_ref` -- the idempotency key of an order created FROM another record (an accepted quote's id):
  `UNIQUE (org_id, source_ref) WHERE source_ref IS NOT NULL`, so a retried conversion can only ever find its order.
* `payment_method` / `gateway` become nullable: a manual order has no charge yet. Both stay CHECKed when present.

Forward-only and idempotent (the chain replay applies a new file twice).
"""
from __future__ import annotations

from noctusai_lib.domain.sql_templates import set_search_path

from .config import CommerceConfig
from .types import OrderChannel
from .sql import _in

#: Unqualified names of the guards this delta emits (the probes in `guards.py` cover each).
ORDERS_CHANNEL_CHECK = "commerce_orders_channel_check"
ORDERS_SOURCE_REF_UNIQUE = "uq_commerce_orders_source_ref"
PRODUCTS_ITEM_FK = "commerce_products_item_fk"


def commerce_erp_migration(cfg: CommerceConfig, schema: str) -> str:
    """The ERP link DDL for `schema`, as one re-runnable migration body."""
    if not schema or not schema.strip():
        raise ValueError("commerce_erp_migration requires a non-empty schema")
    s = schema
    items = cfg.items_table
    sections = [
        "-- Commerce organ, ERP link -- generated by noctusai_lib.domain.commerce.erp_sql (do not hand-edit)",
        f"{set_search_path(s)};",
        f"""-- Products: the optional link to the items catalog (stock applies only when set).
ALTER TABLE {s}.commerce_products ADD COLUMN IF NOT EXISTS item_id UUID;
DO $erp_item_fk$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '{PRODUCTS_ITEM_FK}' AND conrelid = '{s}.commerce_products'::regclass) THEN
        ALTER TABLE {s}.commerce_products ADD CONSTRAINT {PRODUCTS_ITEM_FK}
            FOREIGN KEY (org_id, item_id) REFERENCES {s}.{items} (org_id, id) ON DELETE RESTRICT;
    END IF;
END
$erp_item_fk$;
CREATE INDEX IF NOT EXISTS idx_commerce_products_item ON {s}.commerce_products (org_id, item_id) WHERE item_id IS NOT NULL;""",
        f"""-- Orders: the channel (E7) and the idempotency key of an order made from another record.
ALTER TABLE {s}.commerce_orders ADD COLUMN IF NOT EXISTS channel TEXT NOT NULL DEFAULT '{OrderChannel.STOREFRONT.value}';
ALTER TABLE {s}.commerce_orders DROP CONSTRAINT IF EXISTS {ORDERS_CHANNEL_CHECK};
ALTER TABLE {s}.commerce_orders ADD CONSTRAINT {ORDERS_CHANNEL_CHECK} CHECK (channel IN ({_in(OrderChannel)}));
ALTER TABLE {s}.commerce_orders ADD COLUMN IF NOT EXISTS source_ref TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS {ORDERS_SOURCE_REF_UNIQUE} ON {s}.commerce_orders (org_id, source_ref) WHERE source_ref IS NOT NULL;
-- A manual order exists before any charge: no tender and no gateway yet (their CHECKs still hold when set).
ALTER TABLE {s}.commerce_orders ALTER COLUMN payment_method DROP NOT NULL;
ALTER TABLE {s}.commerce_orders ALTER COLUMN gateway DROP NOT NULL;""",
    ]
    return "\n\n".join(sections) + "\n"


__all__ = ["ORDERS_CHANNEL_CHECK", "ORDERS_SOURCE_REF_UNIQUE", "PRODUCTS_ITEM_FK", "commerce_erp_migration"]
