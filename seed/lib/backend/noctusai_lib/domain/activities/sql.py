"""`activities_migration(cfg, schema)` -- the activities DDL + RPCs for a product's schema.

Conventions of the other organs (`inventory_migration`, `leads_migration`): `org_id UUID NOT NULL` on every table, RLS on
with an `authenticated` own-org SELECT policy and the literal `service_role_bypass`; the backend writes through the
service-role client only (tier `service`, `KB § PATTERNS/security/access-tiers.md`). Forward-only and idempotent
(applied twice by the chain replay).

Event-oriented (`KB § PATTERNS/architect/event-oriented-architecture.md`): every lifecycle change is ONE row-locked RPC that
updates the activity AND appends an immutable, intent-named `act_events` row in the same transaction. The kardex-style
trigger refuses UPDATE / DELETE / TRUNCATE of the events. A repeated intent that changes nothing answers `replayed` and
appends no event (a double click never double-counts).

NOC-REMEDIATE[transition-log-primitive]: `act_events` is the organ's own append-only table because the E1
`transition_log_migration` primitive is not on `dev` yet; when it lands this table is generated by it (same event names, so
the rewrite is mechanical) -- 2026-11-11.

RPC contract: each returns jsonb `{"status": "ok"|"replayed"|"refused", "code"?, "activity"?}`. A refusal rolls the call
back (a plpgsql exception block is a savepoint) and is reported as data, not raised.

Prerequisite (not created here): `public.current_org_id_for(text)` (core 070; the default `org_id_expr`).
"""
from __future__ import annotations

from noctusai_lib.domain._organ_common import definer_search_path, org_rls
from noctusai_lib.domain.sql_templates import set_search_path

from .config import ActivitiesConfig
from .types import ACTIVITY_EVENTS, ACTIVITY_KINDS, ACTIVITY_OUTCOMES, EVENT_CREATED, INTENT_EVENT

ACTIVITIES_MIGRATION_HEADER = "-- Activities organ -- generated by noctusai_lib.domain.activities.sql"

#: Every organ table (unprefixed), in dependency order.
ACTIVITIES_TABLES: tuple[str, ...] = ("types", "activities", "events")
#: Append-only history: events are never updated, deleted or truncated (a trigger refuses).
APPEND_ONLY_TABLES: tuple[str, ...] = ("events",)

#: SQLSTATE carrying a business refusal out of a nested block / an append-only violation.
REFUSAL_SQLSTATE = "AC001"
APPEND_ONLY_SQLSTATE = "AC002"

RPC_NAMES: tuple[str, ...] = ("seed_types", "create", "apply")


def _in(values: tuple[str, ...]) -> str:
    return ", ".join(f"'{v}'" for v in values)


def _refuse(code: str) -> str:
    return f"RAISE EXCEPTION USING ERRCODE = '{REFUSAL_SQLSTATE}', MESSAGE = '{code}';"


def _secdef(s: str, name: str, args: str, sig: str, declare: str, body: str) -> str:
    return f"""CREATE OR REPLACE FUNCTION {s}.{name}({args}) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
{definer_search_path(s)}
AS $fn$
{declare.strip()}
{body.strip()}
$fn$;
REVOKE ALL ON FUNCTION {s}.{name}({sig}) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {s}.{name}({sig}) TO service_role;"""


def _tables(cfg: ActivitiesConfig, s: str) -> list[str]:
    o = cfg.org_id_expr
    t = {name: cfg.table(name) for name in ACTIVITIES_TABLES}
    sections = [
        (
            "Activity types: market DATA the org edits (label / position / active). The slug is immutable.",
            "types",
            f"""
CREATE TABLE IF NOT EXISTS {s}.{t['types']} (
    org_id      UUID NOT NULL,
    slug        TEXT NOT NULL,
    label       TEXT NOT NULL,
    kind        TEXT NOT NULL,
    position    INTEGER NOT NULL DEFAULT 0,
    active      BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, slug),
    CONSTRAINT {t['types']}_slug_shape CHECK (slug ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT {t['types']}_kind_valid CHECK (kind IN ({_in(ACTIVITY_KINDS)})),
    CONSTRAINT {t['types']}_label_nonblank CHECK (btrim(label) <> '')
);
""",
        ),
        (
            "Activities: a task / call / meeting / visit linked to (entity_kind, entity_id), with due, assignee (a plain "
            "user id), done/undone. Never hard-deleted: `cancelar` is the intent. open = done_at IS NULL AND cancelled_at IS NULL.",
            "activities",
            f"""
CREATE TABLE IF NOT EXISTS {s}.{t['activities']} (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id        UUID NOT NULL,
    entity_kind   TEXT NOT NULL,
    entity_id     UUID NOT NULL,
    type_slug     TEXT NOT NULL,
    kind          TEXT NOT NULL,
    title         TEXT NOT NULL,
    notes         TEXT,
    due_at        TIMESTAMPTZ,
    assignee_id   UUID,
    org_unit_id   UUID,
    done_at       TIMESTAMPTZ,
    done_by       UUID,
    outcome       TEXT,
    cancelled_at  TIMESTAMPTZ,
    created_by    UUID,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (org_id, type_slug) REFERENCES {s}.{t['types']} (org_id, slug) ON DELETE RESTRICT,
    CONSTRAINT {t['activities']}_entity_kind_shape CHECK (entity_kind ~ '^[a-z][a-z0-9_]*$'),
    CONSTRAINT {t['activities']}_kind_valid CHECK (kind IN ({_in(ACTIVITY_KINDS)})),
    CONSTRAINT {t['activities']}_title_nonblank CHECK (btrim(title) <> ''),
    CONSTRAINT {t['activities']}_state_exclusive CHECK (NOT (done_at IS NOT NULL AND cancelled_at IS NOT NULL)),
    CONSTRAINT {t['activities']}_outcome_valid CHECK (outcome IS NULL OR outcome IN ({_in(ACTIVITY_OUTCOMES)}))
);
CREATE INDEX IF NOT EXISTS idx_{t['activities']}_entity ON {s}.{t['activities']} (org_id, entity_kind, entity_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_{t['activities']}_open_assignee ON {s}.{t['activities']} (org_id, assignee_id, due_at)
    WHERE done_at IS NULL AND cancelled_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_{t['activities']}_unit ON {s}.{t['activities']} (org_id, org_unit_id) WHERE org_unit_id IS NOT NULL;
""",
        ),
        (
            "Activity events (APPEND-ONLY): who did what to which activity, when. `data` carries ids and changed fields, never free text.",
            "events",
            f"""
CREATE TABLE IF NOT EXISTS {s}.{t['events']} (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    seq          BIGINT GENERATED ALWAYS AS IDENTITY,
    org_id       UUID NOT NULL,
    activity_id  UUID NOT NULL REFERENCES {s}.{t['activities']} (id) ON DELETE RESTRICT,
    event        TEXT NOT NULL,
    actor_id     UUID,
    occurred_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    data         JSONB NOT NULL DEFAULT '{{}}'::jsonb,
    CONSTRAINT {t['events']}_event_valid CHECK (event IN ({_in(ACTIVITY_EVENTS)}))
);
CREATE INDEX IF NOT EXISTS idx_{t['events']}_activity ON {s}.{t['events']} (org_id, activity_id, seq);

CREATE OR REPLACE FUNCTION {s}.{t['events']}_append_only() RETURNS trigger
LANGUAGE plpgsql
{definer_search_path(s)}
AS $fn$
BEGIN
    RAISE EXCEPTION '{t['events']} is append-only (% refused)', TG_OP USING ERRCODE = '{APPEND_ONLY_SQLSTATE}';
END;
$fn$;
DROP TRIGGER IF EXISTS {t['events']}_no_update_delete ON {s}.{t['events']};
CREATE TRIGGER {t['events']}_no_update_delete BEFORE UPDATE OR DELETE ON {s}.{t['events']}
    FOR EACH ROW EXECUTE FUNCTION {s}.{t['events']}_append_only();
DROP TRIGGER IF EXISTS {t['events']}_no_truncate ON {s}.{t['events']};
CREATE TRIGGER {t['events']}_no_truncate BEFORE TRUNCATE ON {s}.{t['events']}
    FOR EACH STATEMENT EXECUTE FUNCTION {s}.{t['events']}_append_only();
""",
        ),
    ]
    out: list[str] = []
    for title, name, body in sections:
        out.append(f"-- {title}\n{body.strip()}\n{org_rls(s, t[name], o, grants=True)}")
    return out


def _handler() -> str:
    return f"""EXCEPTION WHEN SQLSTATE '{REFUSAL_SQLSTATE}' THEN
    GET STACKED DIAGNOSTICS v_code = MESSAGE_TEXT;
    RETURN jsonb_build_object('status', 'refused', 'code', v_code);"""


def _rpcs(cfg: ActivitiesConfig, s: str) -> str:
    ty, ac, ev = (f"{s}.{cfg.table(n)}" for n in ACTIVITIES_TABLES)
    n = {name: cfg.rpc(name) for name in RPC_NAMES}

    seed = _secdef(
        s, n["seed_types"], "p_org UUID, p_rows JSONB", "UUID, JSONB",
        "DECLARE v_inserted INTEGER;",
        f"""
BEGIN
    INSERT INTO {ty} (org_id, slug, label, kind, position)
        SELECT p_org, r->>'slug', r->>'label', r->>'kind', COALESCE((r->>'position')::int, 0)
        FROM jsonb_array_elements(p_rows) AS r
        ON CONFLICT (org_id, slug) DO NOTHING;
    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    RETURN jsonb_build_object('status', 'ok', 'inserted', v_inserted);
END;""",
    )

    create = _secdef(
        s, n["create"], "p_org UUID, p_row JSONB", "UUID, JSONB",
        f"DECLARE v_type {ty}%ROWTYPE; v_row {ac}%ROWTYPE; v_code TEXT;",
        f"""
BEGIN
    SELECT * INTO v_type FROM {ty} WHERE org_id = p_org AND slug = p_row->>'type_slug' AND active;
    IF NOT FOUND THEN
        {_refuse('tipo_invalido')}
    END IF;
    INSERT INTO {ac} (org_id, entity_kind, entity_id, type_slug, kind, title, notes, due_at, assignee_id, org_unit_id, created_by)
        VALUES (p_org, p_row->>'entity_kind', (p_row->>'entity_id')::uuid, v_type.slug, v_type.kind, btrim(p_row->>'title'),
                NULLIF(p_row->>'notes', ''), (p_row->>'due_at')::timestamptz, (p_row->>'assignee_id')::uuid,
                (p_row->>'org_unit_id')::uuid, (p_row->>'created_by')::uuid)
        RETURNING * INTO v_row;
    INSERT INTO {ev} (org_id, activity_id, event, actor_id, data)
        VALUES (p_org, v_row.id, '{EVENT_CREATED}', v_row.created_by,
                jsonb_build_object('type_slug', v_row.type_slug, 'kind', v_row.kind, 'entity_kind', v_row.entity_kind,
                                   'assignee_id', v_row.assignee_id, 'due_at', v_row.due_at, 'org_unit_id', v_row.org_unit_id));
    RETURN jsonb_build_object('status', 'ok', 'activity', to_jsonb(v_row));
{_handler()}
END;""",
    )

    def replayed() -> str:
        return "RETURN jsonb_build_object('status', 'replayed', 'activity', to_jsonb(v_row));"

    def closed_guard() -> str:
        return f"""IF v_row.done_at IS NOT NULL OR v_row.cancelled_at IS NOT NULL THEN
            {_refuse('atividade_encerrada')}
        END IF;"""

    apply = _secdef(
        s, n["apply"], "p_org UUID, p_id UUID, p_actor UUID, p_intent TEXT, p_args JSONB", "UUID, UUID, UUID, TEXT, JSONB",
        f"""
DECLARE
    v_row {ac}%ROWTYPE; v_new {ac}%ROWTYPE; v_code TEXT; v_data JSONB := '{{}}'::jsonb;
    v_outcome TEXT; v_assignee UUID; v_due TIMESTAMPTZ; v_title TEXT; v_notes TEXT; v_fields TEXT[] := ARRAY[]::text[];
""",
        f"""
BEGIN
    SELECT * INTO v_row FROM {ac} WHERE org_id = p_org AND id = p_id FOR UPDATE;
    IF NOT FOUND THEN
        {_refuse('atividade_inexistente')}
    END IF;
    p_args := COALESCE(p_args, '{{}}'::jsonb);
    IF p_intent = 'concluir' THEN
        IF v_row.cancelled_at IS NOT NULL THEN
            {_refuse('atividade_encerrada')}
        END IF;
        IF v_row.done_at IS NOT NULL THEN
            {replayed()}
        END IF;
        v_outcome := COALESCE(NULLIF(p_args->>'outcome', ''), 'realizada');
        IF v_outcome NOT IN ({_in(ACTIVITY_OUTCOMES)}) THEN
            {_refuse('desfecho_invalido')}
        END IF;
        UPDATE {ac} SET done_at = now(), done_by = p_actor, outcome = v_outcome, updated_at = now()
            WHERE org_id = p_org AND id = p_id RETURNING * INTO v_new;
        v_data := jsonb_build_object('outcome', v_outcome);
    ELSIF p_intent = 'reabrir' THEN
        IF v_row.cancelled_at IS NOT NULL THEN
            {_refuse('atividade_encerrada')}
        END IF;
        IF v_row.done_at IS NULL THEN
            {replayed()}
        END IF;
        UPDATE {ac} SET done_at = NULL, done_by = NULL, outcome = NULL, updated_at = now()
            WHERE org_id = p_org AND id = p_id RETURNING * INTO v_new;
    ELSIF p_intent = 'reatribuir' THEN
        {closed_guard()}
        v_assignee := NULLIF(p_args->>'assignee_id', '')::uuid;
        IF v_assignee IS NOT DISTINCT FROM v_row.assignee_id THEN
            {replayed()}
        END IF;
        UPDATE {ac} SET assignee_id = v_assignee, updated_at = now()
            WHERE org_id = p_org AND id = p_id RETURNING * INTO v_new;
        v_data := jsonb_build_object('from', v_row.assignee_id, 'to', v_assignee);
    ELSIF p_intent = 'reagendar' THEN
        {closed_guard()}
        v_due := NULLIF(p_args->>'due_at', '')::timestamptz;
        IF v_due IS NOT DISTINCT FROM v_row.due_at THEN
            {replayed()}
        END IF;
        UPDATE {ac} SET due_at = v_due, updated_at = now()
            WHERE org_id = p_org AND id = p_id RETURNING * INTO v_new;
        v_data := jsonb_build_object('from', v_row.due_at, 'to', v_due);
    ELSIF p_intent = 'editar' THEN
        {closed_guard()}
        v_title := v_row.title;
        v_notes := v_row.notes;
        IF p_args ? 'title' THEN
            v_title := btrim(COALESCE(p_args->>'title', ''));
            IF v_title = '' THEN
                {_refuse('titulo_invalido')}
            END IF;
        END IF;
        IF p_args ? 'notes' THEN
            v_notes := NULLIF(p_args->>'notes', '');
        END IF;
        IF v_title IS DISTINCT FROM v_row.title THEN v_fields := array_append(v_fields, 'title'); END IF;
        IF v_notes IS DISTINCT FROM v_row.notes THEN v_fields := array_append(v_fields, 'notes'); END IF;
        IF cardinality(v_fields) = 0 THEN
            {replayed()}
        END IF;
        UPDATE {ac} SET title = v_title, notes = v_notes, updated_at = now()
            WHERE org_id = p_org AND id = p_id RETURNING * INTO v_new;
        v_data := jsonb_build_object('fields', to_jsonb(v_fields));
    ELSIF p_intent = 'cancelar' THEN
        IF v_row.cancelled_at IS NOT NULL THEN
            {replayed()}
        END IF;
        IF v_row.done_at IS NOT NULL THEN
            {_refuse('atividade_encerrada')}
        END IF;
        UPDATE {ac} SET cancelled_at = now(), updated_at = now()
            WHERE org_id = p_org AND id = p_id RETURNING * INTO v_new;
    ELSE
        {_refuse('intencao_invalida')}
    END IF;
    INSERT INTO {ev} (org_id, activity_id, event, actor_id, data)
        VALUES (p_org, p_id, CASE p_intent {" ".join(f"WHEN '{i}' THEN '{e}'" for i, e in INTENT_EVENT.items())} END, p_actor, v_data);
    RETURN jsonb_build_object('status', 'ok', 'activity', to_jsonb(v_new));
{_handler()}
END;""",
    )
    return "\n\n".join([seed, create, apply])


def activities_migration(cfg: ActivitiesConfig, schema: str) -> str:
    """The whole activities migration body for `schema` (header + search_path + tables + RPCs)."""
    if cfg.schema != schema:
        raise ValueError(f"cfg.schema {cfg.schema!r} != schema {schema!r}")
    return "\n\n".join([ACTIVITIES_MIGRATION_HEADER, f"{set_search_path(schema)};", *_tables(cfg, schema), _rpcs(cfg, schema)]) + "\n"


