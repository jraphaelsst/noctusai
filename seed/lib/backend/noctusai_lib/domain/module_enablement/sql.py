"""`module_enablement_migration(schema)` -- the per-org module switch table, SERVICE-ONLY.

One platform table, `public.org_modules(org_id, module_key, enabled)`. Absent row = module ENABLED (default ON for
every org). Written only by the platform-admin API; read only by the product backends through the service-role
client -- so there is no `authenticated` / `anon` grant and no browser policy (access tier `platform`: entitlements are
NoctusAI's commercial configuration, not the customer's data; a customer learns its own set through `GET /api/modules`).

Re-runnable (`IF NOT EXISTS`, `DROP POLICY IF EXISTS`). The table is always `public.org_modules` whichever schema is passed (products read it via `get_core_client()`).
"""
from __future__ import annotations

from noctusai_lib.domain.sql_templates import service_role_bypass, set_search_path

__all__ = ["MODULE_ENABLEMENT_MIGRATION_HEADER", "module_enablement_migration"]

MODULE_ENABLEMENT_MIGRATION_HEADER = (
    "-- Module enablement organ -- generated by noctusai_lib.domain.module_enablement.sql"
)


def module_enablement_migration(schema: str = "public", *, tier: str = "platform") -> str:
    # `schema` is accepted for the organ-registry signature only: the table is ONE platform table in `public`
    # (products read it through get_core_client()), whichever product renders the file.
    if tier not in ("platform", "org"):
        raise ValueError("tier must be 'platform' or 'org'")
    t = "public.org_modules"
    return f"""{MODULE_ENABLEMENT_MIGRATION_HEADER}
{set_search_path("public")};

CREATE TABLE IF NOT EXISTS {t} (
    org_id      UUID NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    module_key  TEXT NOT NULL,
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    updated_by  UUID,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, module_key)
);
COMMENT ON TABLE {t} IS 'tier:{tier}';

ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "service_role_bypass" ON {t};
{service_role_bypass("org_modules", schema="public")}
REVOKE ALL ON {t} FROM PUBLIC, anon, authenticated;
GRANT ALL ON {t} TO service_role;
"""
