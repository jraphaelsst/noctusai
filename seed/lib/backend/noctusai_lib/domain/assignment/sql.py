"""`assignment_migration(cfg)` -- the assignment organ DDL (service-only, `tier:org`) + the two RPCs that make an
assignment atomic.

    asg_settings      one row per org: the strategy, the default team, keep-last
    asg_teams         a named team (`auto` = takes part in org-wide round-robin; nullable `org_unit_id` = the unit seam)
    asg_members       a user in a team: active, `position` (rotation order), `capacity` (max OPEN subjects), out-of-office window
    asg_rules         `source` / `unit` value -> team (what `by_source` / `by_unit` read)
    asg_cursors       the round-robin cursor of a team (last member served, when)
    asg_assignments   the CURRENT owner of a subject (one row per `(org, subject_kind, subject_id)`; `closed_at` frees capacity)
    asg_events        APPEND-ONLY: assigned / reassigned / unassigned / closed / no_candidate, with from/to user, team,
                      strategy, criterion, actor -- every change of owner is a row, written in the same transaction as the change

`asg_assign` / `asg_release` are SECURITY DEFINER, service-role-only: under a per-member advisory lock they check capacity,
upsert the assignment, move the cursor, write the event AND (when the host named its card table) the card's owner column --
all or nothing. Tables are reached only through the API (service role): no `authenticated` / `anon` privilege.
"""
from __future__ import annotations

from noctusai_lib.domain._organ_common import definer_search_path, org_rls
from noctusai_lib.domain.sql_templates import set_search_path

from .config import AssignmentConfig
from .types import EVENT_KINDS, RULE_KINDS

ASSIGNMENT_MIGRATION_HEADER = "-- Assignment organ -- generated by noctusai_lib.domain.assignment.sql"
ASSIGNMENT_TABLES = ("settings", "teams", "members", "rules", "cursors", "assignments", "events")
APPEND_ONLY_TABLES = ("events",)

UQ_SETTINGS = "uq_{p}settings_org"
UQ_TEAMS = "uq_{p}teams_name"
UQ_MEMBERS = "uq_{p}members_team_user"
UQ_RULES = "uq_{p}rules_match"
UQ_CURSORS = "uq_{p}cursors_team"
UQ_ASSIGNMENTS = "uq_{p}assignments_subject"
CK_MEMBERS_CAPACITY = "{p}members_capacity_positive"
CK_MEMBERS_OOO = "{p}members_ooo_window"
CK_RULES_KIND = "{p}rules_kind"
CK_EVENTS_KIND = "{p}events_kind"
CK_SETTINGS_STRATEGY = "{p}settings_strategy_shape"
EVENTS_GUARD_FN = "{p}events_append_only"
EVENTS_GUARD_MESSAGE = "{p}events is append-only"
#: raised by the RPCs, translated by the Real ledger
ERR_CAPACITY_FULL = "asg_capacity_full"
ERR_SUBJECT_NOT_FOUND = "asg_subject_not_found"


def _section(title: str, schema: str, table: str, body: str) -> str:
    return (
        f"-- {title}\n{body.strip()}\nCOMMENT ON TABLE {schema}.{table} IS 'tier:org';\n"
        f"{org_rls(schema, table, 'NULL::uuid', grants=True, authenticated_select=False)}\n"
    )


def _quoted(values: tuple[str, ...]) -> str:
    return ", ".join(f"'{v}'" for v in values)


def _card_projection(cfg: AssignmentConfig, schema: str, value: str, *, strict: bool, only_if: str = "") -> str:
    """The in-transaction write of the owner onto the host's card (only for `cfg.subject_kind`; empty when no card table).

    `strict` raises when the card row is missing (an assign must not record an owner the funnel never saw); a release
    stays best-effort on a card that has since been deleted."""
    if not cfg.card_table:
        return ""
    org = " AND org_id = p_org" if cfg.card_has_org_id else ""
    guard = f" AND {only_if}" if only_if else ""
    missing = (
        f"\n        IF NOT FOUND THEN\n            RAISE EXCEPTION '{ERR_SUBJECT_NOT_FOUND}' USING ERRCODE = 'P0002';\n        END IF;"
        if strict
        else ""
    )
    return (
        f"\n    IF v_kind = '{cfg.subject_kind}'{guard} THEN\n"
        f"        UPDATE {schema}.{cfg.card_table} SET {cfg.responsavel_field} = {value} WHERE id = v_subject{org};{missing}\n"
        f"    END IF;"
    )


def _rpcs(cfg: AssignmentConfig, s: str) -> str:
    p = cfg.table_prefix
    t = {n: f"{s}.{cfg.table(n)}" for n in ASSIGNMENT_TABLES}
    assign, release = f"{s}.{cfg.table('assign')}", f"{s}.{cfg.table('release')}"
    path = definer_search_path(s)
    return f"""-- Assign (or reassign) a subject: capacity check under a per-member lock, assignment row, cursor, event, card owner -- ONE transaction.
-- `p_row`: subject_kind, subject_id, user_id, team_id?, org_unit_id?, strategy, criterion, actor_id?, note?, advance_cursor?, enforce_capacity?
CREATE OR REPLACE FUNCTION {assign}(p_org UUID, p_row JSONB) RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER
{path}
AS $fn$
DECLARE
    v_kind    TEXT := p_row->>'subject_kind';
    v_subject UUID := (p_row->>'subject_id')::uuid;
    v_user    UUID := (p_row->>'user_id')::uuid;
    v_team    UUID := nullif(p_row->>'team_id', '')::uuid;
    v_unit    UUID := nullif(p_row->>'org_unit_id', '')::uuid;
    v_prev    {t['assignments']}%ROWTYPE;
    v_had     BOOLEAN;
    v_row     {t['assignments']}%ROWTYPE;
    v_capacity INTEGER;
    v_open    INTEGER;
    v_event   TEXT;
    v_from    UUID;
BEGIN
    PERFORM pg_advisory_xact_lock(hashtextextended(p_org::text || ':' || v_user::text, 0));
    SELECT * INTO v_prev FROM {t['assignments']} WHERE org_id = p_org AND subject_kind = v_kind AND subject_id = v_subject FOR UPDATE;
    v_had := FOUND AND v_prev.closed_at IS NULL;
    IF v_had AND v_prev.user_id = v_user THEN
        RETURN jsonb_build_object('changed', false, 'event', NULL, 'assignment', to_jsonb(v_prev));
    END IF;

    IF coalesce((p_row->>'enforce_capacity')::boolean, false) AND v_team IS NOT NULL THEN
        SELECT capacity INTO v_capacity FROM {t['members']} WHERE org_id = p_org AND team_id = v_team AND user_id = v_user;
        IF v_capacity IS NOT NULL THEN
            SELECT count(*) INTO v_open FROM {t['assignments']}
             WHERE org_id = p_org AND user_id = v_user AND closed_at IS NULL AND NOT (subject_kind = v_kind AND subject_id = v_subject);
            IF v_open >= v_capacity THEN
                RAISE EXCEPTION '{ERR_CAPACITY_FULL}' USING ERRCODE = 'P0001';
            END IF;
        END IF;
    END IF;

    v_event := CASE WHEN v_had THEN 'reassigned' ELSE 'assigned' END;
    v_from  := CASE WHEN v_had THEN v_prev.user_id ELSE NULL END;
    INSERT INTO {t['assignments']} (org_id, subject_kind, subject_id, user_id, team_id, org_unit_id, strategy, criterion, assigned_at, closed_at)
    VALUES (p_org, v_kind, v_subject, v_user, v_team, v_unit, p_row->>'strategy', p_row->>'criterion', now(), NULL)
    ON CONFLICT (org_id, subject_kind, subject_id) DO UPDATE
       SET user_id = EXCLUDED.user_id, team_id = EXCLUDED.team_id, org_unit_id = EXCLUDED.org_unit_id,
           strategy = EXCLUDED.strategy, criterion = EXCLUDED.criterion, assigned_at = now(), closed_at = NULL, updated_at = now()
    RETURNING * INTO v_row;

    IF coalesce((p_row->>'advance_cursor')::boolean, false) AND v_team IS NOT NULL THEN
        INSERT INTO {t['cursors']} (org_id, team_id, last_user_id, moved_at) VALUES (p_org, v_team, v_user, now())
        ON CONFLICT (team_id) DO UPDATE SET last_user_id = EXCLUDED.last_user_id, moved_at = now(), updated_at = now();
    END IF;

    INSERT INTO {t['events']} (org_id, subject_kind, subject_id, event, from_user_id, to_user_id, team_id, org_unit_id, strategy, criterion, actor_id, note)
    VALUES (p_org, v_kind, v_subject, v_event, v_from, v_user, v_team, v_unit, p_row->>'strategy', p_row->>'criterion',
            nullif(p_row->>'actor_id', '')::uuid, p_row->>'note');
{_card_projection(cfg, s, 'v_user', strict=True)}
    RETURN jsonb_build_object('changed', true, 'event', v_event, 'assignment', to_jsonb(v_row));
END;
$fn$;
REVOKE EXECUTE ON FUNCTION {assign}(UUID, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {assign}(UUID, JSONB) TO service_role;

-- Release a subject: `unassigned` (no owner any more: the assignment row goes, the card owner is cleared) or `closed`
-- (the work is done: the owner stays as history, `closed_at` frees the member's capacity). The event is written either way.
-- `p_row`: subject_kind, subject_id, event ('unassigned' | 'closed'), actor_id?, note?
CREATE OR REPLACE FUNCTION {release}(p_org UUID, p_row JSONB) RETURNS JSONB
LANGUAGE plpgsql SECURITY DEFINER
{path}
AS $fn$
DECLARE
    v_kind    TEXT := p_row->>'subject_kind';
    v_subject UUID := (p_row->>'subject_id')::uuid;
    v_event   TEXT := p_row->>'event';
    v_prev    {t['assignments']}%ROWTYPE;
BEGIN
    IF v_event NOT IN ('unassigned', 'closed') THEN
        RAISE EXCEPTION 'asg_release: event must be unassigned or closed' USING ERRCODE = '22023';
    END IF;
    SELECT * INTO v_prev FROM {t['assignments']} WHERE org_id = p_org AND subject_kind = v_kind AND subject_id = v_subject FOR UPDATE;
    IF NOT FOUND OR v_prev.closed_at IS NOT NULL THEN
        RETURN jsonb_build_object('changed', false, 'event', NULL);
    END IF;
    IF v_event = 'closed' THEN
        UPDATE {t['assignments']} SET closed_at = now(), updated_at = now() WHERE id = v_prev.id;
    ELSE
        DELETE FROM {t['assignments']} WHERE id = v_prev.id;
    END IF;
    INSERT INTO {t['events']} (org_id, subject_kind, subject_id, event, from_user_id, to_user_id, team_id, org_unit_id, strategy, criterion, actor_id, note)
    VALUES (p_org, v_kind, v_subject, v_event, v_prev.user_id, NULL, v_prev.team_id, v_prev.org_unit_id, v_prev.strategy, v_prev.criterion,
            nullif(p_row->>'actor_id', '')::uuid, p_row->>'note');
{_card_projection(cfg, s, 'NULL', strict=False, only_if="v_event = 'unassigned'")}
    RETURN jsonb_build_object('changed', true, 'event', v_event);
END;
$fn$;
REVOKE EXECUTE ON FUNCTION {release}(UUID, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {release}(UUID, JSONB) TO service_role;
"""


def assignment_migration(cfg: AssignmentConfig, schema: str | None = None) -> str:
    s = schema or cfg.schema
    if s != cfg.schema:
        raise ValueError(f"schema {s!r} != cfg.schema {cfg.schema!r}")
    p = cfg.table_prefix
    t = {n: cfg.table(n) for n in ASSIGNMENT_TABLES}
    guard_fn = EVENTS_GUARD_FN.format(p=p)
    parts = [ASSIGNMENT_MIGRATION_HEADER, f"{set_search_path(s)};"]

    parts.append(_section("Teams: a named group of members. `auto` = takes part in org-wide round-robin; `org_unit_id` is the nullable unit seam.", s, t["teams"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['teams']} (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID NOT NULL,
    name        TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 60),
    auto        BOOLEAN NOT NULL DEFAULT true,
    org_unit_id UUID,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- A team name is unique per org, case-insensitively: two "Vendas" / "vendas" teams are one mistake.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_TEAMS.format(p=p)} ON {s}.{t['teams']} (org_id, lower(btrim(name)));
"""))

    parts.append(_section("Settings: ONE row per org -- the strategy (a builtin or a host-registered custom name), the default team, keep-last.", s, t["settings"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['settings']} (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id          UUID NOT NULL,
    strategy        TEXT NOT NULL DEFAULT 'round_robin',
    default_team_id UUID REFERENCES {s}.{t['teams']}(id) ON DELETE SET NULL,
    keep_last       BOOLEAN NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT {CK_SETTINGS_STRATEGY.format(p=p)} CHECK (strategy ~ '^[a-z][a-z0-9_]{{1,39}}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_SETTINGS.format(p=p)} ON {s}.{t['settings']} (org_id);
"""))

    parts.append(_section("Members: a user in a team, with rotation position, capacity (max OPEN subjects) and an out-of-office window.", s, t["members"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['members']} (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id     UUID NOT NULL,
    team_id    UUID NOT NULL REFERENCES {s}.{t['teams']}(id) ON DELETE CASCADE,
    user_id    UUID NOT NULL,
    active     BOOLEAN NOT NULL DEFAULT true,
    position   INTEGER NOT NULL DEFAULT 0,
    capacity   INTEGER,
    ooo_from   TIMESTAMPTZ,
    ooo_until  TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT {CK_MEMBERS_CAPACITY.format(p=p)} CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT {CK_MEMBERS_OOO.format(p=p)} CHECK (ooo_until IS NULL OR ooo_from IS NULL OR ooo_until > ooo_from)
);
-- One seat per user per team.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_MEMBERS.format(p=p)} ON {s}.{t['members']} (team_id, user_id);
CREATE INDEX IF NOT EXISTS idx_{t['members']}_user ON {s}.{t['members']} (org_id, user_id);
"""))

    parts.append(_section("Rules: a `source` / `unit` value routes to a team (read by the by_source / by_unit strategies).", s, t["rules"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['rules']} (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID NOT NULL,
    kind        TEXT NOT NULL,
    match_value TEXT NOT NULL CHECK (length(btrim(match_value)) > 0),
    team_id     UUID NOT NULL REFERENCES {s}.{t['teams']}(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT {CK_RULES_KIND.format(p=p)} CHECK (kind IN ({_quoted(RULE_KINDS)}))
);
-- One team per (kind, value): two would make "which team wins" a coin flip.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_RULES.format(p=p)} ON {s}.{t['rules']} (org_id, kind, match_value);
"""))

    parts.append(_section("Cursors: where a team's round-robin stands (last member served, when).", s, t["cursors"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['cursors']} (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id       UUID NOT NULL,
    team_id      UUID NOT NULL REFERENCES {s}.{t['teams']}(id) ON DELETE CASCADE,
    last_user_id UUID,
    moved_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_CURSORS.format(p=p)} ON {s}.{t['cursors']} (team_id);
"""))

    parts.append(_section("Assignments: the CURRENT owner of a subject (`org_unit_id` = the nullable unit seam). `closed_at` frees capacity.", s, t["assignments"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['assignments']} (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id       UUID NOT NULL,
    subject_kind TEXT NOT NULL CHECK (subject_kind ~ '^[a-z][a-z0-9_]{{0,39}}$'),
    subject_id   UUID NOT NULL,
    user_id      UUID NOT NULL,
    team_id      UUID REFERENCES {s}.{t['teams']}(id) ON DELETE SET NULL,
    org_unit_id  UUID,
    strategy     TEXT NOT NULL,
    criterion    TEXT NOT NULL,
    assigned_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at    TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- One current owner per subject: the guard that makes a concurrent double-assign impossible.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_ASSIGNMENTS.format(p=p)} ON {s}.{t['assignments']} (org_id, subject_kind, subject_id);
CREATE INDEX IF NOT EXISTS idx_{t['assignments']}_open ON {s}.{t['assignments']} (org_id, user_id) WHERE closed_at IS NULL;
"""))

    parts.append(_section("Events: APPEND-ONLY. Every change of owner is a row (who -> who, which team, which strategy, why, by whom).", s, t["events"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['events']} (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id       UUID NOT NULL,
    subject_kind TEXT NOT NULL,
    subject_id   UUID NOT NULL,
    event        TEXT NOT NULL,
    from_user_id UUID,
    to_user_id   UUID,
    team_id      UUID,
    org_unit_id  UUID,
    strategy     TEXT,
    criterion    TEXT,
    actor_id     UUID,
    note         TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT {CK_EVENTS_KIND.format(p=p)} CHECK (event IN ({_quoted(EVENT_KINDS)}))
);
CREATE INDEX IF NOT EXISTS idx_{t['events']}_subject ON {s}.{t['events']} (org_id, subject_kind, subject_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_{t['events']}_when ON {s}.{t['events']} (org_id, created_at DESC);
CREATE OR REPLACE FUNCTION {s}.{guard_fn}()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER {definer_search_path(s)}
AS $$ BEGIN RAISE EXCEPTION '{EVENTS_GUARD_MESSAGE.format(p=p)}' USING ERRCODE = 'insufficient_privilege'; END; $$;
REVOKE ALL ON FUNCTION {s}.{guard_fn}() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {s}.{guard_fn}() TO service_role;
DROP TRIGGER IF EXISTS {guard_fn} ON {s}.{t['events']};
CREATE TRIGGER {guard_fn}
    BEFORE UPDATE OR DELETE ON {s}.{t['events']}
    FOR EACH ROW EXECUTE FUNCTION {s}.{guard_fn}();
"""))
    parts.append(_rpcs(cfg, s))
    return "\n".join(parts)


