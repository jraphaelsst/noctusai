"""`resumable_uploads_migration(schema)` -- upload sessions + append-only events, SERVICE-ONLY (tier `org`, written
through the backend only; no browser grant: the browser talks to the upload endpoints, never to these tables).
Re-runnable (`IF NOT EXISTS`, `DROP POLICY IF EXISTS`)."""
from __future__ import annotations

from noctusai_lib.domain.sql_templates import service_role_bypass, set_search_path

__all__ = ["RESUMABLE_UPLOADS_MIGRATION_HEADER", "resumable_uploads_migration"]

RESUMABLE_UPLOADS_MIGRATION_HEADER = "-- Resumable uploads organ -- generated by noctusai_lib.domain.resumable_uploads.sql"


def resumable_uploads_migration(schema: str = "public") -> str:
    # postgrest-qualified-ok: these are DDL identifiers in the migration SQL, never a PostgREST table name
    s, t, e = schema, f"{schema}.upload_sessions", f"{schema}.upload_session_events"
    return f"""{RESUMABLE_UPLOADS_MIGRATION_HEADER}
{set_search_path(s)};

CREATE TABLE IF NOT EXISTS {t} (
    id           UUID PRIMARY KEY,
    org_id       UUID NOT NULL,
    user_id      UUID,
    filename     TEXT NOT NULL,
    content_type TEXT NOT NULL,
    size_bytes   BIGINT NOT NULL CHECK (size_bytes > 0),
    part_size    INTEGER NOT NULL CHECK (part_size > 0),
    total_parts  INTEGER NOT NULL CHECK (total_parts > 0),
    status       TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','completed','aborted','expired')),
    client_key   TEXT,
    object_key   TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ
);
COMMENT ON TABLE {t} IS 'tier:org';
CREATE INDEX IF NOT EXISTS upload_sessions_org_key_idx ON {t} (org_id, client_key) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS upload_sessions_expiry_idx ON {t} (expires_at) WHERE status = 'open';

CREATE TABLE IF NOT EXISTS {e} (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    org_id      UUID NOT NULL,
    session_id  UUID NOT NULL REFERENCES {t}(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL CHECK (kind IN ('opened','completed','aborted','expired')),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    detail      JSONB NOT NULL DEFAULT '{{}}'::jsonb
);
COMMENT ON TABLE {e} IS 'tier:org';
CREATE INDEX IF NOT EXISTS upload_session_events_session_idx ON {e} (session_id, occurred_at);

ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;
ALTER TABLE {e} ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "service_role_bypass" ON {t};
{service_role_bypass("upload_sessions", schema=s)}
DROP POLICY IF EXISTS "service_role_bypass" ON {e};
{service_role_bypass("upload_session_events", schema=s)}
REVOKE ALL ON {t} FROM PUBLIC, anon, authenticated;
REVOKE ALL ON {e} FROM PUBLIC, anon, authenticated;
GRANT ALL ON {t} TO service_role;
GRANT ALL ON {e} TO service_role;
"""
