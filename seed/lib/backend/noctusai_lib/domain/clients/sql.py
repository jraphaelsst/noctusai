"""`clients_table_ddl(schema, config)` / `clients_migration(schema, config)` -- the clients DDL for a product schema.

Same conventions as the other organs: `org_id UUID NOT NULL`, RLS on, own-org SELECT for `authenticated` + the
literal-named `service_role_bypass`; the backend writes through the service role, so no authenticated write policy
exists. Re-runnable (`IF NOT EXISTS`, `DROP POLICY IF EXISTS`).

Four tables:

* `clients` -- the person. `status` / `tags` are DATA (`ClientsConfig`), plain TEXT. `doc` (CPF) is a person's
  document, so the table has NO authenticated read path (`authenticated_select=False`): the API masks it per role.
  One client per lead (`uq_<clients>_lead`) makes the lead->client conversion idempotent under concurrency.
* `client_schedules` -- a weekly slot (`weekday` 0 = Monday, wall-clock `slot_time` in the org's zone; the API calls it `time`).
  `materialized_until` is the materialization cursor: sessions are generated only past it, so a generated session
  the user deleted is never resurrected by the next top-up.
* `client_sessions` -- one appointment. `entry_id` is the finance receivable when booked (no FK: the finance
  tables belong to another organ and may be absent); `booking_rev` versions the receivable's `source_ref` so a
  session un-billed (receivable cancelled) and billed again books a FRESH receivable. `uq_<sessions>_slot`
  (`schedule_id, starts_at`) is the idempotency guard of materialization (NULL `schedule_id` = one-off, never
  conflicts).
* `client_payments` -- the manual payment record (method + notes + which finance settlements it produced). The
  settlement itself carries the method; the notes live here (finance settlements have no notes column).

Prerequisite (not created here): `public.current_org_id_for(text)`.
"""
from __future__ import annotations

from typing import Optional

from noctusai_lib.domain._organ_common import org_rls
from noctusai_lib.domain.sql_templates import set_search_path

from .config import ClientsConfig

CLIENTS_MIGRATION_HEADER = "-- Clients organ -- generated by noctusai_lib.domain.clients.sql"
UQ_LEAD = "uq_{table}_lead"
UQ_SLOT = "uq_{table}_slot"


def clients_table_ddl(schema: str, config: Optional[ClientsConfig] = None, *, org_id_expr: Optional[str] = None) -> str:
    """The four tables + indexes + RLS, schema-qualified (no header / search_path prelude)."""
    if not schema or not schema.strip():
        raise ValueError("clients_table_ddl requires a non-empty schema")
    cfg = config or ClientsConfig()
    expr = org_id_expr or f"public.current_org_id_for('{schema}')"
    s = schema
    c, se, sc, p = cfg.clients_table, cfg.sessions_table, cfg.schedules_table, cfg.payments_table
    return f"""CREATE TABLE IF NOT EXISTS {s}.{c} (
    id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id               UUID NOT NULL,
    name                 TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    phone                TEXT,
    email                TEXT,
    doc                  TEXT,
    birth_date           DATE,
    status               TEXT NOT NULL,
    tags                 TEXT[] NOT NULL DEFAULT '{{}}',
    notes                TEXT,
    lead_id              UUID,
    whatsapp_chat_id     TEXT,
    default_price_cents  BIGINT CHECK (default_price_cents IS NULL OR default_price_cents >= 0),
    session_duration_min INTEGER CHECK (session_duration_min IS NULL OR session_duration_min > 0),
    started_at           DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by           UUID
);
-- One client per lead: the guard that makes the lead -> client conversion idempotent (NULL lead_id never conflicts).
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_LEAD.format(table=c)} ON {s}.{c} (org_id, lead_id);
CREATE INDEX IF NOT EXISTS idx_{c}_name ON {s}.{c} (org_id, name, id);
{org_rls(s, c, expr, grants=True, authenticated_select=False)}

CREATE TABLE IF NOT EXISTS {s}.{sc} (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id             UUID NOT NULL,
    client_id          UUID NOT NULL REFERENCES {s}.{c}(id) ON DELETE CASCADE,
    weekday            SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    slot_time          TIME NOT NULL,
    duration_min       INTEGER NOT NULL CHECK (duration_min > 0),
    price_cents        BIGINT CHECK (price_cents IS NULL OR price_cents >= 0),
    starts_on          DATE NOT NULL,
    ends_on            DATE CHECK (ends_on IS NULL OR ends_on >= starts_on),
    active             BOOLEAN NOT NULL DEFAULT true,
    materialized_until DATE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_{sc}_client ON {s}.{sc} (org_id, client_id);
{org_rls(s, sc, expr, grants=True)}

CREATE TABLE IF NOT EXISTS {s}.{se} (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id        UUID NOT NULL,
    client_id     UUID NOT NULL REFERENCES {s}.{c}(id) ON DELETE CASCADE,
    schedule_id   UUID REFERENCES {s}.{sc}(id) ON DELETE SET NULL,
    starts_at     TIMESTAMPTZ NOT NULL,
    duration_min  INTEGER NOT NULL CHECK (duration_min > 0),
    status        TEXT NOT NULL,
    price_cents   BIGINT CHECK (price_cents IS NULL OR price_cents >= 0),
    waive_charge  BOOLEAN NOT NULL DEFAULT false,
    notes         TEXT,
    entry_id      UUID,
    booking_rev   INTEGER NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- One generated session per (schedule, instant): the guard that makes materialization idempotent.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_SLOT.format(table=se)} ON {s}.{se} (schedule_id, starts_at);
CREATE INDEX IF NOT EXISTS idx_{se}_org_starts ON {s}.{se} (org_id, starts_at, id);
CREATE INDEX IF NOT EXISTS idx_{se}_client_starts ON {s}.{se} (org_id, client_id, starts_at);
{org_rls(s, se, expr, grants=True)}

CREATE TABLE IF NOT EXISTS {s}.{p} (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id         UUID NOT NULL,
    client_id      UUID NOT NULL REFERENCES {s}.{c}(id) ON DELETE RESTRICT,
    amount_cents   BIGINT NOT NULL CHECK (amount_cents > 0),
    paid_on        DATE NOT NULL,
    account_id     UUID NOT NULL,
    method         TEXT NOT NULL,
    notes          TEXT,
    settlement_ids UUID[] NOT NULL DEFAULT '{{}}',
    created_by     UUID,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_{p}_client ON {s}.{p} (org_id, client_id, paid_on);
{org_rls(s, p, expr, grants=True)}
"""


def clients_migration(schema: str, config: Optional[ClientsConfig] = None, *, org_id_expr: Optional[str] = None) -> str:
    """The whole clients migration body for `schema` (header + search_path + DDL)."""
    return "\n\n".join(
        [CLIENTS_MIGRATION_HEADER, f"{set_search_path(schema)};", clients_table_ddl(schema, config, org_id_expr=org_id_expr)]
    )


__all__ = ["CLIENTS_MIGRATION_HEADER", "UQ_LEAD", "UQ_SLOT", "clients_migration", "clients_table_ddl"]
