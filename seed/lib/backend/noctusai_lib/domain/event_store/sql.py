def _lit(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _arr(values) -> str:
    return "ARRAY[" + ", ".join(_lit(v) for v in values) + "]::text[]"


def _event_json(alias: str) -> str:
    """One stored event as jsonb (the `tx_id` xid8 as a JSON number)."""
    a = alias
    return (f"jsonb_build_object('global_position', {a}.global_position, 'event_id', {a}.event_id, 'org_id', {a}.org_id, "
            f"'stream_type', {a}.stream_type, 'stream_id', {a}.stream_id, 'version', {a}.version, "
            f"'event_type', {a}.event_type, 'schema_version', {a}.schema_version, 'data', {a}.data, "
            f"'metadata', {a}.metadata, 'occurred_at', {a}.occurred_at, 'recorded_at', {a}.recorded_at, "
            f"'tx_id', {a}.tx_id::text::bigint)")


def _fn(s: str, name: str, args: str, sig: str, body: str, *, returns: str = "JSONB", volatility: str = "",
        public: bool = True) -> str:
    fn = f"{s}.{name}"
    vol = f"\n{volatility}" if volatility else ""
    grant = f"\nGRANT EXECUTE ON FUNCTION {fn}({sig}) TO service_role;" if public else ""
    return f"""CREATE OR REPLACE FUNCTION {fn}({args}) RETURNS {returns}
LANGUAGE plpgsql{vol}
SECURITY DEFINER
{definer_search_path(s)}
AS $fn$
{body.strip()}
$fn$;
REVOKE ALL ON FUNCTION {fn}({sig}) FROM PUBLIC, anon, authenticated;{grant}"""


def _refused(code: str, extra: str = "") -> str:
    tail = f", {extra}" if extra else ""
    return f"jsonb_build_object('status', 'refused', 'code', {_lit(code)}{tail})"


