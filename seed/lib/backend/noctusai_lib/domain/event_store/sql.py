"""`event_store_migration(cfg)` -- the event store organ's tables, guards and RPCs for ONE product schema.

The log IS the truth (KB § PATTERNS/backend/event-store.md; the sibling for "the state row is the truth" is the
transition log). What one render emits (forward-only, idempotent -- the chain replay applies it twice):

* `es_streams (stream_type, stream_id, org_id, version, updated_at)` -- one row per stream, the optimistic-
  concurrency anchor (`es_append` locks it FOR UPDATE);
* `es_events (global_position identity, event_id UNIQUE, org_id, stream_type, stream_id, version, event_type,
  schema_version, data, pii, subject_id, metadata, occurred_at, recorded_at, tx_id)` with
  `UNIQUE(stream_type, stream_id, version)`; the only FK is a NO ACTION one to `es_streams` (never CASCADE);
* `es_projections` (the projection registry, see below) and `es_checkpoints (projection, tx_id, position, ...)`;
* immutability: `guc_carveout_guard_sql` makes `es_events` writable by INSERT only under `es_append`'s
  transaction-local flag (UPDATE and DELETE always refused) and `es_streams` writable only under the same flag
  (DELETE always refused); `truncate_guard_sql` refuses TRUNCATE on both;
* LGPD (owner rule 2026-11-07, "never personal data in events by default"): `pii` and `subject_id` are
  RESERVED -- a CHECK keeps both NULL until a migration deliberately enables crypto-shredding; metadata keys
  are a closed set of ids/provenance;
* RPCs (SECURITY DEFINER, `search_path` pinned, EXECUTE revoked from PUBLIC/anon/authenticated, granted to
  service_role), all answering jsonb `{status: ...}`:
  `es_append`, `es_load`, `es_read_all`, `es_stored_event_types`, `es_register_projection`,
  `es_run_projection`, `es_rebuild_begin` / `es_rebuild_step` / `es_rebuild_swap`,
  `es_checkpoint_get` / `es_checkpoint_advance` / `es_checkpoint_error` / `es_checkpoint_reset`.

**Read visibility.** `es_read_all` (and every projection read) returns only events whose writing transaction is
SETTLED -- `tx_id < pg_snapshot_xmin(pg_current_snapshot())` -- and orders/pages by the pair
`(tx_id, global_position)`, never by `global_position` alone: a position is taken at INSERT time, so a
transaction that inserted early and commits late would otherwise be skipped by a reader that already advanced
past it. Every transaction with an xid below the snapshot's xmin has finished, so the set below the cursor never
grows again.

**Projection hooks.** A projection is a SQL function `<schema>.<handler>(p_events jsonb, p_target regclass)
RETURNS void` registered by name in `es_projections` (via `es_register_projection`, from the product's own
migration). `sync` projections are called by `es_append` inside its transaction (a failing hook refuses the
whole append); `async` ones by `es_run_projection`, which applies a batch AND advances the checkpoint in ONE
transaction. The target is a parameter so the rebuild can replay the same handler into a shadow table.
"""
