"""`engagement_migration(cfg)` -- the engagement organ DDL: points ledger + owner-tunable rules (service-only, `tier:org`).

    points         the ledger: APPEND-ONLY. UPDATE is always refused; DELETE is refused except inside the one
                   SECURITY DEFINER path (`erase_member_points`, the LGPD delete-by-subject) that raises a
                   transaction-local GUC (`guc_carveout_guard_sql`). Idempotent on `(org_id, member_id, idempotency_key)`.
    point_rules    points per `(source, action)` with optional daily / period caps (`PointRule`)
    badge_rules    a threshold on a metric (`BadgeRule`)

Totals are a SQL SUM (`points_totals`), never a Python loop; a stored projection is added only if that is MEASURED slow.
All tables are reached only through the API (service role): no `authenticated` / `anon` privilege.
"""
from __future__ import annotations

from noctusai_lib.domain._organ_common import definer_search_path, org_rls
from noctusai_lib.domain.engagement.config import EngagementConfig
from noctusai_lib.domain.sql_templates import guc_carveout_guard_sql, guc_carveout_set_config_sql, set_search_path

ENGAGEMENT_MIGRATION_HEADER = "-- Engagement organ -- generated by noctusai_lib.domain.engagement.sql"
ENGAGEMENT_TABLES = ("points", "point_rules", "badge_rules")
UQ_POINT_RULES = "uq_{p}point_rules_action"
UQ_BADGE_RULES = "uq_{p}badge_rules_badge"
POINTS_GUARD_FN = "guard_{p}points_append_only"
POINTS_ERASE_GUC = "engagement.erase_points"
POINTS_TOTALS_RPC = "points_totals"
POINTS_ERASE_RPC = "erase_member_points"
POINTS_GUARD_MESSAGE = "{p}points is append-only"


def _section(title: str, schema: str, table: str, body: str) -> str:
    return (
        f"-- {title}\n{body.strip()}\nCOMMENT ON TABLE {schema}.{table} IS 'tier:org';\n"
        f"{org_rls(schema, table, 'NULL::uuid', grants=True, authenticated_select=False)}\n"
    )


def engagement_migration(cfg: EngagementConfig, schema: str | None = None) -> str:
    s = schema or cfg.schema
    if s != cfg.schema:
        raise ValueError(f"schema {s!r} != cfg.schema {cfg.schema!r}")
    p = cfg.table_prefix
    t = {n: f"{p}{n}" for n in ENGAGEMENT_TABLES}
    guard_fn = POINTS_GUARD_FN.format(p=p)
    parts = [ENGAGEMENT_MIGRATION_HEADER, f"{set_search_path(s)};"]

    totals, erase = f"{p}{POINTS_TOTALS_RPC}", f"{p}{POINTS_ERASE_RPC}"
    parts.append(_section("Points ledger -- append-only; the one DELETE path is the LGPD erase-by-subject function.", s, t["points"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['points']} (
    org_id          UUID NOT NULL,
    member_id       TEXT NOT NULL CHECK (length(btrim(member_id)) > 0),
    source          TEXT NOT NULL CHECK (length(btrim(source)) > 0),
    action          TEXT NOT NULL CHECK (length(btrim(action)) > 0),
    points          INTEGER NOT NULL,
    occurred_at     TIMESTAMPTZ NOT NULL,
    idempotency_key TEXT NOT NULL CHECK (length(btrim(idempotency_key)) > 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- the idempotency guarantee: a replayed event never double-counts (the Real ledger treats 23505 as "already recorded")
    PRIMARY KEY (org_id, member_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_{t['points']}_when ON {s}.{t['points']} (org_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_{t['points']}_member ON {s}.{t['points']} (org_id, member_id, source, action);

{guc_carveout_guard_sql(schema=s, table=t['points'], guc=POINTS_ERASE_GUC, function=guard_fn, trigger=guard_fn, error_message=POINTS_GUARD_MESSAGE.format(p=p), errcode='insufficient_privilege', allow_ops=('DELETE',), search_path=('pg_catalog', s, 'pg_temp'))}

-- Per-member totals over a window as ONE SQL aggregate.
CREATE OR REPLACE FUNCTION {s}.{totals}(p_org UUID, p_members TEXT[] DEFAULT NULL, p_since TIMESTAMPTZ DEFAULT NULL, p_until TIMESTAMPTZ DEFAULT NULL)
RETURNS TABLE (member_id TEXT, points BIGINT)
LANGUAGE sql STABLE SECURITY DEFINER
{definer_search_path(s)}
AS $fn$
    SELECT g.member_id, sum(g.points)::bigint
      FROM {s}.{t['points']} g
     WHERE g.org_id = p_org
       AND (p_members IS NULL OR g.member_id = ANY(p_members))
       AND (p_since IS NULL OR g.occurred_at >= p_since)
       AND (p_until IS NULL OR g.occurred_at < p_until)
     GROUP BY g.member_id
$fn$;
REVOKE EXECUTE ON FUNCTION {s}.{totals}(UUID, TEXT[], TIMESTAMPTZ, TIMESTAMPTZ) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {s}.{totals}(UUID, TEXT[], TIMESTAMPTZ, TIMESTAMPTZ) TO service_role;

-- LGPD delete-by-subject: the ONLY path allowed to delete ledger rows (raises the transaction-local GUC around the DELETE).
CREATE OR REPLACE FUNCTION {s}.{erase}(p_org UUID, p_member TEXT) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER
{definer_search_path(s)}
AS $fn$
DECLARE
    v_deleted BIGINT;
BEGIN
    {guc_carveout_set_config_sql(POINTS_ERASE_GUC, True)}
    DELETE FROM {s}.{t['points']} WHERE org_id = p_org AND member_id = p_member;
    GET DIAGNOSTICS v_deleted = ROW_COUNT;
    {guc_carveout_set_config_sql(POINTS_ERASE_GUC, False)}
    RETURN v_deleted;
END;
$fn$;
REVOKE EXECUTE ON FUNCTION {s}.{erase}(UUID, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION {s}.{erase}(UUID, TEXT) TO service_role;
"""))

    parts.append(_section("Owner-tunable points per (source, action), with optional daily / period caps.", s, t["point_rules"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['point_rules']} (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id     UUID NOT NULL,
    source     TEXT NOT NULL CHECK (length(btrim(source)) > 0),
    action     TEXT NOT NULL CHECK (length(btrim(action)) > 0),
    points     INTEGER NOT NULL CHECK (points > 0),
    daily_cap  INTEGER CHECK (daily_cap IS NULL OR daily_cap > 0),
    period_cap INTEGER CHECK (period_cap IS NULL OR period_cap > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (daily_cap IS NULL OR period_cap IS NULL OR daily_cap <= period_cap)
);
-- One rule per (source, action): two would make "which rule wins" a coin flip.
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_POINT_RULES.format(p=p)} ON {s}.{t['point_rules']} (org_id, source, action);
"""))

    parts.append(_section("Badges: a threshold on a metric (`points`, `count:<source>.<action>`).", s, t["badge_rules"], f"""
CREATE TABLE IF NOT EXISTS {s}.{t['badge_rules']} (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID NOT NULL,
    badge_id    TEXT NOT NULL CHECK (length(btrim(badge_id)) > 0),
    metric      TEXT NOT NULL CHECK (length(btrim(metric)) > 0),
    threshold   INTEGER NOT NULL CHECK (threshold > 0),
    label       TEXT,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS {UQ_BADGE_RULES.format(p=p)} ON {s}.{t['badge_rules']} (org_id, badge_id);
"""))
    return "\n".join(parts)


