export type ItemsMessageKey = keyof typeof ITEMS_MESSAGES;

/** Translate an items message key (pt-BR). `{name}` placeholders are filled from `vars`. */
export function itemsT(key: string, vars?: Record<string, string | number>): string {
  const raw = (ITEMS_MESSAGES as Record<string, string>)[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : raw;
}
