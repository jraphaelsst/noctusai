-- ────────────────────────────────────────────────────────────────────────
-- 2. Knowledge documents ↔ editorial items.
--
-- The `knowledge_documents` ROW always holds the PUBLISHED content (that is
-- what FTS, `kb_ler`, `search_knowledge` and every store read serve), so
-- retrieval never needs a second read path. A governed document is a row
-- + an editorial item; its drafts live in `editorial_versions`, never on the
-- row. Publish copies the published version onto the row (trigger below),
-- archive deactivates it. Until its first publish a governed document is
-- `ativo = false` (invisible to retrieval).
--
-- Governance is per COLLECTION (`requer_revisao`, default false) and applies
-- to documents entering/changing through the store. Agent-package sync
-- collections (`projeto-<slug>`) are never flagged: developer-owned context
-- stays git-is-the-source (Decision Board agents-a1..a5, 2026-10-03).
-- ────────────────────────────────────────────────────────────────────────

ALTER TABLE agents.knowledge_collections
    ADD COLUMN IF NOT EXISTS requer_revisao BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE agents.knowledge_documents
    ADD COLUMN IF NOT EXISTS editorial_item_id UUID NULL
        REFERENCES agents.editorial_items(id) ON DELETE RESTRICT;

CREATE UNIQUE INDEX IF NOT EXISTS idx_agents_knowledge_documents_editorial_item
    ON agents.knowledge_documents (editorial_item_id) WHERE editorial_item_id IS NOT NULL;

-- Write guard on governed documents: content, activation and identity change
-- ONLY through the publish/archive sync below (which raises the
-- transaction-local flag). A direct service-role UPDATE cannot edit live
-- governed content around the review, and cannot activate an unpublished
-- document. Linking an unlinked row (NULL -> item) is the one allowed edge.
CREATE OR REPLACE FUNCTION agents.knowledge_guard_governed()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = agents, public
AS $fn$
DECLARE
    v_published INTEGER;
BEGIN
    IF NEW.editorial_item_id IS NOT NULL AND NEW.ativo THEN
        SELECT i.published_version_n INTO v_published
          FROM agents.editorial_items i WHERE i.id = NEW.editorial_item_id;
        IF v_published IS NULL THEN
            RAISE EXCEPTION 'knowledge_unpublished_cannot_be_active' USING ERRCODE = 'P0001';
        END IF;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.editorial_item_id IS NOT NULL
       AND current_setting('agents.knowledge_publish_sync', true) IS DISTINCT FROM 'on' THEN
        IF NEW.editorial_item_id IS DISTINCT FROM OLD.editorial_item_id
           OR NEW.titulo IS DISTINCT FROM OLD.titulo
           OR NEW.tipo IS DISTINCT FROM OLD.tipo
           OR NEW.resumo IS DISTINCT FROM OLD.resumo
           OR NEW.conteudo IS DISTINCT FROM OLD.conteudo
           OR NEW.proveniencia IS DISTINCT FROM OLD.proveniencia
           OR NEW.source_sha IS DISTINCT FROM OLD.source_sha
           OR NEW.ativo IS DISTINCT FROM OLD.ativo
           OR NEW.slug IS DISTINCT FROM OLD.slug
           OR NEW.collection_id IS DISTINCT FROM OLD.collection_id THEN
            RAISE EXCEPTION 'knowledge_governed_write_via_editorial' USING ERRCODE = 'P0001';
        END IF;
    END IF;
    RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS knowledge_guard_governed ON agents.knowledge_documents;
CREATE TRIGGER knowledge_guard_governed
    BEFORE INSERT OR UPDATE ON agents.knowledge_documents
    FOR EACH ROW EXECUTE FUNCTION agents.knowledge_guard_governed();

-- publish / archive -> the document row. AFTER INSERT on the append-only event
-- log (same transaction as the transition), so the row can never disagree with
-- the item's published version.
CREATE OR REPLACE FUNCTION agents.knowledge_sync_published()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = agents, public
AS $fn$
DECLARE
    v_item agents.editorial_items%ROWTYPE;
    v_doc agents.knowledge_documents%ROWTYPE;
    v_content JSONB;
BEGIN
    SELECT * INTO v_item FROM agents.editorial_items WHERE id = NEW.item_id;
    IF NOT FOUND OR v_item.kind <> 'knowledge_document' THEN
        RETURN NEW;
    END IF;
    SELECT * INTO v_doc FROM agents.knowledge_documents WHERE editorial_item_id = NEW.item_id;
    IF NOT FOUND THEN
        RETURN NEW;  -- item exists before its row is linked (create flow): nothing to sync yet
    END IF;
    PERFORM set_config('agents.knowledge_publish_sync', 'on', true);
    IF NEW.action = 'publish' THEN
        SELECT v.content INTO v_content FROM agents.editorial_versions v
         WHERE v.item_id = NEW.item_id AND v.n = NEW.version_n;
        UPDATE agents.knowledge_documents SET
            titulo = v_content->>'titulo',
            tipo = v_content->>'tipo',
            resumo = v_content->>'resumo',
            conteudo = v_content->>'conteudo',
            proveniencia = coalesce(v_content->'proveniencia', '{}'::jsonb),
            source_sha = v_content->>'source_sha',
            ativo = true
         WHERE id = v_doc.id;
        INSERT INTO agents.knowledge_revisions (org_id, document_id, op, snapshot, author_id, motivo)
        VALUES (v_doc.org_id, v_doc.id, 'update',
                jsonb_build_object('editorial_item_id', NEW.item_id, 'version_n', NEW.version_n,
                                   'source_sha', v_content->>'source_sha', 'ativo', true),
                NEW.actor_id, 'editorial:publish');
    ELSIF NEW.action = 'archive' THEN
        UPDATE agents.knowledge_documents SET ativo = false WHERE id = v_doc.id;
        INSERT INTO agents.knowledge_revisions (org_id, document_id, op, snapshot, author_id, motivo)
        VALUES (v_doc.org_id, v_doc.id, 'archive',
                jsonb_build_object('editorial_item_id', NEW.item_id, 'version_n', NEW.version_n, 'ativo', false),
                NEW.actor_id, coalesce(NEW.motivo, 'editorial:archive'));
    END IF;
    PERFORM set_config('agents.knowledge_publish_sync', 'off', true);
    RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS knowledge_sync_published ON agents.editorial_events;
CREATE TRIGGER knowledge_sync_published
    AFTER INSERT ON agents.editorial_events
    FOR EACH ROW WHEN (NEW.action IN ('publish', 'archive'))
    EXECUTE FUNCTION agents.knowledge_sync_published();

REVOKE ALL ON FUNCTION agents.knowledge_guard_governed() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION agents.knowledge_sync_published() FROM PUBLIC, anon, authenticated;

-- ────────────────────────────────────────────────────────────────────────
-- 3. govern_collection — flag a collection `requer_revisao` and BACKFILL every
-- existing document in it: a live document (ativo) becomes the PUBLISHED
-- version 1 of a new item, an archived one an `arquivado` item, so retrieval
-- returns exactly what it returned before the flag (nothing is hidden). One
-- transaction; idempotent (already-linked documents are skipped). The
-- backfill writes through the editorial tables' own write-guard flag with a
-- synthetic, clearly-marked history (one `publish`/`archive` event, motivo
-- "backfill ...") — it is not a review and does not pretend to be one.
-- ────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION agents.govern_collection(
    p_org_id UUID, p_collection_id UUID, p_actor_id UUID
) RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = agents, public
AS $fn$
DECLARE
    d agents.knowledge_documents%ROWTYPE;
    v_content JSONB;
    v_item UUID;
    v_n INTEGER := 0;
BEGIN
    IF p_actor_id IS NULL THEN
        RAISE EXCEPTION 'editorial_actor_required' USING ERRCODE = 'P0001';
    END IF;
    PERFORM 1 FROM agents.knowledge_collections c
     WHERE c.id = p_collection_id AND c.org_id = p_org_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'knowledge_collection_not_found' USING ERRCODE = 'P0001';
    END IF;
    FOR d IN SELECT * FROM agents.knowledge_documents x
              WHERE x.collection_id = p_collection_id AND x.org_id = p_org_id
                AND x.editorial_item_id IS NULL ORDER BY x.created_at, x.id LOOP
        v_content := jsonb_build_object(
            'titulo', d.titulo, 'tipo', d.tipo, 'resumo', d.resumo, 'conteudo', d.conteudo,
            'proveniencia', d.proveniencia, 'source_sha', d.source_sha);
        PERFORM set_config('editorial.in_transition', 'on', true);
        INSERT INTO agents.editorial_items
            (org_id, kind, ref, state, published_version_n, current_version_n)
        VALUES (d.org_id, 'knowledge_document', d.agent_id::text || '/' || d.slug,
                CASE WHEN d.ativo THEN 'publicado' ELSE 'arquivado' END,
                CASE WHEN d.ativo THEN 1 ELSE NULL END, 1)
        RETURNING id INTO v_item;
        INSERT INTO agents.editorial_versions (item_id, n, content, content_sha, author_id)
        VALUES (v_item, 1, v_content,
                encode(sha256(convert_to(v_content::text, 'UTF8')), 'hex'), p_actor_id);
        INSERT INTO agents.editorial_events
            (item_id, version_n, action, from_state, to_state, actor_id, grant_name, motivo)
        VALUES (v_item, 1, CASE WHEN d.ativo THEN 'publish' ELSE 'archive' END, NULL,
                CASE WHEN d.ativo THEN 'publicado' ELSE 'arquivado' END, p_actor_id, NULL,
                'backfill: documento ja existente antes do fluxo editorial (migration 018, govern_collection)');
        PERFORM set_config('editorial.in_transition', 'off', true);
        UPDATE agents.knowledge_documents SET editorial_item_id = v_item WHERE id = d.id;
        v_n := v_n + 1;
    END LOOP;
    UPDATE agents.knowledge_collections SET requer_revisao = true WHERE id = p_collection_id;
    RETURN v_n;
END;
$fn$;

REVOKE ALL ON FUNCTION agents.govern_collection(UUID, UUID, UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION agents.govern_collection(UUID, UUID, UUID) TO service_role;

-- ────────────────────────────────────────────────────────────────────────
-- 4. Retrieval reads PUBLISHED only. Same bodies as 013 (search_knowledge /
-- list_knowledge_documents) plus the published-version predicate; the admin
-- list additionally reports the editorial state (it still lists drafts'
-- rows and archived documents — it is not a retrieval path).
-- ────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION agents.search_knowledge(
    p_org_id UUID,
    p_agent_id UUID,
    p_query TEXT,
    p_colecao TEXT DEFAULT NULL,
    p_limite INT DEFAULT 8
) RETURNS TABLE (
    doc_id UUID,
    slug TEXT,
    titulo TEXT,
    colecao TEXT,
    tag TEXT,
    tipo TEXT,
    trecho TEXT,
    rank REAL
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = agents, public
AS $$
BEGIN
    -- L5: bounded query (the router caps it at the same 512).
    IF p_query IS NULL OR length(p_query) > 512 THEN
        RAISE EXCEPTION 'query_too_long' USING ERRCODE = 'P0001';
    END IF;
    RETURN QUERY
    SELECT
        d.id AS doc_id,
        d.slug,
        d.titulo,
        c.slug AS colecao,
        c.tag,
        d.tipo,
        -- L5: ts_headline re-parses its whole input — bound it, a 2 MB
        -- document must not cost a 2 MB headline pass per hit.
        ts_headline(
            'portuguese',
            coalesce(d.resumo, '') || E'\n\n' || left(d.conteudo, 50000),
            websearch_to_tsquery('portuguese', p_query),
            'MaxFragments=2, MinWords=15, MaxWords=40'
        ) AS trecho,
        ts_rank(d.busca, websearch_to_tsquery('portuguese', p_query))::REAL AS rank
    FROM agents.knowledge_documents d
    JOIN agents.knowledge_collections c ON c.id = d.collection_id
    WHERE d.org_id = p_org_id
      AND d.agent_id = p_agent_id
      AND d.ativo = true
      AND (d.editorial_item_id IS NULL OR EXISTS (
            SELECT 1 FROM agents.editorial_items i
             WHERE i.id = d.editorial_item_id AND i.published_version_n IS NOT NULL))
      AND (p_colecao IS NULL OR c.slug = p_colecao)
      AND d.busca @@ websearch_to_tsquery('portuguese', p_query)
    ORDER BY rank DESC, d.updated_at DESC
    LIMIT LEAST(GREATEST(p_limite, 1), 20);
END;
$$;

REVOKE ALL ON FUNCTION agents.search_knowledge(UUID, UUID, TEXT, TEXT, INT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION agents.search_knowledge(UUID, UUID, TEXT, TEXT, INT) TO service_role;

CREATE OR REPLACE FUNCTION agents.list_knowledge_documents(
    p_org_id UUID,
    p_agent_id UUID,
    p_collection_id UUID,
    p_q TEXT DEFAULT NULL,
    p_tipo TEXT DEFAULT NULL,
    p_limit INT DEFAULT 20,
    p_offset INT DEFAULT 0
) RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = agents, public
AS $$
DECLARE
    v_pat TEXT;
    v_total BIGINT;
    v_items JSONB;
BEGIN
    IF p_q IS NOT NULL AND length(p_q) > 200 THEN
        RAISE EXCEPTION 'query_too_long' USING ERRCODE = 'P0001';
    END IF;
    IF p_q IS NOT NULL AND p_q <> '' THEN
        v_pat := '%' || replace(replace(replace(p_q, '\', '\\'), '%', '\%'), '_', '\_') || '%';
    END IF;

    SELECT count(*) INTO v_total
    FROM agents.knowledge_documents d
    WHERE d.org_id = p_org_id AND d.agent_id = p_agent_id AND d.collection_id = p_collection_id
      AND (p_tipo IS NULL OR d.tipo = p_tipo)
      AND (v_pat IS NULL
           OR d.titulo ILIKE v_pat ESCAPE '\'
           OR d.resumo ILIKE v_pat ESCAPE '\'
           OR d.conteudo ILIKE v_pat ESCAPE '\');

    SELECT COALESCE(jsonb_agg(to_jsonb(r) ORDER BY r.updated_at DESC, r.id), '[]'::JSONB) INTO v_items
    FROM (
        SELECT d.id, d.org_id, d.collection_id, d.agent_id, d.slug, d.titulo, d.tipo,
               d.proveniencia, d.resumo, d.conteudo, d.source_sha, d.ativo, d.created_at, d.updated_at,
               d.editorial_item_id,
               (SELECT i.state FROM agents.editorial_items i WHERE i.id = d.editorial_item_id) AS editorial_state
        FROM agents.knowledge_documents d
        WHERE d.org_id = p_org_id AND d.agent_id = p_agent_id AND d.collection_id = p_collection_id
          AND (p_tipo IS NULL OR d.tipo = p_tipo)
          AND (v_pat IS NULL
               OR d.titulo ILIKE v_pat ESCAPE '\'
               OR d.resumo ILIKE v_pat ESCAPE '\'
               OR d.conteudo ILIKE v_pat ESCAPE '\')
        ORDER BY d.updated_at DESC, d.id
        LIMIT LEAST(GREATEST(p_limit, 1), 100)
        OFFSET GREATEST(p_offset, 0)
    ) r;

    RETURN jsonb_build_object('total', v_total, 'items', v_items);
END;
$$;

REVOKE ALL ON FUNCTION agents.list_knowledge_documents(UUID, UUID, UUID, TEXT, TEXT, INT, INT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION agents.list_knowledge_documents(UUID, UUID, UUID, TEXT, TEXT, INT, INT) TO service_role;

-- ────────────────────────────────────────────────────────────────────────
-- 5. Self-check: with nothing governed yet, the published predicate must keep
-- EVERY live document visible. Aborts the migration (and so the deploy step)
-- rather than hiding knowledge.
-- ────────────────────────────────────────────────────────────────────────

DO $check$
DECLARE
    v_live BIGINT;
    v_visible BIGINT;
BEGIN
    SELECT count(*) INTO v_live FROM agents.knowledge_documents WHERE ativo = true;
    SELECT count(*) INTO v_visible FROM agents.knowledge_documents d
     WHERE d.ativo = true
       AND (d.editorial_item_id IS NULL OR EXISTS (
            SELECT 1 FROM agents.editorial_items i
             WHERE i.id = d.editorial_item_id AND i.published_version_n IS NOT NULL));
    IF v_live <> v_visible THEN
        RAISE EXCEPTION 'migration 018 would hide knowledge: % live, % visible', v_live, v_visible;
    END IF;
END
$check$;

