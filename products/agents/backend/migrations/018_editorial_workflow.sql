-- ────────────────────────────────────────────────────────────────────────
-- 1. Seed editorial tables (generated by noctusai_lib.domain.sql_templates.editorial_tables)
-- ────────────────────────────────────────────────────────────────────────
-- Editorial workflow (seed domain/editorial). Three tables, write-once / append-only,
-- every state change through agents.editorial_create_item / editorial_transition.
-- RLS deny-by-default: no policy but service_role_bypass; consumers add an org-scoped
-- SELECT policy only if a client reads directly. The DB re-checks legality + separation
-- of duties; the GRANTS it receives (p_grants) come from the caller (the permissions
-- organ) — the DB cannot see them, so only the service-role API may call these functions.

CREATE TABLE IF NOT EXISTS agents.editorial_items (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id              UUID NOT NULL,
    kind                TEXT NOT NULL,
    ref                 TEXT NOT NULL,
    state               TEXT NOT NULL DEFAULT 'rascunho',
    published_version_n INTEGER NULL,
    current_version_n   INTEGER NOT NULL DEFAULT 1,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT editorial_items_state_check CHECK (state IN ('rascunho', 'revisao_editorial', 'revisao_seguranca', 'publicado', 'arquivado')),
    CONSTRAINT editorial_items_org_kind_ref_key UNIQUE (org_id, kind, ref),
    CONSTRAINT editorial_items_version_order_check
        CHECK (published_version_n IS NULL OR published_version_n <= current_version_n)
);

CREATE TABLE IF NOT EXISTS agents.editorial_versions (
    item_id     UUID NOT NULL REFERENCES agents.editorial_items(id) ON DELETE RESTRICT,
    n           INTEGER NOT NULL CHECK (n >= 1),
    content     JSONB NOT NULL,
    content_sha TEXT NOT NULL,
    author_id   UUID NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (item_id, n),
    CONSTRAINT editorial_versions_sha_check CHECK (content_sha ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS agents.editorial_events (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    item_id    UUID NOT NULL,
    version_n  INTEGER NOT NULL,
    action     TEXT NOT NULL CHECK (action IN ('create', 'edit', 'submit', 'approve_editorial', 'approve_security', 'publish', 'send_back', 'archive')),
    from_state TEXT NULL,
    to_state   TEXT NOT NULL,
    actor_id   UUID NOT NULL,
    grant_name TEXT NULL,
    motivo     TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (item_id, version_n) REFERENCES agents.editorial_versions(item_id, n) ON DELETE RESTRICT,
    CONSTRAINT editorial_events_motivo_check
        CHECK (action NOT IN ('archive', 'send_back') OR length(btrim(coalesce(motivo, ''))) > 0)
);

CREATE INDEX IF NOT EXISTS idx_editorial_items_org_state ON agents.editorial_items (org_id, state);
CREATE INDEX IF NOT EXISTS idx_editorial_events_item ON agents.editorial_events (item_id, id);

ALTER TABLE agents.editorial_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE agents.editorial_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE agents.editorial_events ENABLE ROW LEVEL SECURITY;
CREATE POLICY "service_role_bypass" ON agents.editorial_items FOR ALL TO service_role USING (true) WITH CHECK (true);
CREATE POLICY "service_role_bypass" ON agents.editorial_versions FOR ALL TO service_role USING (true) WITH CHECK (true);
CREATE POLICY "service_role_bypass" ON agents.editorial_events FOR ALL TO service_role USING (true) WITH CHECK (true);
REVOKE ALL ON agents.editorial_items, agents.editorial_versions, agents.editorial_events FROM anon, authenticated;

-- The rule table, GENERATED from the Python workflow (never hand-edited here).
CREATE OR REPLACE FUNCTION agents.editorial_rules()
RETURNS TABLE (action TEXT, from_state TEXT, to_state TEXT, grant_name TEXT, needs_motivo BOOLEAN,
               not_author BOOLEAN, not_editorial_approver BOOLEAN, needs_security_signoff BOOLEAN,
               creates_version BOOLEAN)
LANGUAGE sql IMMUTABLE SET search_path = agents, public
AS $fn$
    SELECT * FROM (VALUES
        ('create', NULL::text, 'rascunho', 'editorial:editar', false, false, false, false, true),
        ('edit', 'rascunho', 'rascunho', 'editorial:editar', false, false, false, false, true),
        ('edit', 'publicado', 'rascunho', 'editorial:editar', false, false, false, false, true),
        ('submit', 'rascunho', 'revisao_editorial', 'editorial:editar', false, false, false, false, false),
        ('approve_editorial', 'revisao_editorial', 'revisao_seguranca', 'editorial:revisar', false, true, false, false, false),
        ('approve_security', 'revisao_seguranca', 'revisao_seguranca', 'editorial:revisar_seguranca', false, true, true, false, false),
        ('publish', 'revisao_seguranca', 'publicado', 'editorial:publicar', false, true, false, true, false),
        ('send_back', 'revisao_editorial', 'rascunho', 'editorial:revisar', true, false, false, false, false),
        ('send_back', 'revisao_seguranca', 'rascunho', 'editorial:revisar_seguranca', true, false, false, false, false),
        ('archive', 'rascunho', 'arquivado', 'editorial:publicar', true, false, false, false, false),
        ('archive', 'revisao_editorial', 'arquivado', 'editorial:publicar', true, false, false, false, false),
        ('archive', 'revisao_seguranca', 'arquivado', 'editorial:publicar', true, false, false, false, false),
        ('archive', 'publicado', 'arquivado', 'editorial:publicar', true, false, false, false, false)
    ) AS r(action, from_state, to_state, grant_name, needs_motivo, not_author,
           not_editorial_approver, needs_security_signoff, creates_version)
$fn$;

-- Immutability: versions are write-once, events append-only. DELETE is refused too.
CREATE OR REPLACE FUNCTION agents.editorial_guard_immutable()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = agents, public
AS $fn$
BEGIN
    IF TG_TABLE_NAME = 'editorial_versions' THEN
        RAISE EXCEPTION 'editorial_version_immutable' USING ERRCODE = 'P0001';
    END IF;
    RAISE EXCEPTION 'editorial_event_append_only' USING ERRCODE = 'P0001';
END;
$fn$;

-- Writes only inside editorial_create_item / editorial_transition (they raise the
-- transaction-local flag). A direct service-role INSERT/UPDATE/DELETE cannot forge a
-- state, a version or an audit event around the legality + separation-of-duties checks.
CREATE OR REPLACE FUNCTION agents.editorial_guard_via_transition()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = agents, public
AS $fn$
BEGIN
    IF current_setting('editorial.in_transition', true) IS DISTINCT FROM 'on' THEN
        RAISE EXCEPTION 'editorial_write_via_transition_only' USING ERRCODE = 'P0001';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'editorial_write_via_transition_only' USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END;
$fn$;

CREATE OR REPLACE FUNCTION agents.editorial_create_item(
    p_org_id UUID, p_kind TEXT, p_ref TEXT, p_actor_id UUID, p_grants TEXT[],
    p_content JSONB, p_content_sha TEXT
) RETURNS UUID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = agents, public
AS $fn$
DECLARE
    v_rule RECORD;
    v_id UUID;
BEGIN
    SELECT * INTO v_rule FROM agents.editorial_rules() r WHERE r.action = 'create';
    IF p_actor_id IS NULL THEN
        RAISE EXCEPTION 'editorial_actor_required' USING ERRCODE = 'P0001';
    END IF;
    IF NOT (v_rule.grant_name = ANY (coalesce(p_grants, ARRAY[]::TEXT[]))) THEN
        RAISE EXCEPTION 'editorial_missing_grant' USING ERRCODE = 'P0001';
    END IF;
    IF p_content IS NULL OR p_content_sha IS NULL THEN
        RAISE EXCEPTION 'editorial_content_required' USING ERRCODE = 'P0001';
    END IF;
    PERFORM set_config('editorial.in_transition', 'on', true);
    INSERT INTO agents.editorial_items (org_id, kind, ref, state, current_version_n)
    VALUES (p_org_id, p_kind, p_ref, v_rule.to_state, 1) RETURNING id INTO v_id;
    INSERT INTO agents.editorial_versions (item_id, n, content, content_sha, author_id)
    VALUES (v_id, 1, p_content, p_content_sha, p_actor_id);
    INSERT INTO agents.editorial_events (item_id, version_n, action, from_state, to_state, actor_id, grant_name)
    VALUES (v_id, 1, 'create', NULL, v_rule.to_state, p_actor_id, v_rule.grant_name);
    PERFORM set_config('editorial.in_transition', 'off', true);
    RETURN v_id;
END;
$fn$;

CREATE OR REPLACE FUNCTION agents.editorial_transition(
    p_org_id UUID, p_item_id UUID, p_action TEXT, p_actor_id UUID, p_grants TEXT[],
    p_motivo TEXT DEFAULT NULL, p_content JSONB DEFAULT NULL, p_content_sha TEXT DEFAULT NULL
) RETURNS BIGINT
LANGUAGE plpgsql SECURITY DEFINER SET search_path = agents, public
AS $fn$
DECLARE
    v_item agents.editorial_items%ROWTYPE;
    v_rule RECORD;
    v_n INTEGER;
    v_new_n INTEGER;
    v_author UUID;
    v_last_submit BIGINT;
    v_ed_approver UUID;
    v_signed BOOLEAN;
    v_published INTEGER;
    v_event BIGINT;
BEGIN
    SELECT * INTO v_item FROM agents.editorial_items
     WHERE id = p_item_id AND org_id = p_org_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'editorial_item_not_found' USING ERRCODE = 'P0001';
    END IF;
    SELECT * INTO v_rule FROM agents.editorial_rules() r
     WHERE r.action = p_action AND r.from_state = v_item.state;
    IF NOT FOUND THEN
        IF NOT EXISTS (SELECT 1 FROM agents.editorial_rules() r WHERE r.action = p_action) THEN
            RAISE EXCEPTION 'editorial_unknown_action' USING ERRCODE = 'P0001';
        END IF;
        RAISE EXCEPTION 'editorial_illegal_transition' USING ERRCODE = 'P0001';
    END IF;

    v_n := v_item.current_version_n;
    SELECT v.author_id INTO v_author FROM agents.editorial_versions v
     WHERE v.item_id = p_item_id AND v.n = v_n;
    SELECT coalesce(max(e.id), 0) INTO v_last_submit FROM agents.editorial_events e
     WHERE e.item_id = p_item_id AND e.version_n = v_n AND e.action = 'submit';
    SELECT e.actor_id INTO v_ed_approver FROM agents.editorial_events e
     WHERE e.item_id = p_item_id AND e.version_n = v_n AND e.action = 'approve_editorial'
       AND e.id > v_last_submit ORDER BY e.id DESC LIMIT 1;
    SELECT EXISTS (SELECT 1 FROM agents.editorial_events e
     WHERE e.item_id = p_item_id AND e.version_n = v_n AND e.action = 'approve_security'
       AND e.id > v_last_submit) INTO v_signed;

    IF p_action = 'approve_security' AND v_signed THEN
        RAISE EXCEPTION 'editorial_illegal_transition' USING ERRCODE = 'P0001';
    END IF;
    IF p_actor_id IS NULL THEN
        RAISE EXCEPTION 'editorial_actor_required' USING ERRCODE = 'P0001';
    END IF;
    IF NOT (v_rule.grant_name = ANY (coalesce(p_grants, ARRAY[]::TEXT[]))) THEN
        RAISE EXCEPTION 'editorial_missing_grant' USING ERRCODE = 'P0001';
    END IF;
    IF v_rule.needs_motivo AND length(btrim(coalesce(p_motivo, ''))) = 0 THEN
        RAISE EXCEPTION 'editorial_motivo_required' USING ERRCODE = 'P0001';
    END IF;
    IF v_rule.creates_version AND (p_content IS NULL OR p_content_sha IS NULL) THEN
        RAISE EXCEPTION 'editorial_content_required' USING ERRCODE = 'P0001';
    END IF;
    IF v_rule.not_author AND p_actor_id = v_author THEN
        RAISE EXCEPTION 'editorial_self_approval' USING ERRCODE = 'P0001';
    END IF;
    IF v_rule.not_editorial_approver AND p_actor_id IS NOT DISTINCT FROM v_ed_approver THEN
        RAISE EXCEPTION 'editorial_same_approver' USING ERRCODE = 'P0001';
    END IF;
    IF v_rule.needs_security_signoff AND NOT v_signed THEN
        RAISE EXCEPTION 'editorial_security_signoff_missing' USING ERRCODE = 'P0001';
    END IF;

    PERFORM set_config('editorial.in_transition', 'on', true);
    v_new_n := v_n;
    IF v_rule.creates_version THEN
        v_new_n := v_n + 1;
        INSERT INTO agents.editorial_versions (item_id, n, content, content_sha, author_id)
        VALUES (p_item_id, v_new_n, p_content, p_content_sha, p_actor_id);
    END IF;
    v_published := v_item.published_version_n;
    IF p_action = 'publish' THEN
        v_published := v_n;
    ELSIF p_action = 'archive' THEN
        v_published := NULL;
    END IF;
    UPDATE agents.editorial_items
       SET state = v_rule.to_state, current_version_n = v_new_n,
           published_version_n = v_published, updated_at = now()
     WHERE id = p_item_id;
    INSERT INTO agents.editorial_events
        (item_id, version_n, action, from_state, to_state, actor_id, grant_name, motivo)
    VALUES (p_item_id, v_new_n, p_action, v_rule.from_state, v_rule.to_state, p_actor_id,
            v_rule.grant_name, nullif(btrim(coalesce(p_motivo, '')), ''))
    RETURNING id INTO v_event;
    PERFORM set_config('editorial.in_transition', 'off', true);
    RETURN v_event;
END;
$fn$;

