def test_migration_numbers_are_unique_and_the_base_commerce_migration_is_untouched():
    from app.commerce import CFG

    files = sorted(migrations_dir(PRODUCT_DIR).glob("*.sql"))
    numbers = [int(p.name.split("_", 1)[0]) for p in files]
    assert len(numbers) == len(set(numbers)), numbers
    # The base commerce migration is APPLIED in prod: it must keep equalling the base generator and
    # never absorb the P4 deltas (they ship as their own files, found by header).
    (base,) = find_organ_migration(PRODUCT_DIR, "-- Commerce organ -- generated by noctusai_lib.domain.commerce.sql")
    assert base.read_text(encoding="utf-8") == commerce_migration(CFG, "commerce")


def test_money_delta_is_applied_before_the_fiscal_delta():
    from noctusai_seed.organs import ORGAN_REGISTRY

    num = {o: int(find_organ_migration(PRODUCT_DIR, ORGAN_REGISTRY[o].migration_header)[0].name.split("_")[0]) for o in ORGANS}
    base = int(find_organ_migration(PRODUCT_DIR, "-- Commerce organ -- generated by noctusai_lib.domain.commerce.sql")[0].name.split("_")[0])
    assert base < num["commerce_money"] < num["commerce_fiscal"]
    assert all(num[o] > base for o in ORGANS)


def _routes(app) -> set[tuple[str, str]]:
    return {(m, r.path) for r in app.routes if hasattr(r, "methods") for m in r.methods}


P4_ROUTES = [
    # finance (+ reconciliation, DRE)
    ("GET", "/api/finance/accounts"), ("POST", "/api/finance/accounts"),
    ("GET", "/api/finance/entries"), ("POST", "/api/finance/entries"),
    ("GET", "/api/finance/categories"), ("GET", "/api/finance/recurrences"),
    # parties / inventory
    ("GET", "/api/parties"), ("POST", "/api/parties"),
    ("GET", "/api/inventory/warehouses"), ("GET", "/api/inventory/balances"),
    # items
    ("GET", "/api/items"), ("POST", "/api/items"), ("POST", ITEMS_IMPORT_PATH_PATTERN),
    # fiscal
    ("GET", "/api/commerce/fiscal"), ("PUT", "/api/commerce/fiscal"), ("POST", CERTIFICATE_UPLOAD_PATH_PATTERN),
    ("POST", "/api/commerce/fiscal/nfse-cutover"),
    # money (refund) + staff order actions
    ("POST", "/api/commerce/orders/{order_id}/refunds"),
    # webhooks
    ("POST", "/api/webhooks/payments/{gateway_name}/{org_id}"),
    ("POST", "/api/webhooks/invoices/{provider_name}/{org_id}"),
]


@pytest.mark.parametrize("method,path", P4_ROUTES)
def test_p4_route_is_mounted(client, method, path):
    from app.main import app

    assert (method, path) in _routes(app), f"{method} {path} is not mounted"


def test_finance_reconciliation_and_attachment_routes_exist(client):
    from app.main import app

    paths = {p for _m, p in _routes(app)}
    pat = lambda patt: re.compile("^" + re.escape(patt).replace(r"\*", r"[^/]+") + "$")  # noqa: E731
    for patt in (ATTACHMENT_UPLOAD_PATH_PATTERN, STATEMENT_UPLOAD_PATH_PATTERN):
        assert any(pat(patt).match(re.sub(r"\{[^}]+\}", "x", p)) for p in paths), patt


