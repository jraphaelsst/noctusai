"""P4 money + finance + items + fiscal, mounted on the commerce host (backend).

Pins: (a) every rendered organ migration equals its generator output (`assert_organ_migration_current`) and
the applied base commerce migration was NOT rewritten; (b) every P4 route is mounted (path list); (c) representative
finance / items / fiscal / invoice-webhook routes are strictly 401 / fail-closed; (d) the order hooks reach the
fiscal slice; (e) the finance DRE tax-regime prefill reads the store profile; (f) the upload body overrides and the
scheduler jobs are registered; (g) the app boots. Collaborators swap through `dependency_overrides` -- nothing is patched.
"""
