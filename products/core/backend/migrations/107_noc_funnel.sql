-- Lead -> card at INSERT time: whatever writes a lead (public form, WhatsApp intake, admin) lands it in the
-- first active stage with its `entrada` movimento. Plain trigger (no SECURITY DEFINER): writers are service_role.
CREATE OR REPLACE FUNCTION public.website_leads_enter_funnel()
RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = public
AS $$
DECLARE
    v_stage UUID;
BEGIN
    IF NEW.etapa_id IS NULL THEN
        SELECT id INTO v_stage
          FROM public.pipeline_stages
         WHERE org_id = '68230bf3-1323-5ad3-96ad-a87b8c1c844d' AND pipeline = 'funil_noc' AND ativo
         ORDER BY posicao, created_at
         LIMIT 1;
        NEW.etapa_id := v_stage;
    END IF;
    RETURN NEW;
END; $$;
REVOKE ALL ON FUNCTION public.website_leads_enter_funnel() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS website_leads_enter_funnel ON public.website_leads;
CREATE TRIGGER website_leads_enter_funnel
    BEFORE INSERT ON public.website_leads
    FOR EACH ROW EXECUTE FUNCTION public.website_leads_enter_funnel();

