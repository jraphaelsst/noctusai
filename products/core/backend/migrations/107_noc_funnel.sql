-- Backfill the legacy `stage` column onto etapa_id + status (only rows not placed yet, so a replay is a no-op).
-- Outcomes are statuses, never columns: ganho -> status ganho (kept at Proposta), perdido -> status perdido
-- (reason 'outro' + the old free text), descartado -> arquivado; both of the last two sit at Novo.
UPDATE public.website_leads l
   SET etapa_id = s.id,
       status = CASE l.stage
                    WHEN 'ganho' THEN 'ganho'
                    WHEN 'perdido' THEN 'perdido'
                    WHEN 'descartado' THEN 'arquivado'
                    ELSE 'aberto'
                END,
       motivo_perda_codigo = CASE WHEN l.stage = 'perdido' THEN 'outro' ELSE l.motivo_perda_codigo END,
       motivo_perda = CASE WHEN l.stage = 'perdido' THEN l.lost_reason ELSE l.motivo_perda END
  FROM public.pipeline_stages s
 WHERE l.etapa_id IS NULL
   AND s.org_id = '68230bf3-1323-5ad3-96ad-a87b8c1c844d'
   AND s.pipeline = 'funil_noc'
   AND s.slug = CASE l.stage
                    WHEN 'contatado' THEN 'contatado'
                    WHEN 'qualificado' THEN 'qualificado'
                    WHEN 'proposta' THEN 'proposta'
                    WHEN 'ganho' THEN 'proposta'
                    ELSE 'novo'
                END;

