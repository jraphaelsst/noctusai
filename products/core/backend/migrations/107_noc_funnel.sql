CREATE OR REPLACE FUNCTION public.pipeline_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, public
AS $$ BEGIN NEW.updated_at = now(); RETURN NEW; END; $$;

-- Stages are ROWS (rename = one UPDATE). `papel` is the semantic role code keys on.
CREATE TABLE IF NOT EXISTS public.pipeline_stages (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID NOT NULL,
    pipeline    TEXT NOT NULL,
    slug        TEXT NOT NULL CHECK (slug ~ '^[a-z0-9_]+$'),
    label       TEXT NOT NULL CHECK (length(trim(label)) > 0),
    cor         TEXT NOT NULL DEFAULT 'secondary'
                CHECK (cor IN ('primary', 'secondary', 'success', 'warning', 'destructive', 'muted')),
    posicao     INTEGER NOT NULL DEFAULT 0,
    papel       TEXT,
    ativo       BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (org_id, pipeline, slug)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_pipeline_stages_papel
    ON public.pipeline_stages (org_id, pipeline, papel) WHERE papel IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_pipeline_stages_board ON public.pipeline_stages (org_id, pipeline, posicao);
CREATE OR REPLACE TRIGGER set_updated_at_pipeline_stages
    BEFORE UPDATE ON public.pipeline_stages
    FOR EACH ROW EXECUTE FUNCTION public.pipeline_set_updated_at();
ALTER TABLE public.pipeline_stages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pipeline_stages FROM anon, authenticated;
GRANT ALL ON public.pipeline_stages TO service_role;
DROP POLICY IF EXISTS "service_role_bypass" ON public.pipeline_stages;
CREATE POLICY "service_role_bypass" ON public.pipeline_stages FOR ALL TO service_role USING (true) WITH CHECK (true);
COMMENT ON TABLE public.pipeline_stages IS 'tier:platform';

-- Stage-transition history. APPEND-ONLY: the trigger refuses UPDATE/DELETE.
-- `entidade_id` is deliberately not an FK (one column cannot reference every
-- pipeline's card table); `responsavel_id` is nullable (system moves) and not
-- an FK (the user table differs per product). `kind` = mover | entrada | perdido |
-- reaberto | arquivado; status events repeat the card's current stage in both
-- columns (`para_etapa_id` is NULL only for a card that sits in no stage).
CREATE TABLE IF NOT EXISTS public.pipeline_movimentos (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id         UUID NOT NULL,
    pipeline       TEXT NOT NULL,
    entidade_id    UUID NOT NULL,
    de_etapa_id    UUID REFERENCES public.pipeline_stages(id),
    para_etapa_id  UUID REFERENCES public.pipeline_stages(id),
    kind           TEXT NOT NULL DEFAULT 'mover',
    responsavel_id UUID,
    motivo         TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.pipeline_movimentos ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'mover';
CREATE INDEX IF NOT EXISTS idx_pipeline_movimentos_entidade ON public.pipeline_movimentos (org_id, pipeline, entidade_id, created_at DESC);
CREATE OR REPLACE FUNCTION public.pipeline_movimentos_append_only()
RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = public, public
AS $$ BEGIN RAISE EXCEPTION 'pipeline_movimentos is append-only'; END; $$;
DROP TRIGGER IF EXISTS pipeline_movimentos_no_update_delete ON public.pipeline_movimentos;
CREATE TRIGGER pipeline_movimentos_no_update_delete
    BEFORE UPDATE OR DELETE ON public.pipeline_movimentos
    FOR EACH ROW EXECUTE FUNCTION public.pipeline_movimentos_append_only();
ALTER TABLE public.pipeline_movimentos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pipeline_movimentos FROM anon, authenticated;
GRANT ALL ON public.pipeline_movimentos TO service_role;
DROP POLICY IF EXISTS "service_role_bypass" ON public.pipeline_movimentos;
CREATE POLICY "service_role_bypass" ON public.pipeline_movimentos FOR ALL TO service_role USING (true) WITH CHECK (true);
COMMENT ON TABLE public.pipeline_movimentos IS 'tier:platform';

