"""Block-type catalog seed (estruturas-contract.md section 3.1): ONE source, pinned to the migration.

``estruturas_tipos_bloco.py`` holds the 21 canonical types written by the owner's team (copied from
``catalogo-blocos.json``, our own content) plus the protected system row ``Outro``; the migration text is GENERATED by
``seed_sql()`` and this test asserts the migration file carries exactly that text (the ``geracao_taxonomias`` pattern).
Pure Python: no database, no mock.
"""
from pathlib import Path

from noctusai_lib.testing.migrations import migration_path

from app.modules.media_creation import estruturas_formatos as fmt
from app.modules.media_creation import estruturas_tipos_bloco as catalogo

MIGRATION = migration_path(Path(__file__).resolve().parents[3], "cs_estruturas")

CANONICAL_21 = [
    "Headline", "Intensificador do Mistério", "Revelação", "Opinião Polêmica", "Pontos de Identificação",
    "Provas e Argumentações", "Fatos Curiosos", "Histórias Magnéticas", "Notícia do Momento", "Valor Prático",
    "Contraste", "Pergunta Reflexiva", "Apresentação Magnética", "Encerramento", "CTA Salvar", "CTA Compartilhar",
    "CTA Comentar", "CTA Seguir", "CTA Curtir", "CTA Link/Produto", "CTA",
]


class TestCatalog:
    def test_21_canonical_types_in_the_owners_order_plus_the_system_outro(self):
        assert [t.nome for t in catalogo.TIPOS_BLOCO] == [*CANONICAL_21, "Outro"]
        assert [t.ordem for t in catalogo.TIPOS_BLOCO] == list(range(1, 23))
        assert [t.nome for t in catalogo.TIPOS_BLOCO if t.sistema] == ["Outro"]
        assert catalogo.NOME_OUTRO == "Outro" and catalogo.TIPO_NOMES == tuple([*CANONICAL_21, "Outro"])

    def test_every_row_respects_the_column_limits_of_the_migration(self):
        for t in catalogo.TIPOS_BLOCO:
            assert 1 <= len(t.nome) <= fmt.TIPO_NOME_MAX
            assert 1 <= len(t.instrucao_referencia) <= fmt.TIPO_INSTRUCAO_MAX
            assert t.tempo_tipico is None or 1 <= len(t.tempo_tipico) <= fmt.BLOCO_TEMPO_MAX

    def test_the_21_carry_a_typical_time_and_an_instruction_and_outro_has_no_time(self):
        assert all(t.tempo_tipico and t.instrucao_referencia for t in catalogo.TIPOS_BLOCO[:-1])
        outro = catalogo.TIPOS_BLOCO[-1]
        assert outro.tempo_tipico is None and "sem inventar" in outro.instrucao_referencia

    def test_spot_checks_against_the_owners_file(self):
        by = {t.nome: t for t in catalogo.TIPOS_BLOCO}
        assert by["Headline"].tempo_tipico == "0–3s" and by["Headline"].instrucao_referencia.startswith("Frase de abertura que para a rolagem")
        assert by["CTA"].tempo_tipico == "2–4s" and by["Provas e Argumentações"].tempo_tipico == "5–12s"
        assert "Nunca inventar números" in by["Provas e Argumentações"].instrucao_referencia
        assert catalogo.CATALOGO_VERSAO == 1


class TestSeedSql:
    def test_the_migration_carries_exactly_the_generated_seed(self):
        text = MIGRATION.read_text(encoding="utf-8")
        assert catalogo.seed_sql() in text
        assert text.count(catalogo.seed_sql()) == 1
        assert "-- BEGIN seed_sql\n" + catalogo.seed_sql() + "-- END seed_sql" in text

    def test_the_seed_never_overwrites_an_admin_edit_and_is_idempotent(self):
        sql = catalogo.seed_sql()
        assert sql.rstrip().endswith("ON CONFLICT (nome) DO NOTHING;")
        assert "DO UPDATE" not in sql

    def test_quotes_are_escaped_and_the_sql_has_one_row_per_type(self):
        sql = catalogo.seed_sql()
        assert sql.count("\n    ('") == 22
        # the "você que…" instruction carries double quotes, the Provas one none; a single quote would double
        assert "''" not in sql or "'" in "".join(t.instrucao_referencia for t in catalogo.TIPOS_BLOCO)

    def test_a_single_quote_is_doubled(self):
        assert catalogo._q("it's") == "'it''s'" and catalogo._q(None) == "NULL"


class TestFormatos:
    def test_post_formato_mapping_is_the_s1_vocabulary(self):
        assert fmt.FORMATO_PARA_POST == {"reels": "reel", "carrossel": "carrossel", "stories": "story", "post": "feed"}
        assert fmt.formato_do_post("reels") == "reel" and fmt.formato_do_post("post") == "feed" and fmt.formato_do_post(None) is None
        assert [fmt.formato_da_estrutura(v) for v in ("reel", "carrossel", "story", "feed")] == ["reels", "carrossel", "stories", "post"]
        assert set(fmt.FORMATO_PARA_POST) == set(fmt.FORMATOS)

    def test_an_unknown_formato_is_an_error_never_mapped_silently(self):
        import pytest

        with pytest.raises(ValueError):
            fmt.formato_do_post("video")
        with pytest.raises(ValueError):
            fmt.formato_da_estrutura("short")

    def test_provenance_vocabulary_and_pending_subset(self):
        assert fmt.PROVENIENCIAS == ("fonte", "referencia", "ia_sugerido", "admin")
        assert set(fmt.PROVENIENCIAS_PENDENTES) == {"referencia", "ia_sugerido"}
        assert fmt.OBJETIVOS == ("alcance", "autoridade", "conexao", "venda") and fmt.MAX_OBJETIVOS == 4
