def _q(value: Optional[str]) -> str:
    """SQL string literal (or NULL); the catalog has no non-text values."""
    if value is None:
        return "NULL"
    return "'" + value.replace("'", "''") + "'"


def seed_sql() -> str:
    """The ``INSERT ... ON CONFLICT (nome) DO NOTHING`` the migration carries verbatim.

    ``DO NOTHING`` on purpose: after the seed an admin owns names, order and instructions, so a re-apply must neither
    overwrite an edit nor trip the ``UNIQUE (ordem)`` of a reordered catalog. The arbiter is ``nome`` (the name is the
    key the loaders look types up by): Postgres refuses a DEFERRABLE unique constraint (``ordem``) as an arbiter, so a
    bare ``ON CONFLICT DO NOTHING`` is not available here.
    """
    values = ",\n".join(
        f"    ({_q(t.nome)}, {t.ordem}, {_q(t.tempo_tipico)}, {_q(t.instrucao_referencia)}, "
        f"{'true' if t.sistema else 'false'})"
        for t in TIPOS_BLOCO
    )
    return (
        "INSERT INTO social_wiring.cs_estrutura_tipos_bloco (nome, ordem, tempo_tipico, instrucao_referencia, sistema)\n"
        "VALUES\n" + values + "\n"
        "ON CONFLICT (nome) DO NOTHING;\n"
    )


