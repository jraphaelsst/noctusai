-- Get-or-create the card of an imóvel; its seq-1 `created` event rides the same transaction. Returns {id, criado}.
CREATE OR REPLACE FUNCTION social_wiring.imobshot_obter_ou_criar_card(p_org UUID, p_codigo TEXT, p_ator UUID)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = social_wiring, public
AS $$
DECLARE
    v_id  UUID;
    v_res JSONB;
BEGIN
    INSERT INTO social_wiring.imobshot_cards (org_id, imovel_codigo)
    VALUES (p_org, p_codigo)
    ON CONFLICT (org_id, imovel_codigo) DO NOTHING
    RETURNING id INTO v_id;

    IF v_id IS NOT NULL THEN
        v_res := social_wiring.imobshot_card_record_created(
            p_org, jsonb_build_object('entity_id', v_id), '{}'::jsonb, p_ator,
            CASE WHEN p_ator IS NULL THEN 'system' ELSE 'user' END);
        IF v_res->>'status' <> 'ok' THEN
            RAISE EXCEPTION 'imobshot_card_record_created refused: %', v_res;
        END IF;
        RETURN jsonb_build_object('id', v_id, 'criado', true);
    END IF;

    SELECT id INTO v_id FROM social_wiring.imobshot_cards WHERE org_id = p_org AND imovel_codigo = p_codigo;
    RETURN jsonb_build_object('id', v_id, 'criado', false);
END;
$$;

-- Link a lote to a card (same org only) + the `lote_vinculado` event (from_state = to_state: a link moves no stage).
CREATE OR REPLACE FUNCTION social_wiring.imobshot_vincular_lote(p_card UUID, p_lote UUID, p_ator UUID)
RETURNS BOOLEAN
LANGUAGE plpgsql
SET search_path = social_wiring, public
AS $$
DECLARE
    v_org   UUID;
    v_etapa TEXT;
    v_n     INTEGER;
    v_res   JSONB;
BEGIN
    SELECT org_id, etapa INTO v_org, v_etapa FROM social_wiring.imobshot_cards WHERE id = p_card FOR UPDATE;
    IF v_org IS NULL THEN
        RETURN false;
    END IF;
    UPDATE social_wiring.fotos_lotes SET card_id = p_card, updated_at = now()
     WHERE id = p_lote AND org_id = v_org AND card_id IS DISTINCT FROM p_card;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    IF v_n = 0 THEN
        RETURN false;
    END IF;
    v_res := social_wiring.imobshot_card_transition(
        v_org, jsonb_build_object('entity_id', p_card), v_etapa, v_etapa, 'lote_vinculado',
        jsonb_build_object('lote_id', p_lote), p_ator, CASE WHEN p_ator IS NULL THEN 'system' ELSE 'user' END);
    IF v_res->>'status' <> 'ok' THEN
        RAISE EXCEPTION 'imobshot_card_transition (lote_vinculado) refused: %', v_res;
    END IF;
    RETURN true;
END;
$$;

-- Apply a recomputed etapa (+ the cover). Writes ONLY when it changed, and then the `etapa_mudou` event in the same
-- transaction. The row is locked, so two concurrent syncs cannot both write the same transition. Returns whether it changed.
CREATE OR REPLACE FUNCTION social_wiring.imobshot_aplicar_etapa(p_card UUID, p_etapa TEXT, p_capa UUID, p_ator UUID)
RETURNS BOOLEAN
LANGUAGE plpgsql
SET search_path = social_wiring, public
AS $$
DECLARE
    v_org   UUID;
    v_atual TEXT;
    v_res   JSONB;
BEGIN
    SELECT org_id, etapa INTO v_org, v_atual
      FROM social_wiring.imobshot_cards WHERE id = p_card FOR UPDATE;
    IF v_org IS NULL THEN
        RETURN false;
    END IF;

    UPDATE social_wiring.imobshot_cards SET capa_foto_id = p_capa
     WHERE id = p_card AND capa_foto_id IS DISTINCT FROM p_capa;

    IF v_atual = p_etapa THEN
        RETURN false;
    END IF;

    UPDATE social_wiring.imobshot_cards
       SET etapa_desde = now(),
           fotos_concluidas_at = CASE WHEN p_etapa = 'fotos_aprovadas' THEN now() ELSE fotos_concluidas_at END
     WHERE id = p_card;
    -- The primitive writes `etapa` (+ updated_at) and the event; an etapa outside the CHECK raises check_violation here.
    v_res := social_wiring.imobshot_card_transition(
        v_org, jsonb_build_object('entity_id', p_card), v_atual, p_etapa, 'etapa_mudou',
        '{}'::jsonb, p_ator, CASE WHEN p_ator IS NULL THEN 'system' ELSE 'user' END);
    IF v_res->>'status' <> 'ok' THEN
        RAISE EXCEPTION 'imobshot_card_transition (etapa_mudou) refused: %', v_res;
    END IF;
    RETURN true;
END;
$$;

