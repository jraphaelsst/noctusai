CREATE OR REPLACE FUNCTION social_wiring.imobshot_card_create(p_org UUID, p_row JSONB, p_data JSONB DEFAULT '{}'::jsonb, p_actor_id UUID DEFAULT NULL, p_actor_kind TEXT DEFAULT 'user', p_correlation_id UUID DEFAULT NULL, p_event_id UUID DEFAULT NULL, p_occurred_at TIMESTAMPTZ DEFAULT NULL) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, social_wiring, pg_temp
AS $fn$
DECLARE
    v_row  JSONB;
    v_cols TEXT;
    v_ins  JSONB;
    v_key  JSONB;
    v_prev social_wiring.imobshot_card_events%ROWTYPE;
    v_ev   social_wiring.imobshot_card_events%ROWTYPE;
BEGIN
    IF p_row IS NULL OR jsonb_typeof(p_row) <> 'object' THEN
        RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_row');
    END IF;
    p_data := COALESCE(p_data, '{}'::jsonb);
    IF jsonb_typeof(p_data) <> 'object' THEN
        RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_data');
    END IF;
    IF p_actor_kind IS NULL OR p_actor_kind <> ALL (ARRAY['user', 'agent', 'system', 'integration']::text[]) THEN
        RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_actor_kind');
    END IF;
    IF p_event_id IS NOT NULL THEN
        SELECT * INTO v_prev FROM social_wiring.imobshot_card_events WHERE id = p_event_id;
        IF FOUND THEN
            IF v_prev.org_id = p_org AND v_prev.event_type = 'created' THEN
                RETURN jsonb_build_object('status', 'replayed', 'event', to_jsonb(v_prev));
            END IF;
            RETURN jsonb_build_object('status', 'refused', 'code', 'idempotency_conflict');
        END IF;
    END IF;
    v_row := p_row || jsonb_build_object('org_id', p_org);
    SELECT string_agg(quote_ident(k), ', ') INTO v_cols FROM jsonb_object_keys(v_row) AS k;
    BEGIN
        EXECUTE format('INSERT INTO %I.%I AS x (%s) SELECT %s FROM jsonb_populate_record(NULL::%I.%I, $1) RETURNING to_jsonb(x.*)',
                       'social_wiring', 'imobshot_cards', v_cols, v_cols, 'social_wiring', 'imobshot_cards')
            INTO v_ins USING v_row;
        v_key := jsonb_build_object('entity_id', v_ins->'id');
        INSERT INTO social_wiring.imobshot_card_events (id, org_id, entity_id, seq, from_state, to_state, event_type, data, actor_id, actor_kind, correlation_id, occurred_at)
        VALUES (COALESCE(p_event_id, gen_random_uuid()), p_org, (v_key->>'entity_id')::uuid, 1, NULL, (v_ins->>'etapa')::text, 'created', p_data, p_actor_id, p_actor_kind, p_correlation_id, COALESCE(p_occurred_at, now())) RETURNING * INTO v_ev;
    EXCEPTION
        WHEN unique_violation THEN
            IF p_event_id IS NOT NULL THEN
                SELECT * INTO v_prev FROM social_wiring.imobshot_card_events WHERE id = p_event_id;
                IF FOUND AND v_prev.org_id = p_org AND v_prev.event_type = 'created' THEN
                    RETURN jsonb_build_object('status', 'replayed', 'event', to_jsonb(v_prev));
                END IF;
            END IF;
            RETURN jsonb_build_object('status', 'refused', 'code', 'duplicate', 'detail', SQLERRM);
        WHEN undefined_column OR not_null_violation OR check_violation OR foreign_key_violation
             OR invalid_text_representation OR datatype_mismatch OR invalid_datetime_format THEN
            RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_row', 'detail', SQLERRM);
    END;
    RETURN jsonb_build_object('status', 'ok', 'event', to_jsonb(v_ev));
END;
$fn$;
REVOKE ALL ON FUNCTION social_wiring.imobshot_card_create(UUID, JSONB, JSONB, UUID, TEXT, UUID, UUID, TIMESTAMPTZ) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION social_wiring.imobshot_card_create(UUID, JSONB, JSONB, UUID, TEXT, UUID, UUID, TIMESTAMPTZ) TO service_role;

