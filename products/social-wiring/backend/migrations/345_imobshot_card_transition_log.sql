-- ============================================================================
-- 2. Copy the legacy history into the primitive (only while the legacy table exists; re-runs are no-ops).
-- ============================================================================
DO $legacy$
DECLARE
    v_old     BIGINT;
    v_bad     BIGINT;
    v_sample  TEXT;
    v_moved   BIGINT;
BEGIN
    IF to_regclass('social_wiring.imobshot_eventos') IS NULL THEN
        RETURN;
    END IF;

    SELECT count(*) INTO v_old FROM social_wiring.imobshot_eventos;

    -- Already moved (a re-run, possibly after new traffic wrote events of its own): nothing to do. Every legacy id
    -- present in the primitive means the copy committed whole; the chain check below only applies to a fresh move.
    SELECT count(*) INTO v_moved
      FROM social_wiring.imobshot_eventos o JOIN social_wiring.imobshot_card_events n ON n.id = o.id;
    IF v_moved = v_old THEN
        RETURN;
    END IF;

    -- Walk each card's events in order; carry the etapa forward through the events that carry none (lote_vinculado).
    CREATE TEMP TABLE _imobshot_walk ON COMMIT DROP AS
    SELECT w.*, lag(w.to_s) OVER (PARTITION BY w.card_id ORDER BY w.seq) AS from_s
      FROM (
        SELECT l.*, first_value(l.etapa_para) OVER (PARTITION BY l.card_id, l.grp ORDER BY l.seq) AS to_s
          FROM (
            SELECT e.*,
                   row_number() OVER win AS seq,
                   count(e.etapa_para) OVER win AS grp
              FROM social_wiring.imobshot_eventos e
            WINDOW win AS (PARTITION BY e.card_id ORDER BY e.at, (e.tipo <> 'card_criado'), e.id)
          ) l
      ) w;

    SELECT count(*), string_agg(id::text, ', ' ORDER BY id) FILTER (WHERE rn <= 5) INTO v_bad, v_sample
      FROM (
        SELECT w.id, row_number() OVER (ORDER BY w.id) AS rn
          FROM _imobshot_walk w
         WHERE (w.seq = 1 AND w.tipo <> 'card_criado')
            OR (w.seq > 1 AND w.tipo = 'card_criado')
            OR w.to_s IS NULL
            OR (w.tipo IN ('etapa_mudou', 'card_arquivado') AND w.etapa_de IS DISTINCT FROM w.from_s)
            OR jsonb_typeof(w.detalhe) <> 'object'
      ) bad;
    IF v_bad > 0 THEN
        RAISE EXCEPTION 'imobshot_eventos -> imobshot_card_events: % legacy row(s) cannot be mapped (sample ids: %); nothing was moved or dropped', v_bad, v_sample;
    END IF;

    SELECT count(*), string_agg(c.id::text, ', ') INTO v_bad, v_sample
      FROM social_wiring.imobshot_cards c
      JOIN (SELECT DISTINCT ON (card_id) card_id, to_s FROM _imobshot_walk ORDER BY card_id, seq DESC) last_ev
        ON last_ev.card_id = c.id
     WHERE last_ev.to_s IS DISTINCT FROM c.etapa;
    IF v_bad > 0 THEN
        RAISE EXCEPTION 'imobshot_eventos -> imobshot_card_events: % card(s) whose history does not end at their current etapa (card ids: %); nothing was moved or dropped', v_bad, v_sample;
    END IF;

    INSERT INTO social_wiring.imobshot_card_events
        (id, org_id, entity_id, seq, from_state, to_state, event_type, data, actor_id, actor_kind,
         correlation_id, occurred_at, recorded_at)
    SELECT w.id, w.org_id, w.card_id, w.seq::int, w.from_s, w.to_s,
           CASE w.tipo WHEN 'card_criado' THEN 'created' ELSE w.tipo END,
           w.detalhe || jsonb_build_object('legacy_tipo', w.tipo, 'migrated_from', 'imobshot_eventos'),
           w.actor_id,
           CASE WHEN w.actor_id IS NULL THEN 'system' ELSE 'user' END,
           NULL, w.at, w.at
      FROM _imobshot_walk w
    ON CONFLICT (id) DO NOTHING;

    SELECT count(*) INTO v_moved
      FROM social_wiring.imobshot_card_events WHERE data->>'migrated_from' = 'imobshot_eventos';
    IF v_moved <> v_old THEN
        RAISE EXCEPTION 'imobshot_eventos -> imobshot_card_events: % legacy row(s), % copied; nothing was dropped', v_old, v_moved;
    END IF;
    DROP TABLE IF EXISTS _imobshot_walk;
END
$legacy$;

