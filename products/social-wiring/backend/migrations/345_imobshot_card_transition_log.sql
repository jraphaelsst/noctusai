CREATE OR REPLACE FUNCTION social_wiring.imobshot_card_erase_subject(p_org UUID, p_subject JSONB, p_reason TEXT, p_actor_id UUID DEFAULT NULL) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, social_wiring, pg_temp
AS $fn$
DECLARE
    v_n INTEGER;
BEGIN
    IF p_org IS NULL OR p_subject IS NULL OR jsonb_typeof(p_subject) <> 'object' OR NOT (p_subject ?| ARRAY['entity_id']::text[])
       OR EXISTS (SELECT 1 FROM jsonb_each(p_subject) j WHERE j.key <> ALL (ARRAY['entity_id']::text[]) OR jsonb_typeof(j.value) = 'null') THEN
        RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_key');
    END IF;
    IF p_reason IS NULL OR btrim(p_reason) = '' THEN
        RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_reason');
    END IF;
    -- The ONE gated delete (LGPD erasure, owner decision 2026-11-07): the flag is transaction-local and is
    -- dropped again before anything else runs, error or not.
    PERFORM set_config('noctus_tl.erase_imobshot_card', 'on', true);
    BEGIN
        DELETE FROM social_wiring.imobshot_card_events e WHERE e.org_id = p_org AND (NOT (p_subject ? 'entity_id') OR e.entity_id = (p_subject->>'entity_id')::uuid);
        GET DIAGNOSTICS v_n = ROW_COUNT;
    EXCEPTION WHEN OTHERS THEN
        PERFORM set_config('noctus_tl.erase_imobshot_card', 'off', true);
        RAISE;
    END;
    PERFORM set_config('noctus_tl.erase_imobshot_card', 'off', true);
    INSERT INTO social_wiring.transition_log_erasures (org_id, aggregate, subject, events_deleted, reason, actor_id)
        VALUES (p_org, 'imobshot_card', p_subject, v_n, p_reason, p_actor_id);
    RETURN jsonb_build_object('status', 'ok', 'deleted', v_n);
END;
$fn$;
REVOKE ALL ON FUNCTION social_wiring.imobshot_card_erase_subject(UUID, JSONB, TEXT, UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION social_wiring.imobshot_card_erase_subject(UUID, JSONB, TEXT, UUID) TO service_role;

CREATE OR REPLACE FUNCTION social_wiring.imobshot_card_backfill_initial_state(p_org UUID DEFAULT NULL) RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, social_wiring, pg_temp
AS $fn$
DECLARE
    v_n INTEGER;
BEGIN
    INSERT INTO social_wiring.imobshot_card_events (org_id, entity_id, seq, from_state, to_state, event_type, data, actor_kind, occurred_at)
    SELECT s.org_id, s.id, 1, NULL, s.etapa, 'imported_initial_state',
