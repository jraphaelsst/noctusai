CREATE OR REPLACE FUNCTION social_wiring.cs_criacao_cota_erase_subject(p_org UUID, p_subject JSONB, p_reason TEXT, p_actor_id UUID DEFAULT NULL) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, social_wiring, pg_temp
AS $fn$
DECLARE
    v_n INTEGER;
BEGIN
    IF p_org IS NULL OR p_subject IS NULL OR jsonb_typeof(p_subject) <> 'object' OR NOT (p_subject ?| ARRAY['entity_id']::text[])
       OR EXISTS (SELECT 1 FROM jsonb_each(p_subject) j WHERE j.key <> ALL (ARRAY['entity_id']::text[]) OR jsonb_typeof(j.value) = 'null') THEN
        RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_key');
    END IF;
    IF p_reason IS NULL OR btrim(p_reason) = '' THEN
        RETURN jsonb_build_object('status', 'refused', 'code', 'invalid_reason');
    END IF;
    -- The ONE gated delete (LGPD erasure, owner decision 2026-11-07): the flag is transaction-local and is
    -- dropped again before anything else runs, error or not.
    PERFORM set_config('noctus_tl.erase_cs_criacao_cota', 'on', true);
    BEGIN
        DELETE FROM social_wiring.cs_criacao_cota_events e WHERE e.org_id = p_org AND (NOT (p_subject ? 'entity_id') OR e.entity_id = (p_subject->>'entity_id')::uuid);
        GET DIAGNOSTICS v_n = ROW_COUNT;
    EXCEPTION WHEN OTHERS THEN
        PERFORM set_config('noctus_tl.erase_cs_criacao_cota', 'off', true);
        RAISE;
    END;
    PERFORM set_config('noctus_tl.erase_cs_criacao_cota', 'off', true);
    INSERT INTO social_wiring.transition_log_erasures (org_id, aggregate, subject, events_deleted, reason, actor_id)
        VALUES (p_org, 'cs_criacao_cota', p_subject, v_n, p_reason, p_actor_id);
    RETURN jsonb_build_object('status', 'ok', 'deleted', v_n);
END;
$fn$;
REVOKE ALL ON FUNCTION social_wiring.cs_criacao_cota_erase_subject(UUID, JSONB, TEXT, UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION social_wiring.cs_criacao_cota_erase_subject(UUID, JSONB, TEXT, UUID) TO service_role;

CREATE OR REPLACE FUNCTION social_wiring.cs_criacao_cota_backfill_initial_state(p_org UUID DEFAULT NULL) RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, social_wiring, pg_temp
AS $fn$
DECLARE
    v_n INTEGER;
BEGIN
    INSERT INTO social_wiring.cs_criacao_cota_events (org_id, entity_id, seq, from_state, to_state, event_type, data, actor_kind, occurred_at)
    SELECT s.org_id, s.id, 1, NULL, s.limite_usd_cents, 'imported_initial_state',
           jsonb_build_object('synthetic', true, 'source', 'transition_log_backfill'), 'synthetic', COALESCE(s.created_at, now())
      FROM social_wiring.cs_criacao_cotas s
     WHERE (p_org IS NULL OR s.org_id = p_org)
       AND NOT EXISTS (SELECT 1 FROM social_wiring.cs_criacao_cota_events e WHERE e.entity_id = s.id)
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RETURN v_n;
END;
$fn$;
REVOKE ALL ON FUNCTION social_wiring.cs_criacao_cota_backfill_initial_state(UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION social_wiring.cs_criacao_cota_backfill_initial_state(UUID) TO service_role;

-- ----------------------------------------------------------------------------
-- 3. month-to-date spend, from the ledger
-- ----------------------------------------------------------------------------
-- A finished step spent its vendor cost whether it succeeded or failed; a step with no measured cost is COUNTED, not
-- folded into zero. The month is the Brazilian calendar month of terminado_em.
CREATE OR REPLACE VIEW social_wiring.cs_criacao_gasto_mes WITH (security_invoker = true) AS
SELECT j.org_id,
       (date_trunc('month', j.terminado_em AT TIME ZONE 'America/Sao_Paulo'))::date AS mes,
       COALESCE(sum(j.custo_usd), 0)::numeric(14, 6) AS custo_usd,
       COALESCE(sum(j.custo_brl), 0)::numeric(14, 6) AS custo_brl,
       count(*) AS passos,
       count(*) FILTER (WHERE j.custo_usd IS NULL) AS passos_sem_custo
  FROM social_wiring.cs_criacao_jobs j
 WHERE j.terminado_em IS NOT NULL AND j.status IN ('concluido', 'falhou')
 GROUP BY j.org_id, (date_trunc('month', j.terminado_em AT TIME ZONE 'America/Sao_Paulo'))::date;

CREATE OR REPLACE FUNCTION social_wiring.cs_criacao_cota_estado(p_org UUID)
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = social_wiring, pg_catalog, pg_temp
AS $fn$
    SELECT jsonb_build_object(
        'limite_usd_mes', l.limite,
        'gasto_usd_mes', COALESCE(g.custo_usd, 0),
        'restante_usd', l.limite - COALESCE(g.custo_usd, 0),
        'passos_sem_custo', COALESCE(g.passos_sem_custo, 0))
      FROM (SELECT COALESCE((SELECT c.limite_usd_cents FROM social_wiring.cs_criacao_cotas c WHERE c.org_id = p_org), 1500) / 100.0 AS limite) l
      LEFT JOIN social_wiring.cs_criacao_gasto_mes g
        ON g.org_id = p_org AND g.mes = (date_trunc('month', now() AT TIME ZONE 'America/Sao_Paulo'))::date;
$fn$;
REVOKE ALL ON FUNCTION social_wiring.cs_criacao_cota_estado(UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION social_wiring.cs_criacao_cota_estado(UUID) TO service_role;

